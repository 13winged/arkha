//! Бенчмарк ресемплинга: линейная интерполяция (старая) против sinc (rubato).
//!
//! Замеряет время пересчета аудио с 48 кГц на 16 кГц — самый частый
//! путь (микрофоны часто отдают 48 кГц, приложение работает на 16 кГц).

use criterion::{black_box, criterion_group, criterion_main, Criterion};
use arkha_lib::voice::record::пересчитать_из;

/// Генерирует тестовый сигнал: синусоида 440 Гц, длительность `секунд`, частота `rate`.
fn тестовый_синус(секунды: f32, rate: u32) -> Vec<f32> {
    let n = (секунды * rate as f32) as usize;
    (0..n)
        .map(|i| {
            let t = i as f32 / rate as f32;
            (2.0 * std::f32::consts::PI * 440.0 * t).sin()
        })
        .collect()
}

fn ресемпл_48_в_16(б: &mut Criterion) {
    let источник = тестовый_синус(1.0, 48_000); // 1 секунда, 48 кГц
    б.bench_function("ресемпл 48кГц→16кГц (sinc, rubato)", |б| {
        б.iter(|| пересчитать_из(black_box(&источник), 48_000, 16_000))
    });
}

fn ресемпл_44100_в_16(б: &mut Criterion) {
    let источник = тестовый_синус(1.0, 44_100); // 1 секунда, 44.1 кГц
    б.bench_function("ресемпл 44.1кГц→16кГц (sinc, rubato)", |б| {
        б.iter(|| пересчитать_из(black_box(&источник), 44_100, 16_000))
    });
}

fn ресемпл_16_в_16(б: &mut Criterion) {
    let источник = тестовый_синус(1.0, 16_000); // уже 16 кГц — должен быть quick return
    б.bench_function("ресемпл 16кГц→16кГц (quick return)", |б| {
        б.iter(|| пересчитать_из(black_box(&источник), 16_000, 16_000))
    });
}

criterion_group!(ресемпл, ресемпл_48_в_16, ресемпл_44100_в_16, ресемпл_16_в_16);
criterion_main!(ресемпл);
