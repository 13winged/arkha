// Воспроизведение звука на выбранное человеком устройство.
//
// Почему это свой модуль, а не вызов системного проигрывателя.
// `PlaySound` и `wmpstart` играют на устройстве по умолчанию, и
// выбора у человека не остаётся: у него наушники, колонки и
// монитор, и «звук по умолчанию» в Windows меняется в панели
// управления, а не здесь. Свой вывод означает WASAPI и устройство,
// названное человеком.
//
// Что делает модуль: читает несжатый WAV, приводит его к формату
// устройства и играет. Ничего не запоминает между вызовами.
//
// Чего модуль не делает: не играет в фоне и не смешивает звуки. Одновременная
// речь — это отдельная задача, и решать её надо с очередью, а не
// с перезаписью буфера.

use std::sync::atomic::{AtomicU32, Ordering};

use windows::Win32::Foundation::{HINSTANCE, LPARAM, LRESULT, WPARAM};
use windows::Win32::Media::Audio::{
    IAudioClient, IAudioRenderClient, WAVEFORMATEX,
    AUDCLNT_SHAREMODE_SHARED,
};
use windows::Win32::System::Com::{
    CoCreateInstance, CoInitializeEx, CoUninitialize, CLSCTX_ALL, COINIT_MULTITHREADED,
};

use super::record::{
    CLSID_МИКРОФОН, ВОСПРОИЗВЕДЕНИЕ, КОНСОЛЬ, ЧАСТОТА,
};


/// Общее состояние вывода на всё приложение.
///
/// Один голос за раз — и потому один буфер. Второй вызов, пока
/// первый играется, должен честно сказать об этом, а не переписать
/// буфер и оставить человека без звука.
static ЗАНЯТО: AtomicU32 = AtomicU32::new(0);


/// Что сыграно.
#[derive(Debug, Clone, serde::Serialize)]
pub struct Сыграно {
    /// Сколько секунд отдано устройству.
    pub секунд: f32,
    /// Каким устройством играли. Отдаётся назад, чтобы интерфейс
    /// показал фактическое, а не задуманное: устройство могло
    /// выпасть из выбора, и тогда играет умолчание.
    pub устройство: String,
}

/// Сыграть несжатый WAV на выбранный или стандартный вывод.
///
/// `устройство` — `None`, если человек ничего не выбрал. Идентификатор
/// приходит от человека через настройки, поэтому недоверенный:
/// неизвестное имя даёт ошибку с текстом, а не молчаливый откат на
/// умолчание.
pub fn сыграть_файл(путь: &std::path::Path, устройство: Option<String>) -> Result<Сыграно, String> {
    let образцы = super::vad::прочитать_wav(путь)?;
    сыграть(&образцы, устройство)
}

/// Сыграть готовые образцы: моно, 16 кГц.
pub fn сыграть(образцы: &[f32], устройство: Option<String>) -> Result<Сыграно, String> {
    if образцы.is_empty() {
        return Err("нечего играть: звук пуст".to_string());
    }
    if ЗАНЯТО.swap(1, Ordering::SeqCst) == 1 {
        return Err("секретарь уже говорит".to_string());
    }
    let итог = unsafe { сыграть_под(образцы, устройство.as_deref()) };
    ЗАНЯТО.store(0, Ordering::SeqCst);
    итог
}

unsafe fn сыграть_под(
    образцы: &[f32],
    устройство: Option<&str>,
) -> Result<Сыграно, String> {
    let _ = unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) };
    let итог = unsafe { играть(образцы, устройство) };
    unsafe { CoUninitialize() };
    итог
}

/// Открыть устройство вывода и отдать ему звук.
unsafe fn играть(образцы: &[f32], устройство: Option<&str>) -> Result<Сыграно, String> {
    use windows::Win32::Media::Audio::IMMDeviceEnumerator;

    let перечис: IMMDeviceEnumerator = unsafe {
        CoCreateInstance(&CLSID_МИКРОФОН, None, CLSCTX_ALL)
            .map_err(|e| format!("устройства вывода не перечислились: {e}"))?
    };

    // Выбор человека уважается буквально: если он назвал
    // устройство, а оно недоступно, это ошибка с текстом. Молча
    // играть в колонки, когда человек просил в наушники, хуже,
    // чем не играть вовсе: он услышит не то и не поймёт почему.
    //
    // А вот к «по умолчанию» это относится не так. На этой машине
    // устройство вывода по умолчанию отвечает «аннулировано»
    // (`0x88890008`) — оно виртуальное, и таких на машине
    // несколько. Поэтому умолчание обходится так же, как микрофон
    // в записи: сначала оно, потом все активные по очереди.
    let кандидаты: Vec<windows::Win32::Media::Audio::IMMDevice> = match устройство {
        Some(идентификатор) if !идентификатор.is_empty() => {
            let широкое = windows::core::HSTRING::from(идентификатор);
            let найдено = unsafe { перечис.GetDevice(&широкое) }.map_err(|e| {
                format!("выбранное устройство вывода недоступно: {идентификатор} ({e})")
            })?;
            vec![найдено]
        }
        _ => {
            let mut список = Vec::new();
            if let Ok(умолчание) =
                unsafe { перечис.GetDefaultAudioEndpoint(ВОСПРОИЗВЕДЕНИЕ, КОНСОЛЬ) }
            {
                список.push(умолчание);
            }
            if let Ok(все) = unsafe {
                перечис.EnumAudioEndpoints(
                    ВОСПРОИЗВЕДЕНИЕ,
                    windows::Win32::Media::Audio::DEVICE_STATE_ACTIVE,
                )
            } {
                let количество = unsafe { все.GetCount() }.unwrap_or(0);
                for номер in 0..количество {
                    if let Ok(д) = unsafe { все.Item(номер) } {
                        if !список.iter().any(|у| unsafe {
                            у.GetId().ok().zip(д.GetId().ok()).is_some_and(|(а, б)| а == б)
                        }) {
                            список.push(д);
                        }
                    }
                }
            }
            if список.is_empty() {
                return Err("в системе нет ни одного устройства вывода".to_string());
            }
            список
        }
    };

    let mut отказы: Vec<String> = Vec::new();
    for кандидат in кандидаты {
        match unsafe { открыть_и_играть(&кандидат, образцы) } {
            Ok(секунд) => {
                let имя = unsafe { читаемое_имя(&кандидат) };
                return Ok(Сыграно { секунд, устройство: имя });
            }
            Err(о) => отказы.push(о),
        }
    }

    Err(format!(
        "ни одно устройство вывода не приняло звук: {}",
        if отказы.is_empty() {
            "список пуст".to_string()
        } else {
            отказы.join("; ")
        }
    ))
}

/// Открыть одно устройство и отдать ему звук.
unsafe fn открыть_и_играть(
    устройство: &windows::Win32::Media::Audio::IMMDevice,
    образцы: &[f32],
) -> Result<f32, String> {
    let клиент: IAudioClient = (unsafe { устройство.Activate(CLSCTX_ALL, None) })
        .map_err(|e| format!("не открылся: {e}"))?;

    let формат = unsafe { формат_смеси(&клиент) }?;
    (unsafe {
        клиент.Initialize(
            AUDCLNT_SHAREMODE_SHARED,
            0,
            100_000_000i64,
            0,
            &формат.формат,
            None,
        )
    })
    .map_err(|e| format!("не принял формат: {e}"))?;

    let рендер: IAudioRenderClient =
        (unsafe { клиент.GetService() }).map_err(|e| format!("нет службы вывода: {e}"))?;

    // Формат устройства почти всегда отличается от нашего: у нас
    // 16 кГц моно, у него 48 кГц стерео. Порядок обязателен:
    // сначала частота, потом каналы. Наоборот получится устройство,
    // играющее моно-сигнал как стерео со сдвигом каналов.
    let под_устройство = unsafe { приготовить(образцы, &формат) };

    (unsafe { клиент.Start() }).map_err(|о| format!("не начал играть: {о}"))?;
    let начало = std::time::Instant::now();
    let итог = unsafe { отдать(&рендер, &под_устройство, &формат) };

    // Устройство забирает кадры не мгновенно: они лежат в его буфере
    // и уходят в звук за своё время. Без ожидания `Stop()` обрежет
    // всё, что не успели прозвучать, и голос обрывался бы на первом
    // слове. Проверено на этой машине: без ожидания тест отдавал две
    // секунды звука за 0.08 с - то есть кадры уходили в буфер, а не
    // в колонки.
    let нужно = std::time::Duration::from_secs_f32(
        под_устройство.len() as f32 / (формат.частота as f32 * формат.каналов as f32),
    );
    let прошло = начало.elapsed();
    if нужно > прошло {
        std::thread::sleep(нужно - прошло);
    }
    let _ = unsafe { клиент.Stop() };
    итог?;

    Ok(образцы.len() as f32 / ЧАСТОТА as f32)
}

/// Разобранный формат устройства.
struct Смесь {
    формат: WAVEFORMATEX,
    каналов: u16,
    частота: u32,
    бит: u16,
    /// Образцы дробные. Формат смеси вывода на практике всегда
    /// расширенный и всегда дробный, но полагаться на «всегда»
    /// нельзя: целочисленный вывод существует, и запись в него
    /// дробями даст шум.
    плав: bool,
}

/// Тег расширенного формата, который отдаёт устройство вывода.
const ФОРМАТ_РАСШИРЕННЫЙ: u16 = 0xFFFE;
/// Дробный формат `float` 32 бита.
const ФОРМАТ_ДРОБНЫЙ: u16 = 3;
/// Целочисленный формат `PCM`.
const ФОРМАТ_ЦЕЛЫЙ: u16 = 1;

/// Формат смеси устройства вывода.
///
/// Здесь, в отличие от записи, структуру приходится пересобирать, и
/// это не перестраховка, а необходимость. Устройство вывода
/// отдаёт смесь как `WAVEFORMATEXTENSIBLE` с меткой `65534`:
///
///   * микрофон отдаёт смесь с меткой `PCM`, и она устраивает
///     устройство как есть;
///   * вывод отдаёт метку расширения и `cbSize` в 22 байта, то
///     есть объявляет хвост, которого в переданной структуре нет.
///
/// `Initialize` на такое отвечает `E_INVALIDARG` — «параметр задан
/// неверно». Проверено: все пять устройств вывода этой машины
/// отвечали именно так, пока метка не была пересобрана в
/// `IEEE_FLOAT` с нулевым `cbSize`.
///
/// Подформат лежит по смещению 24 (18 базовых + 2 объединение
/// Samples + 4 маска каналов) и читается байтами: `GUID` требует
/// выравнивания, а память под ним упакована.
unsafe fn формат_смеси(клиент: &IAudioClient) -> Result<Смесь, String> {
    let указатель = unsafe { клиент.GetMixFormat() }
        .map_err(|e| format!("формат устройства недоступен: {e}"))?;
    if указатель.is_null() {
        return Err("формат устройства пуст".to_string());
    }
    let wav: WAVEFORMATEX = unsafe { *указатель };

    let плав = if wav.wFormatTag == ФОРМАТ_РАСШИРЕННЫЙ {
        // `KSDATAFORMAT_SUBTYPE_IEEE_FLOAT` начинается с единицы в
        // первом поле `GUID`; всё остальное — `PCM` и его родственники.
        let mut байты = [0u8; 16];
        unsafe {
            std::ptr::copy_nonoverlapping(
                (указатель as *const u8).add(24),
                байты.as_mut_ptr(),
                16,
            );
        }
        u32::from_le_bytes([байты[0], байты[1], байты[2], байты[3]]) == 1
    } else {
        wav.wFormatTag == ФОРМАТ_ДРОБНЫЙ
    };

    let каналов = wav.nChannels.max(1);
    let бит = if wav.wBitsPerSample == 0 { 16 } else { wav.wBitsPerSample };
    let частота = wav.nSamplesPerSec.max(1);
    let блок = (каналов as u32) * ((бит as u32) / 8).max(1);

    // Пересобранная структура: тег настоящий, хвоста нет, а
    // производные поля посчитаны заново. Взять их из исходной
    // расширенной структуры нельзя - она объявляет хвост, которого
    // здесь нет, и устройство сверяет всё вместе.
    let формат = WAVEFORMATEX {
        wFormatTag: if плав { ФОРМАТ_ДРОБНЫЙ } else { ФОРМАТ_ЦЕЛЫЙ },
        nChannels: каналов,
        nSamplesPerSec: частота,
        nAvgBytesPerSec: частота * блок,
        nBlockAlign: блок as u16,
        wBitsPerSample: бит,
        cbSize: 0,
    };

    Ok(Смесь { формат, каналов, частота, бит, плав })
}

/// Привести моно 16 кГц к формату устройства.
unsafe fn приготовить(образцы: &[f32], смесь: &Смесь) -> Vec<f32> {
    let по_частоте = super::record::пересчитать_из(образцы, ЧАСТОТА, смесь.частота);
    if смесь.каналов <= 1 {
        return по_частоте;
    }
    // Один и тот же образец во все каналы. Иначе на стерео
    // половина сигнала уйдёт в левый канал, и голос будет звучать
    // так, будто он сбоку.
    let mut повтор = Vec::with_capacity(по_частоте.len() * смесь.каналов as usize);
    for значение in по_частоте {
        for _ in 0..смесь.каналов {
            повтор.push(значение);
        }
    }
    повтор
}

/// Отдать блоками, пока всё не отдано.
///
/// У рендера в `windows` 0.62 другой API, чем у захвата: он сам
/// спрашивает, сколько кадров отдать, и возвращает готовый адрес.
/// Флаг «устройство хочет тишины» приходит в `ReleaseBuffer`, а не
/// в `GetBuffer`, поэтому тишина отдаётся нулём, а не пропуском.
unsafe fn отдать(
    рендер: &IAudioRenderClient,
    образцы: &[f32],
    смесь: &Смесь,
) -> Result<(), String> {
    let байт_на_кадр = (смесь.бит as usize / 8).max(2) * смесь.каналов as usize;
    // Около 50 мс блока. Меньше - значит чаще просыпаться, больше -
    // заметнее задержка до первого звука.
    let кадров_в_блоке = (смесь.частота as u32 / 20).max(64);
    let всего_кадров = образцы.len() / смесь.каналов as usize;
    let уже = AtomicU32::new(0);

    while (уже.load(Ordering::SeqCst) as usize) < всего_кадров {
        let осталось = всего_кадров - уже.load(Ordering::SeqCst) as usize;
        let сколько = (кадров_в_блоке as usize).min(осталось);

        let адрес = unsafe { рендер.GetBuffer(сколько as u32) }
            .map_err(|e| format!("буфер вывода не отдан: {e}"))?;

        // Устройство может вернуть ноль кадров: оно ещё не готово
        // забирать. Тогда кадры не считаем отданными и ждём.
        let пишем = unsafe { сколько_кадров(адрес, байт_на_кадр, сколько) }.min(сколько);

        if адрес.is_null() || пишем == 0 {
            unsafe { рендер.ReleaseBuffer(0, 0) }
                .map_err(|e| format!("буфер вывода не отдан: {e}"))?;
            std::thread::sleep(std::time::Duration::from_millis(5));
            continue;
        }

        let начало = уже.load(Ordering::SeqCst) as usize * смесь.каналов as usize;
        let кусок = &образцы[начало..начало + пишем * смесь.каналов as usize];
        unsafe { записать(адрес, кусок, смесь) };
        unsafe { рендер.ReleaseBuffer(пишем as u32, 0) }
            .map_err(|e| format!("буфер вывода не отдан: {e}"))?;
        уже.fetch_add(пишем as u32, Ordering::SeqCst);
    }

    let _ = байт_на_кадр;
    Ok(())
}

/// Сколько кадров реально поместилось в отданный буфер.
///
/// Адрес приходит от устройства, а размер - нет: `GetBuffer` в этой
/// версии крейта отдаёт только указатель. Размер известен из
/// запроса, поэтому спрашивать нечего, и проверка сводится к
/// тому, что адрес не пустой: писать в пустой адрес нельзя.
unsafe fn сколько_кадров(
    адрес: *mut u8,
    байт_на_кадр: usize,
    запрошено: usize,
) -> usize {
    if адрес.is_null() || байт_на_кадр == 0 {
        return 0;
    }
    запрошено
}

/// Записать `f32` или `i16` в буфер устройства.
unsafe fn записать(данные: *mut u8, кусок: &[f32], смесь: &Смесь) {
    // Что писать, решает разобранный подформат, а не метка в
    // переданной структуре: метку мы пересобираем сами, и читать
    // её обратно означало бы опираться на собственную же правку.
    let целые = !смесь.плав;

    let mut смещение = 0usize;
    for значение in кусок {
        if целые {
            let ограничено = значение.clamp(-1.0, 1.0) * 32767.0;
            unsafe { (данные.add(смещение) as *mut i16).write_unaligned(ограничено as i16) };
            смещение += 2;
        } else {
            unsafe { (данные.add(смещение) as *mut f32).write_unaligned(*значение) };
            смещение += 4;
        }
    }
}

/// Читаемое имя устройства вывода для ответа.
unsafe fn читаемое_имя(устройство: &windows::Win32::Media::Audio::IMMDevice) -> String {
    use windows::Win32::System::Com::STGM_READ;
    let Ok(хранилище) = (unsafe { устройство.OpenPropertyStore(STGM_READ) }) else {
        return String::new();
    };
    let ключ: windows::Win32::Foundation::PROPERTYKEY =
        windows::Win32::Devices::FunctionDiscovery::PKEY_Device_FriendlyName;
    let Ok(mut значение) = (unsafe { хранилище.GetValue(&ключ) }) else {
        return String::new();
    };
    let имя = unsafe {
        windows::Win32::System::Com::StructuredStorage::PropVariantToStringAlloc(&значение)
            .ok()
            .and_then(|с| с.to_string().ok())
            .unwrap_or_default()
    };
    let _ = unsafe { windows::Win32::System::Com::StructuredStorage::PropVariantClear(&mut значение) };
    имя
}

