// Распознавание речи: отдельный сервер, который человек включает сам.
//
// Два решения, оба измерены на этой машине.
//
// **Распознавание идёт на процессоре.** На карте модель вместе с
// аудиоэнкодером занимает 2594 МиБ, на процессоре — 143 МиБ.
// Разница в задержке: 86 мс против 274 мс медианы, то есть на 188 мс
// больше. Эти 188 мс — цена, которую разумно платить: 2.4 ГиБ на
// карте это разница между «агент работает на 24 слоях» и «агент
// сваливается в разделяемую память уже на 16». Сравнение строк в
// `docs/10-замеры.md`, раздел «Голос на карте из трёх моделей».
//
// **Модель не поднимается сама.** Пока человек не включил голос, на
// карте нет ни сервера распознавания, ни его весов. Это и просил
// человек: голос включается сам, а не висит всё время.

use std::path::PathBuf;
use std::process::{Child, Command, Stdio};
use std::sync::atomic::Ordering;
use std::time::{Duration, Instant};

use super::{ошибка, Голос};

/// Порт сервера распознавания. Отдельный от агента намеренно: если
/// оба на одном порту, второй не поднимется молча, и человек увидит
/// «модель не запущена», хотя на самом деле занят порт.
const ПОРТ_РАСПОЗНАВАНИЯ: u16 = 19110;

/// Сколько ждём готовности сервера распознавания.
const ОЖИДАНИЕ: Duration = Duration::from_secs(60);

/// Поднять сервер распознавания, если он ещё не поднят.
pub fn включить(г: &Голос) -> Result<(), String> {
    if г.поднят() {
        return Ok(());
    }
    let exe = г.путь_к("llama-server.exe")?;
    let модель = г.модель("Qwen3-ASR-0.6B-Q8_0.gguf")?;
    let проектор = г.модель("mmproj-Qwen3-ASR-0.6B-Q8_0.gguf")?;

    let mut ребёнок = Command::new(&exe)
        .args([
            "-m",
            &модель.to_string_lossy(),
            "--mmproj",
            &проектор.to_string_lossy(),
            "-ngl",
            "0",
            "--no-mmproj-offload",
            "-c",
            "4096",
            "--jinja",
            "--host",
            "127.0.0.1",
            "--port",
            &ПОРТ_РАСПОЗНАВАНИЯ.to_string(),
            "-np",
            "1",
            "-t",
            "6",
        ])
        .current_dir(exe.parent().unwrap_or(std::path::Path::new(".")))
        .env(
            "PATH",
            crate::model_manager::prepend_path(
                &crate::model_manager::bin_dir().join("cudart"),
            ),
        )
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|e| format!("не удалось запустить распознавание: {e}"))?;

    let край = Instant::now() + ОЖИДАНИЕ;
    while Instant::now() < край {
        if готово() {
            г.сохранить_процесс(ребёнок);
            return Ok(());
        }
        std::thread::sleep(Duration::from_millis(400));
    }
    // Не дождались — процесс обязан умереть, иначе он останется
    // висеть на карте молча и следующая попытка упрётся в занятый
    // порт с сообщением, которое ничего не объясняет.
    let _ = ребёнок.kill();
    Err(format!(
        "распознавание не поднялось за {} с. Проверь, что скачана модель Qwen3-ASR-0.6B",
        ОЖИДАНИЕ.as_secs()
    ))
}

/// Опустить сервер распознавания.
pub fn выключить(г: &Голос) {
    if let Some(mut ребёнок) = г.забрать_процесс() {
        let _ = ребёнок.kill();
        let _ = ребёнок.wait();
    }
}

/// Сервер отвечает.
fn готово() -> bool {
    let адрес = format!("http://127.0.0.1:{ПОРТ_РАСПОЗНАВАНИЯ}/health");
    match std::net::TcpStream::connect_timeout(
        &match addr_хоста() {
            Some(х) => х,
            None => return false,
        },
        Duration::from_millis(500),
    ) {
        Ok(_) => true,
        Err(_) => false,
    }
}

fn addr_хоста() -> Option<std::net::SocketAddr> {
    use std::net::ToSocketAddrs;
    format!("127.0.0.1:{ПОРТ_РАСПОЗНАВАНИЯ}").to_socket_addrs().ok()?.next()
}

/// Распознать звуковой файл в текст.
///
/// Файл, а не поток: запись с микрофона — отдельная забота, и она
/// не должна быть условием того, что распознавание вообще работает.
pub fn распознать(г: &Голос, звук: &std::path::Path) -> Result<String, String> {
    включить(г)?;
    if !звук.exists() {
        return Err(ошибка(format!(
            "файла звука нет: {}",
            звук.display()
        )));
    }
    let данные = std::fs::read(звук).map_err(|e| format!("не читается звук: {e}"))?;
    let b64 = база64(&данные);

    // Тело запроса собирается руками, а не через `serde_json`:
    // там 1.5 МБ base64, и лишняя копия ради удобства не нужна.
    let тело = format!(
        r#"{{"model":"local","messages":[{{"role":"user","content":[{{"type":"input_audio","input_audio":{{"data":"{b64}","format":"wav"}}}}]}}],"max_tokens":256,"temperature":0}}"#
    );

    let адрес = format!("http://127.0.0.1:{ПОРТ_РАСПОЗНАВАНИЯ}/v1/chat/completions");
    let ответ = отправить(&адрес, тело.as_bytes())?;
    разобрать_ответ(&ответ)
}

/// Ответ модели приходит с префиксом вида
/// `language Russian<asr_text>Проверка…`.
///
/// Префикс убирается. Без этого секретарь диктовал бы вслух слово
/// «language» в начале каждой фразы — и человек услышал бы это
/// раньше, чем понял бы, что ошибка в разборе ответа.
fn разобрать_ответ(ответ: &[u8]) -> Result<String, String> {
    let json: serde_json::Value =
        serde_json::from_slice(ответ).map_err(|e| format!("ответ распознавания не разобран: {e}"))?;
    let текст = json
        .pointer("/choices/0/message/content")
        .and_then(|в| в.as_str())
        .ok_or_else(|| ошибка("в ответе распознавания нет текста"))?;
    let чистый = match текст.find("<asr_text>") {
        Some(м) => &текст[м + "<asr_text>".len()..],
        None => текст,
    };
    Ok(чистый.trim().to_string())
}

/// Минимальный HTTP-клиент поверх `TcpStream`.
///
/// Своим кодом, а не новой зависимостью: запрос один, тело большое,
/// ответ маленький, а в проекте уже есть `reqwest`, но он блокирующий
/// и тянет за собой TLS-стек, который здесь не нужен — сервер
/// локальный и без шифрования.
fn отправить(адрес: &str, тело: &[u8]) -> Result<Vec<u8>, String> {
    use std::io::{Read, Write};
    use std::net::TcpStream;

    let хост = адрес
        .trim_start_matches("http://")
        .trim_end_matches("/v1/chat/completions");
    let mut поток = TcpStream::connect(хост)
        .map_err(|e| format!("не соединиться с распознаванием: {e}"))?;
    let запрос = format!(
        "POST /v1/chat/completions HTTP/1.1\r\nHost: {хост}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
        тело.len()
    );
    поток
        .write_all(запрос.as_bytes())
        .and_then(|()| поток.write_all(тело))
        .map_err(|e| format!("запрос не отправлен: {e}"))?;

    let mut всё = Vec::new();
    поток
        .read_to_end(&mut всё)
        .map_err(|e| format!("ответ не прочитан: {e}"))?;
    // Отрезаем заголовки: иначе в JSON попадёт мусор до пустой строки.
    let начало = всё
        .windows(4)
        .position(|окно| окно == b"\r\n\r\n")
        .ok_or_else(|| ошибка("ответ без заголовков"))?;
    Ok(всё[начало + 4..].to_vec())
}

/// Base64 без новой зависимости.
///
/// Своя реализация ради одной функции: `base64` в проекте нет, а
/// тянуть крейт ради `encode` значило бы менять список лицензий
/// ради строки, которая пишется за двадцать строк кода.
fn база64(данные: &[u8]) -> String {
    const АЛФАВИТ: &[u8; 64] =
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut вывод = String::with_capacity(данные.len().div_ceil(3) * 4);
    for кусок in данные.chunks(3) {
        let b0 = кусок[0] as u32;
        let b1 = *кусок.get(1).unwrap_or(&0) as u32;
        let b2 = *кусок.get(2).unwrap_or(&0) as u32;
        let тройка = (b0 << 16) | (b1 << 8) | b2;
        вывод.push(АЛФАВИТ[(тройка >> 18) as usize & 63] as char);
        вывод.push(АЛФАВИТ[(тройка >> 12) as usize & 63] as char);
        вывод.push(if кусок.len() > 1 {
            АЛФАВИТ[(тройка >> 6) as usize & 63] as char
        } else {
            '='
        });
        вывод.push(if кусок.len() > 2 {
            АЛФАВИТ[тройка as usize & 63] as char
        } else {
            '='
        });
    }
    вывод
}

/// Порт сервера распознавания — наружу, для интерфейса и гейтов.
pub fn порт() -> u16 {
    ПОРТ_РАСПОЗНАВАНИЯ
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Разбор ответа: префикс уходит, остаток остаётся.
    ///
    /// Проверяется на живом ответе модели, снятом на этой машине:
    /// ответ был `language Russian<asr_text>Проверка распознавания
    /// речи. Сегодня вторник.` Кириллица записана escape-последовательностями,
    /// потому что байтовый литерал не принимает не-ASCII.
    #[test]
    fn префикс_языка_вырезается() {
        let сырой = br#"{"choices":[{"message":{"content":"language Russian<asr_text>\u041f\u0440\u043e\u0432\u0435\u0440\u043a\u0430."}}]}"#;
        let текст = разобрать_ответ(сырой).expect("разобралось");
        assert_eq!(текст, "Проверка.", "{текст}");
    }

    /// Ответ без префикса тоже должен читаться: полагаться на то,
    /// что модель всегда добавляет метку, нельзя.
    #[test]
    fn ответ_без_префикса_читается_как_есть() {
        // Кириллица escape-последовательностями: байтовый литерал
        // не принимает не-ASCII.
        let сырой = br#"{"choices":[{"message":{"content":"  \u043f\u0440\u043e\u0441\u0442\u043e \u0442\u0435\u043a\u0441\u0442  "}}]}"#;
        assert_eq!(
            разобрать_ответ(сырой).expect("разобралось"),
            "просто текст"
        );
    }

    /// Ответ без текста — это ошибка, а не пустая строка: тихо
    /// вернуть пустоту значит отдать модели фразу, которой не
    /// было сказано.
    #[test]
    fn пустой_ответ_это_ошибка() {
        let e = разобрать_ответ(br#"{"choices":[]}"#).unwrap_err();
        assert!(e.contains("нет текста"), "{e}");
    }

    /// Base64 обязан совпадать с тем, что понимает сервер.
    /// Сверяем с эталоном, посчитанным независимо.
    #[test]
    fn base64_совпадает_с_эталоном() {
        assert_eq!(база64(b""), "");
        assert_eq!(база64(b"f"), "Zg==");
        assert_eq!(база64(b"fo"), "Zm8=");
        assert_eq!(база64(b"foo"), "Zm9v");
        assert_eq!(база64(b"foobar"), "Zm9vYmFy");
    }

    /// Порядок: загрузка поднимает счётчик, который виден гейту.
    #[test]
    fn счётчик_сдвигается_монотонно() {
        let г = Голос::новый();
        let первый = г.счётчик_следующий();
        assert_eq!(первый + 1, г.счётчик_следующий());
        let _ = Ordering::SeqCst;
    }
}