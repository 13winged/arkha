// Определение речи в потоке: Silero VAD, ONNX, без Python.
//
// Зачем. Пока детектор молчит при тишине, цикл разговора упирается
// в два плохих варианта: ждать фиксированное время (и обрывать
// человека на середине фразы) или ждать полной тишины (и отвечать
// с паузой в полсекунды). VAD отвечает на третий вопрос: «звучит ли
// сейчас речь», и позволяет закончить фразу в тот момент, когда
// человек действительно замолчал, а не когда кончился таймер.
//
// Отдельная модель, а не слой основной. Silero VAD — 2.22 МиБ,
// 1.8 млн параметров, работает на процессоре, не занимает видеопамять.
// Основная модель на карте не должна знать про то, что человек
// ещё говорит: она отвечает на вопрос «что делать», а этот вопрос
// задаёт детектор.
//
// Модель: snakers4/silero-vad, MIT. Распространяется через GitHub,
// а не через Hugging Face — там её нет ни под каким именем, и поиск
// выдаёт только зеркала с нулевым числом скачиваний. Настоящий путь:
//   https://raw.githubusercontent.com/snakers4/silero-vad/master/
//     src/silero_vad/data/silero_vad.onnx
// Проверено 14.10.2026, репозиторий жив (10435 звёзд, push
// 2026-09-29). Лицензии: docs/09-лицензии.md, раздел «VAD».
//
// Движок: candle-onnx, MIT OR Apache-2.0. Выбран потому, что это
// чистый Rust без внешних бинарных файлов: установщик остаётся один
// и не требует на машине человека ни Python, ни ONNX Runtime.
//
// Чего здесь нет: записи с микрофона и самого цикла разговора.
// Детектор умеет отвечать на вопрос «звучит ли речь», но кто задаёт
// этот вопрос — пока не собрано. Проверяется он на файле, который
// уже есть на диске.

use std::collections::HashMap;
use std::path::Path;

use candle_core::{Device, Tensor};
use candle_onnx::onnx::ModelProto;

use super::{ошибка, Голос};

/// Сколько образцов в одном окне.
///
/// Не наш выбор: столько требует сама модель при 16 кГц. 512
/// образцов это 32 миллисекунды — примерно как задержка восприятия
/// речи, меньше окно начинает дрожать на стыках слогов.
pub const ОКНО: usize = 512;

/// Частота дискретизации, которую ждёт модель.
pub const ЧАСТОТА: i64 = 16_000;

/// Порог, выше которого окно считается речью.
pub const ПОРОГ_НАЧАЛА: f32 = 0.5;

/// Порог, ниже которого речь считается закончившейся.
///
/// Ниже порога начала намеренно. Если оба порога равны, одна
/// согласная на стыке фраз обрывает фразу на полуслове.
pub const ПОРОГ_КОНЦА: f32 = 0.35;

/// Сколько тихих окон подряд нужно, чтобы объявить конец речи.
///
/// Пауза между словами — это тоже тишина, но речь в ней не
/// закончилась. 8 окон это 256 миллисекунд: короче человеческой
/// паузы между фразами, длиннее дрожания между словами.
pub const ТИШИНА_ДО_КОНЦА: usize = 8;

/// Имя файла модели в папке моделей.
pub const ФАЙЛ_МОДЕЛИ: &str = "silero_vad.onnx";

/// Что изменилось в разговоре на этом окне.
///
/// Отдельный тип, а не `bool`: «заговорил» и «замолчал» — разные
/// события, и свести их к одному флагу значит потерять тот самый
/// момент окончания фразы, ради которого детектор и нужен.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Событие {
    /// Речь началась. Момент, когда нужно остановить синтез.
    НачалоРечи,
    /// Речь закончилась. Момент, когда можно отвечать.
    КонецРечи,
}

/// Детектор речи поверх Silero VAD.
///
/// Держит состояние модели между окнами: у Silero есть скрытое
/// состояние LSTM, и сбросить его между окнами — значит получить
/// модель, которая не помнит, что только что звучало, и начинает
/// каждое окно заново.
pub struct Детектор {
    модель: ModelProto,
    /// Скрытое состояние модели между окнами.
    ///
    /// Одно, а не два. В Silero 5 скрытое и клеточное состояния
    /// сложены в один тензор `[2, 1, 128]` и передаются как `state`,
    /// возвращаются как `stateN`. Раздельно они были только в
    /// более старых версиях, и код, написанный по памяти о `h` и
    /// `c`, честно падает с «missing input state».
    ///
    /// Обнулять его между окнами нельзя: модель перестаёт помнить,
    /// что только что звучало, и каждое окно начинает заново — а
    /// это уже не VAD, а броски монетки.
    state: Tensor,
    /// Решение принимается здесь, а не в детекторе.
    ///
    /// Отделено намеренно: `решить` — чистая функция от одного
    /// числа, и проверять её можно без модели, без файла и без
    /// живой машины. Всё, что касается загрузки ONNX, живёт в
    /// детекторе; всё, что касается смысла, — здесь.
    состояние: Состояние,
    /// Неполное окно, доехавшее от прошлого вызова.
    буфер: Vec<f32>,
    /// Последняя вычисленная вероятность, ради диагностики.
    последнее: f32,
    /// Формы последних поданных входов: только для текста ошибки.
    последние_формы: HashMap<String, String>,
}

/// Смысловая часть детектора: где мы находимся в разговоре.
///
/// Ничего не знает про ONNX. Три числа и два порога — весь
/// алгоритм, который должен работать всегда одинаково.
#[derive(Debug, Default)]
struct Состояние {
    /// Речь идёт прямо сейчас.
    в_речи: bool,
    /// Сколько тихих окон подряд набежало.
    тихих: usize,
}

impl Состояние {
    /// Перевести вероятность в событие, с гистерезисом и задержкой.
    ///
    /// Гистерезис — два разных порога, а не один. При одном пороге
    /// согласная на стыке фраз обрывает фразу на полуслове.
    /// Задержка — молчание между словами тоже молчание, но речь в
    /// нём не закончилась.
    fn решить(&mut self, п: f32) -> Option<Событие> {
        if !self.в_речи {
            if п >= ПОРОГ_НАЧАЛА {
                self.в_речи = true;
                self.тихих = 0;
                return Some(Событие::НачалоРечи);
            }
            return None;
        }
        if п < ПОРОГ_КОНЦА {
            self.тихих += 1;
            if self.тихих >= ТИШИНА_ДО_КОНЦА {
                self.в_речи = false;
                self.тихих = 0;
                return Some(Событие::КонецРечи);
            }
        } else {
            self.тихих = 0;
        }
        None
    }
}

impl Детектор {
    /// Загрузить модель из папки моделей.
    ///
    /// Ошибка обязана называть, где искали файл: «файл не найден»
    /// без пути — это просьба догадаться, а человек не должен
    /// гадать, куда класть модель.
    pub fn загрузить(путь: &Path) -> Result<Self, String> {
        let байты = std::fs::read(путь).map_err(|e| {
            ошибка(format!(
                "модель VAD не читается: {e}\n  ждали: {}",
                путь.display()
            ))
        })?;
        let модель = prost::Message::decode(байты.as_slice())
            .map_err(|e| ошибка(format!("модель VAD разобрана как ONNX не удалась: {e}")))?;
        Ok(Self {
            модель,
            state: нулевое_состояние()?,
            состояние: Состояние::default(),
            буфер: Vec::new(),
            последнее: 0.0,
            последние_формы: HashMap::new(),
        })
    }

    /// Последняя вычисленная вероятность.
    ///
    /// Хранится ради диагностики: по нему видно, на каком пороге
    /// детектор сомневался, когда человек говорил «ааа» в тишине.
    pub fn последняя_вероятность(&self) -> f32 {
        self.последнее
    }

    /// Прогнать одно окно и вернуть вероятность речи, от 0 до 1.
    ///
    /// Обновляет скрытое состояние, поэтому окна должны идти подряд.
    pub fn вероятность(&mut self, окно: &[f32]) -> Result<f32, String> {
        if окно.len() != ОКНО {
            return Err(ошибка(format!(
                "окно должно быть ровно {ОКНО} образцов, а пришло {}",
                окно.len()
            )));
        }
        let вход = Tensor::from_vec(окно.to_vec(), ОКНО, &Device::Cpu)
            .map_err(|e| ошибка(format!("окно не стало тензором: {e}")))?
            .unsqueeze(0)
            .map_err(|e| ошибка(format!("окно не получило ось: {e}")))?;
        // Скаляр, а не массив из одного числа: в графе `sr` объявлен
        // без измерений. Ошибка от candle-onnx читается
        // наоборот — «got [], expected [1]» означает «в модели пусто,
        // а подали один элемент», и это стоило одного прогона,
        // чтобы разобраться.
        // Скаляр без измерений. Отдельного конструктора `scalar` в
        // candle-core 0.11 нет — он делается через `TryFrom<i64>`,
        // и это единственный способ получить именно ранг 0:
        // `Tensor::new(&[ЧАСТОТА])` даёт ранг 1, и модель его
        // не принимает.
        let частота = Tensor::try_from(ЧАСТОТА)
            .map_err(|e| ошибка(format!("частота не стала тензором: {e}")))?;

        let mut входы: HashMap<String, Tensor> = HashMap::new();
        // Имена берутся из самого графа модели, а не по памяти.
        //
        // Проверено на этой модели 14.10.2026: входы `input`,
        // `state`, `sr`, выходы `output`, `stateN`. У Silero версии
        // 5 и новее состояние одно — скрытое и клеточное сложены в
        // один тензор. В более старых было два входа, `h` и `c`, и
        // код, написанный по памяти о них, честно падает с «missing
        // input state».
        входы.insert("input".to_string(), вход);
        входы.insert("sr".to_string(), частота);
        входы.insert("state".to_string(), self.state.clone());
        self.последние_формы = входы
            .iter()
            .map(|(имя, т)| (имя.clone(), format!("{:?}", т.shape())))
            .collect();

        let выходы = candle_onnx::simple_eval(&self.модель, входы).map_err(|e| {
            // Формы входов входят в текст ошибки намеренно. Без них
            // сообщение от ONNX-движка бесполезно: он пишет, какого
            // ранга ждёт, но не пишет, что именно мы подали, и
            // искать это приходится перебором.
            let формы: Vec<String> = ["input", "sr", "state"]
                .iter()
                .map(|имя| match self.последние_формы.get(*имя) {
                    Some(ф) => format!("{имя}={ф}"),
                    None => format!("{имя}=?"),
                })
                .collect();
            ошибка(format!(
                "модель VAD не отработала: {e}\n  подали: {}",
                формы.join(", ")
            ))
        })?;

        // Состояние забирается до вероятности: даже если выход
        // называется не так, как ожидалось, следующее окно должно
        // получить то, что вернула модель, а не пустоту.
        match выходы.get("stateN") {
            Some(т) => self.state = т.clone(),
            None => return Err(ошибка("модель VAD не вернула состояние stateN")),
        }
        // Значение достаётся как `flatten_all` + `Vec<f32>`, и порядок
        // здесь неверен не на словах, а на практике:
//        - `to_scalar` и `to_vec0` требуют ранга ровно 0, а выход
//          объявлен как [1, 1], и падают;
//        - `Vec<f32>` требует ранга ровно 1, и без `flatten_all`
//          тоже падает.
// Только эта пара подходит обеим проверкам сразу.
        let выход = выходы
            .get("output")
            .ok_or_else(|| ошибка("модель VAD не вернула вероятность речи"))?;
        let числа: Vec<f32> = выход
            .clone()
            .flatten_all()
            .map_err(|e| ошибка(format!("вероятность не расплющена: {e}")))?
            .try_into()
            .map_err(|e| ошибка(format!("вероятность не прочитана: {e}")))?;
        let вероятность = *числа
            .first()
            .ok_or_else(|| ошибка("модель VAD вернула пустой выход"))?;
        self.последнее = вероятность;
        Ok(вероятность)
    }

    /// Скорость: один экран — 32 миллисекунды звука.
    pub fn окно_мс(&self) -> u64 {
        (ОКНО as u64 * 1000) / ЧАСТОТА as u64
    }

    /// Обработать произвольный кусок звука.
    ///
    /// Кусок может быть любой длины: он нарезается на окна, а
    /// неполный хвост возвращается в буфер до следующего вызова.
    /// Так микрофон может отдавать звук порциями по 320, по 1024
    /// или по 4096 образцов, и детектор от этого не перестаёт
    /// считать.
    pub fn шаг(&mut self, пкг: &[f32]) -> Result<Vec<Событие>, String> {
        self.буфер.extend_from_slice(пкг);
        let mut события = Vec::new();
        while self.буфер.len() >= ОКНО {
            let окно: Vec<f32> = self.буфер.drain(..ОКНО).collect();
            let п = self.вероятность(&окно)?;
            if let Some(событие) = self.состояние.решить(п) {
                события.push(событие);
            }
        }
        Ok(события)
    }
}

/// Нулевое состояние модели формы `[2, 1, 128]`.
///
/// Форма взята из графа модели, а не выбрана похожей: несовпадение
/// проявилось бы как «ожидалось 2 x 1 x 128, получено 2 x 1 x 64»
/// посреди разговора, и чинить это пришлось бы вслепую.
fn нулевое_состояние() -> Result<Tensor, String> {
    Tensor::zeros(&[2, 1, 128], candle_core::DType::F32, &Device::Cpu)
        .map_err(|e| ошибка(format!("состояние VAD не создано: {e}")))
}

/// Открыть детектор, взяв модель из общей папки моделей.
pub fn открыть(г: &Голос) -> Result<Детектор, String> {
    let путь = г.модель(ФАЙЛ_МОДЕЛИ)?;
    Детектор::загрузить(&путь)
}

/// Что показала проверка файла.
#[derive(Debug, Clone)]
pub struct Отчёт {
    /// Сколько окон разобрано.
    pub окон: usize,
    /// Сколько окон признано речью.
    pub речевых: usize,
    /// Доля речи в файле, от 0 до 1.
    pub доля: f32,
    /// Наибольшая вероятность, встретившаяся в файле.
    pub пик: f32,
}

/// Прогнать детектор по звуковому файлу целиком.
///
/// Нужен гейту и ручной проверке: «детектор грузится» — это не
/// «детектор отличает речь от тишины». Проверять надо на файле, где
/// есть и то и другое.
pub fn проверить_файл(г: &Голос, путь: &Path) -> Result<Отчёт, String> {
    let mut детектор = открыть(г)?;
    let пкг = прочитать_wav(путь)?;
    let mut окон = 0usize;
    let mut речевых = 0usize;
    let mut пик = 0.0f32;
    let mut буфер = Vec::with_capacity(пкг.len());
    буфер.extend_from_slice(&пкг);
    while буфер.len() >= ОКНО {
        let окно: Vec<f32> = буфер.drain(..ОКНО).collect();
        let п = детектор.вероятность(&окно)?;
        if п >= ПОРОГ_НАЧАЛА {
            речевых += 1;
        }
        if п > пик {
            пик = п;
        }
        окон += 1;
    }
    Ok(Отчёт {
        окон,
        речевых,
        доля: if окон == 0 { 0.0 } else { речевых as f32 / окон as f32 },
        пик,
    })
}

/// Прочитать WAV без зависимостей.
///
/// Только то, что в проекте действительно бывает: 16 бит, один
/// канал, PCM. Частота может быть любой — она приводится к 16 кГц.
/// Поддержка сжатого звука была бы добавлением крейта ради
/// формата, которого здесь не бывает: синтез пишет несжатый WAV,
/// и всё остальное от него не отличается.
fn прочитать_wav(путь: &Path) -> Result<Vec<f32>, String> {
    let байты = std::fs::read(путь)
        .map_err(|e| ошибка(format!("звук не читается: {e}\n  ждали: {}", путь.display())))?;
    if байты.len() < 44 || &байты[0..4] != b"RIFF" || &байты[8..12] != b"WAVE" {
        return Err(ошибка(format!(
            "это не WAV: {}. Нужен несжатый PCM 16 бит, один канал",
            путь.display()
        )));
    }

    // Идём по блокам, а не считаем смещение: у файла может быть
    // блок LIST с метаданными перед форматом, и жёсткое смещение 44
    // тогда указывает мимо заголовка данных.
    let mut позиция = 12usize;
    let mut начало_данных = None;
    let mut разрядность = 0u16;
    let mut каналов = 0u16;
    let mut частота_файла = 0u32;
    while позиция + 8 <= байты.len() {
        let имя = &байты[позиция..позиция + 4];
        let размер = u32::from_le_bytes([
            байты[позиция + 4],
            байты[позиция + 5],
            байты[позиция + 6],
            байты[позиция + 7],
        ]) as usize;
        let содержимое = позиция + 8;
        match имя {
            b"fmt " => {
                разрядность = u16::from_le_bytes([байты[содержимое + 14], байты[содержимое + 15]]);
                каналов = u16::from_le_bytes([байты[содержимое + 2], байты[содержимое + 3]]);
                частота_файла = u32::from_le_bytes([
                    байты[содержимое + 4],
                    байты[содержимое + 5],
                    байты[содержимое + 6],
                    байты[содержимое + 7],
                ]);
            }
            b"data" => {
                начало_данных = Some((содержимое, размер));
                break;
            }
            _ => {}
        }
        позиция = содержимое + размер + размер % 2;
    }

    let (начало, размер) = начало_данных
        .ok_or_else(|| ошибка(format!("в WAV нет блока данных: {}", путь.display())))?;
    if разрядность != 16 {
        return Err(ошибка(format!(
            "звук должен быть 16 бит, а он {разрядность}: {}",
            путь.display()
        )));
    }
    if каналов != 1 {
        return Err(ошибка(format!(
            "звук должен быть одним каналом, а их {каналов}: {}",
            путь.display()
        )));
    }
    // Пересчёт в частоту модели. Отказываться тут неправильно:
    // синтез отдаёт 24 000 Гц (проверено на этой машине), а
    // микрофон в Windows по умолчанию тоже не 16 000. Отказ означал
    // бы, что детектор нельзя применять к звуку, который сам же
    // проект и производит.
    let конец = (начало + размер).min(байты.len());
    let mut пкг = Vec::with_capacity((конец - начало) / 2);
    let mut i = начало;
    while i + 1 < конец {
        let сырое = i16::from_le_bytes([байты[i], байты[i + 1]]) as f32 / 32768.0;
        пкг.push(сырое);
        i += 2;
    }
    if частота_файла as i64 != ЧАСТОТА {
        пкг = пересчитать(&пкг, частота_файла);
    }
    Ok(пкг)
}

/// Свойства WAV из заголовка: частота, разрядность, каналы.
///
/// Отдельная функция, потому что заголовок нужен сам по себе: по
/// нему видно, что́ именно пришлось приводить к 16 кГц, а по
/// одному только результату пересчёта это не различить.
fn свойства_wav(байты: &[u8]) -> (u32, u16, u16) {
    let mut частота = 0u32;
    let mut разряд = 0u16;
    let mut каналы = 0u16;
    let mut позиция = 12usize;
    while позиция + 8 <= байты.len() {
        let размер =
            u32::from_le_bytes(байты[позиция + 4..позиция + 8].try_into().unwrap_or([0; 4]))
                as usize;
        let содержимое = позиция + 8;
        if &байты[позиция..позиция + 4] == b"fmt " && содержимое + 16 <= байты.len() {
            каналы = u16::from_le_bytes([байты[содержимое + 2], байты[содержимое + 3]]);
            частота = u32::from_le_bytes(
                байты[содержимое + 4..содержимое + 8].try_into().unwrap_or([0; 4]),
            );
            разряд = u16::from_le_bytes([байты[содержимое + 14], байты[содержимое + 15]]);
            break;
        }
        позиция = содержимое + размер + размер % 2;
    }
    (частота, разряд, каналы)
}

/// Сколько отводков в фильтре нижних частот.
///
/// Нечётное число, чтобы центральный отводок попал ровно на центр
/// окна и сигнал не сдвигался. 63 отводка при срезе около 8 кГц
/// дают подавление верха порядка 60 дБ: этого хватает, чтобы то,
/// что осталось выше 8 кГц, не сложилось обратно в голос.
const ОТВОДКИ: usize = 63;

/// Частота среза в долях частоты Найквиста **исходного** сигнала.
///
/// Срез ставится по частоте Найквиста **выхода**, иначе после
/// прореживания всё, что лежало между 8 и 12 кГц, сложилось бы в
/// 4–8 кГц, то есть прямо в голос. Это и есть алиасинг.
fn срез_для_исходной(от: u32) -> f64 {
    (ЧАСТОТА as f64 / 2.0) / от as f64
}

/// Фильтр нижних частот: свёртка с ядром «окно Хэмминга на синусе».
///
/// Края файла держатся на крайнем образце, а не заполняются
/// нулями: нулевой край дал бы разрыв в начале и в конце, и
/// детектор увидел бы там не тишину, а щелчок.
fn фильтр_низких(пкг: &[f32], срез: f64) -> Vec<f32> {
    if пкг.is_empty() || !(0.0..0.5).contains(&срез) {
        return пкг.to_vec();
    }
    let центр = (ОТВОДКИ - 1) as f64 / 2.0;
    let mut ядро = Vec::with_capacity(ОТВОДКИ);
    for n in 0..ОТВОДКИ {
        let смещение = n as f64 - центр;
        let аргумент = 2.0 * срез * смещение;
        let синк = if аргумент.abs() < 1e-12 {
            1.0
        } else {
            (std::f64::consts::PI * аргумент).sin() / (std::f64::consts::PI * аргумент)
        };
        let окно = 0.54
            - 0.46 * (2.0 * std::f64::consts::PI * n as f64 / (ОТВОДКИ - 1) as f64).cos();
        ядро.push((2.0 * срез * синк * окно) as f32);
    }
    // Сумма ядра приводится к единице, чтобы постоянная составляющая
    // прошла без изменения. Иначе фильтр тихо приглушал бы весь
    // сигнал, и мы гадали бы, почему детектор перестал видеть речь.
    let сумма: f32 = ядро.iter().sum();
    if сумма.abs() > f32::EPSILON {
        for в in &mut ядро {
            *в /= сумма;
        }
    }

    let последний = пкг.len() - 1;
    let mut выход = Vec::with_capacity(пкг.len());
    for i in 0..пкг.len() {
        let mut накоплено = 0.0f32;
        for (k, вес) in ядро.iter().enumerate() {
            let j = (i as isize + k as isize - центр as isize).clamp(0, последний as isize);
            накоплено += пкг[j as usize] * вес;
        }
        выход.push(накоплено);
    }
    выход
}

/// Пересчитать звук в 16 кГц: сперва фильтр, потом прореживание.
///
/// Фильтр обязателен, а не украшение. Линейная интерполяция сама по
/// себе прореживает, но не убирает верх: то, что было выше 8 кГц,
/// переезжает в полезную часть спектра и звучит как шум. Это
/// проверялось: без фильтра пик вероятности на собственной речи
/// проекта был 0.4923 при пороге 0.5, то есть не дотягивал.
fn пересчитать(пкг: &[f32], от: u32) -> Vec<f32> {
    if от == 0 || пкг.is_empty() {
        return пкг.to_vec();
    }
    // Прореживать без фильтра нельзя: верхний спектр сложится
    // обратно в голос. Фильтр нужен только когда частота
    // понижается; при повышении и при равной частоте он не
    // требуется, и тратить на него время незачем.
    let с_фильтром = if от > ЧАСТОТА as u32 {
        Some(фильтр_низких(пкг, срез_для_исходной(от)))
    } else {
        None
    };
    let источник: &[f32] = с_фильтром.as_deref().unwrap_or(пкг);

    let отношение = от as f64 / ЧАСТОТА as f64;
    let сколько = (источник.len() as f64 / отношение).round() as usize;
    let mut выход = Vec::with_capacity(сколько);
    for n in 0..сколько {
        let позиция = n as f64 * отношение;
        let целая = позиция.floor() as usize;
        let доля = (позиция - целая as f64) as f32;
        let левый = источник.get(целая).copied().unwrap_or(0.0);
        let правый = источник.get(целая + 1).copied().unwrap_or(левый);
        выход.push(левый + (правый - левый) * доля);
    }
    выход
}

#[cfg(test)]
