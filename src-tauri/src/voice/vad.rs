    ///
    /// Без этой проверки ошибка в одну миллионную не видна: звук
    /// остаётся похожим на звук, детектор отвечает правдоподобно,
    /// а на деле получает не ту частоту.
    #[test]
    fn пересчёт_меняет_длину_во_столько_же_раз() {
        let пкг: Vec<f32> = (0..480).map(|i| (i as f32 * 0.01).sin()).collect();
        let на16 = пересчитать(&пкг, 24_000);
        assert_eq!(на16.len(), 320, "24 кГц -> 16 кГц должно дать 320");
        let на8 = пересчитать(&пкг, 48_000);
        assert_eq!(на8.len(), 160, "48 кГц -> 16 кГц должно дать 160");
        let без_пересчёта = пересчитать(&пкг, ЧАСТОТА as u32);
        assert_eq!(без_пересчёта.len(), 480, "16 кГц в 16 кГц не меняется");
    }

    /// Нулевая частота означает «не знаю», и такой звук обязан
    /// остаться как есть. Иначе детектор получит тишину вместо
