    /// Фильтр обязан убивать то, что выше порога прореживания.
///
/// Это и есть проверка на алиасинг. Синус 10 кГц в сигнале
/// 24 кГц после приведения к 16 кГц обязан исчезнуть: если он не
/// исчезнет, он сложится в 6 кГц и станет шумом поверх голоса.
/// Без этой проверки пересчёт выглядит рабочим — длина верная,
/// звук на слух похожий — а детектор на таком звуке слепнет.
#[test]
    fn фильтр_убивает_то_что_выше_среза() {
        let частота_входа = 24_000f32;
        let n = 24_000usize; // одна секунда
        let тон: Vec<f32> = (0..n)
            .map(|i| (2.0 * std::f32::consts::PI * 10_000.0 * i as f32 / частота_входа).sin())
            .collect();
        let после = пересчитать(&тон, 24_000);
        // Смотрим на середину: края держатся на крайн��м образце.
        let середина = &после[после.len() / 4..после.len() * 3 / 4];
        let пик = середина.iter().fold(0.0f32, |м, x| м.max(x.abs()));
        assert!(
            пик < 0.01,
            "тон 10 кГц должен исчезнуть после прореживания, а пик {пик}"
        );
    }

    /// Тон ниже среза обязан выжить и почти не измениться.
    ///
    /// Обратная сторона той же проверки: фильтр, который убивает
    /// вместе с верхом и голос, выглядит как «работающий фильтр»
    /// ровно так же, как фильтр, который всё ломает.
    #[test]
    fn фильтр_держит_то_что_ниже_среза() {
        let частота_входа = 24_000f32;
        let n = 24_000usize;
        let тон: Vec<f32> = (0..n)
            .map(|i| (2.0 * std::f32::consts::PI * 1_000.0 * i as f32 / частота_входа).sin())
            .collect();
        let после = пересчитать(&тон, 24_000);
        let середина = &после[после.len() / 4..после.len() * 3 / 4];
        let пик = середина.iter().fold(0.0f32, |м, x| м.max(x.abs()));
        assert!(
            (0.9..=1.0).contains(&пик),
            "тон 1 кГц должен пройти почти без потерь, а пик {пик}"
        );
    }

    /// Постоянная составляющая не должна затухать.
    ///
    /// Это проверка нормализации ядра. Сумма приводится к единице
    /// специально для этого: без неё фильтр тихо приглушает всё
    /// подряд, и выглядит это как «детектор перестал видеть речь».
    #[test]
    fn постоянная_составляющая_не_тухнет() {
        let ровный = vec![0.5f32; 24_000];
        let после = фильтр_низких(&ровный, срез_для_исходной(24_000));
        let середина = &после[после.len() / 4..после.len() * 3 / 4];
        let среднее = середина.iter().sum::<f32>() / середина.len() as f32;
        assert!(
            (среднее - 0.5).abs() < 0.01,
            "постоянная составляющая должна остаться 0.5, а стала {среднее}"
        );
    }


