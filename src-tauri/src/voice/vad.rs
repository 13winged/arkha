    /// Путь к модели VAD в общей папке моделей.
    ///
    /// Учитывает `ARKHA_MODELS_DIR`, чтобы гейты и обычный запуск
    /// смотрели в одно место. Без модели тесты сходятся с пропуском,
    /// а не падают: на машине без скачанных весов проверять нечего,
    /// и падать здесь было бы неправдой о состоянии программы.
    fn путь_модели() -> Option<PathBuf> {
        // Штатный поиск папки моделей проекта, а не разбор
        // переменных здесь: если смена папки когда-нибудь поедет,
        // тест поедет вместе с приложением, а не отдельно от него.
        let п = crate::model_manager::models_dir().join(ФАЙЛ_МОДЕЛИ);
        п.exists().then_some(п)
    }

    /// Тишина обязана быть тишиной.
    ///
    /// На тишине модель обязана выдавать заметно меньше порога.
    /// Если не выдаст, детектор будет считать речью всё подряд и
    /// цикл разговора заработает сам, без спроса человека — а это
    /// ровно то, чего проект не делает ни с голосом, ни с чем-либо
    /// ещё.
    #[test]
    fn тишина_не_считается_речью() {
        let путь = match путь_модели() {
            Some(п) => п,
            None => {
                eprintln!("пропуск: нет модели VAD");
                return;
            }
        };
        let mut д = Детектор::загрузить(&путь).expect("модель VAD загрузилась");
        // Несколько окон подряд: состояние накапливается, и если
        // модель «залипает», это видно уже на третьем окне.
        for окно in 0..3 {
            let п = д
                .вероятность(&vec![0.0f32; ОКНО])
                .unwrap_or_else(|e| panic!("окно {окно}: {e}"));
            assert!(
                (0.0..=1.0).contains(&п),
                "окно {окно}: вероятность вне 0..1: {п}"
            );
            assert!(
                п < ПОРОГ_НАЧАЛА,
                "окно {окно}: на тишине вероятность {п}, а порог {ПОРОГ_НАЧАЛА}"
            );
        }
    }

    /// Окно неверной длины отвергается с точным числом, а не
