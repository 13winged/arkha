// Горячая клавиша записи с микрофона.
//
// Решение владельца: голос включается клавишей, а не словом.
// Разбор источника — docs/28-push-to-talk.md.
//
// Почему низкоуровневый хук, а не `RegisterHotKey`. Регистрация
// горячей клавиши сообщает только о нажатии и повторяет
// сообщение, пока палец лежит на клавише. Для диктовки это не
// годится: нужно знать, когда клавишу отпустили, чтобы остановить
// запись. Низкоуровневый хук даёт и нажатие, и отпускание.
//
// Что модуль не делает: он не пишет на диск, не запускает
// процессов и не перехватывает клавиши насовсем. Нужная клавиша
// пропускается дальше через `CallNextHookEx` — иначе человек не
// смог бы набрать ею текст в других программах.
//
// Поток и разрыв: хук работает на том потоке, который его
// установил, и этому потоку нужен цикл сообщений. Отсюда
// отдельный поток с циклом, а события приходят через канал, а не
// напрямую: так состояние записи не трогается из чужого потока.

use std::sync::atomic::{AtomicBool, AtomicU32, Ordering};
use std::sync::mpsc::{Receiver, Sender};
use std::sync::{Arc, Mutex};

use windows::Win32::Foundation::{LPARAM, LRESULT, WPARAM};
use windows::Win32::UI::Input::KeyboardAndMouse::{
    GetAsyncKeyState, VIRTUAL_KEY, VK_CONTROL, VK_H,
};
use windows::Win32::UI::WindowsAndMessaging::{
    CallNextHookEx, DispatchMessageW, GetMessageW, KBDLLHOOKSTRUCT, SetWindowsHookExW,
    TranslateMessage, UnhookWindowsHookEx, HC_ACTION, WH_KEYBOARD_LL, WM_KEYDOWN, WM_KEYUP,
};

/// Номер отслеживаемой клавиши. Меняется при переназначении.
static СЛЕДИМ: AtomicU32 = AtomicU32::new(0);
/// Нажата ли клавиша прямо сейчас. Отдельно от канала: по этому
/// флагу автоповтор при удержании отсекается, иначе запись
/// начиналась бы заново на каждом повторе.
static НАЖАТА: AtomicBool = AtomicBool::new(false);
/// Жив ли хук.
static ЖИВ: AtomicBool = AtomicBool::new(false);
/// Установлен ли хук в системе (даже если обработка сейчас выключена).
static УСТАНОВЛЕН: AtomicBool = AtomicBool::new(false);

/// Что прислал хук.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Событие {
    /// Палец поставлен. Начинать запись.
    Нажата,
    /// Палец убран. Останавливать запись.
    Отпущена,
}

/// Канал событий: хук пишет, команда приложения читает.
static КАНАЛ: Mutex<Option<Sender<Событие>>> = Mutex::new(None);

/// Умолчание: Ctrl + H. `H` — «hearing»; одной модификаторной
/// клавиши мало, а три клавиши нажимать неудобно.
const УМОЛЧАНИЕ: &str = "Ctrl+H";

/// Комбинация по умолчанию. Нужна интерфейсу и миграции старых
/// настроек, где стояли `Ctrl+Alt+M` и `Ctrl+G`.
pub fn умолчание() -> &'static str {
    УМОЛЧАНИЕ
}

/// Жив ли хук.
pub fn включён() -> bool {
    ЖИВ.load(Ordering::SeqCst)
}

/// Был ли хук вообще установлен.
///
/// Отличается от [`включён`]: выключение голоса гасит обработчик, но
/// сам хук остаётся в системе до конца процесса. Повторная установка
/// поверх него плодит лишние хуки и второй поток-слушатель, поэтому
/// при повторном включении достаточно возобновить старый.
pub fn установлен() -> bool {
    УСТАНОВЛЕН.load(Ordering::SeqCst)
}

/// Возобновить обработку после [`снять`], не ставя второй хук.
pub fn возобновить() -> Result<(), String> {
    if !УСТАНОВЛЕН.load(Ordering::SeqCst) {
        return Err("хук не был установлен".to_string());
    }
    НАЖАТА.store(false, Ordering::SeqCst);
    ЖИВ.store(true, Ordering::SeqCst);
    Ok(())
}

/// Поставить хук и вернуть канал событий.
///
/// Ставится один раз за жизнь процесса: хук глобальный, второй
/// поверх первого только замедлит машину, ничего не добавив.
/// Клавишу меняют отдельно, через `сменить`.
pub fn поставить() -> Result<Receiver<Событие>, String> {
    if включён() {
        return Err("горячая клавиша уже стоит".to_string());
    }
    поставить_с(УМОЛЧАНИЕ)
}

/// Поставить хук на указанное сочетание.
pub fn поставить_с(сочетание: &str) -> Result<Receiver<Событие>, String> {
    СЛЕДИМ.store(клавишу_из(сочетание)?, Ordering::SeqCst);
    НАЖАТА.store(false, Ordering::SeqCst);

    let (отправитель, получатель) = std::sync::mpsc::channel();
    *КАНАЛ.lock().map_err(|e| format!("канал занят: {e}"))? = Some(отправитель);

    let встал = Arc::new(AtomicBool::new(false));
    let флаг = встал.clone();
    let сочетание_в_потоке = сочетание.to_string();

    std::thread::Builder::new()
        .name("горячая клавиша".to_string())
        .spawn(move || цикл(флаг, сочетание_в_потоке))
        .map_err(|e| format!("поток клавиши не начался: {e}"))?;

    // Поток мог не успеть поставить хук. Ждём недолго: если он не
    // встал за секунду, дело не в скорости, а в ошибке.
    for _ in 0..100 {
        if встал.load(Ordering::SeqCst) {
            return Ok(получатель);
        }
        std::thread::sleep(std::time::Duration::from_millis(10));
    }
    Err("хук не установился за секунду".to_string())
}

/// Снять хук.
///
/// Windows не умеет снимать глобальный хук из чужого потока, а
/// своего «остывания» не существует: хук живёт, пока жив поток,
/// который его поставил. Поэтому снятие — это работа с потоком,
/// а не вызов `UnhookWindowsHookEx`. Поток, ушедший в цикл
/// сообщений, живёт до конца процесса, и это осознанно: он
/// ничего не делает, кроме ожидания, и стоит один на всё
/// приложение.
pub fn снять() {
    ЖИВ.store(false, Ordering::SeqCst);
    НАЖАТА.store(false, Ordering::SeqCst);
}

/// Сменить отслеживаемую клавишу на лету, без переустановки хука.
pub fn сменить(сочетание: &str) -> Result<(), String> {
    let клавиша = клавишу_из(сочетание)?;
    СЛЕДИМ.store(клавиша, Ordering::SeqCst);
    НАЖАТА.store(false, Ordering::SeqCst);
    Ok(())
}

/// Разобрать сочетание и достать из него клавишу.
///
/// Поддерживается ровно одно сочетание — `Ctrl+H`. Не
/// «хоть что-нибудь похожее», а одно: любая другая раскладка
/// сочетаний требует своей таблицы и своей проверки, а
/// неполная таблица хуже её отсутствия. Неизвестное сочетание —
/// ошибка с человеческим текстом, а не молчание: человек решил
/// бы, что переназначил клавишу, а запись шла бы по старой.
fn клавишу_из(сочетание: &str) -> Result<u32, String> {
    let норма = сочетание.trim().replace(' ', "").replace('+', "+");
    if норма.eq_ignore_ascii_case(УМОЛЧАНИЕ) {
        return Ok(VK_H.0 as u32);
    }
    Err(format!(
        "сочетание «{сочетание}» не поддерживается, доступно пока только {УМОЛЧАНИЕ}"
    ))
}

/// Обработчик хука.
///
/// Обязан быть `extern "system"` и возвращать результат
/// `CallNextHookEx`: иначе следующий в цепочке хук не увидит
/// событие, а программы начнут вести себя странно.
unsafe extern "system" fn обработать(code: i32, wparam: WPARAM, lparam: LPARAM) -> LRESULT {
    let дальше = || unsafe { CallNextHookEx(None, code, wparam, lparam) };

    // Структуру по адресу из lparam читать можно только при
    // HC_ACTION: при других кодах по этому адресу может лежать
    // что угодно, и чтение — это неопределённое поведение.
    if code != HC_ACTION as i32 {
        return дальше();
    }
    // Хук остаётся в системе до конца процесса, но после выключения
    // голоса он обязан молчать: иначе Ctrl+H продолжал бы начинать
    // запись при выключенном распознавании.
    if !ЖИВ.load(Ordering::SeqCst) {
        return дальше();
    }
    let событие = match wparam.0 as u32 {
        WM_KEYDOWN => Событие::Нажата,
        WM_KEYUP => Событие::Отпущена,
        _ => return дальше(),
    };

    let данные = unsafe { &*(lparam.0 as *const KBDLLHOOKSTRUCT) };
    if данные.vkCode as u32 != СЛЕДИМ.load(Ordering::SeqCst) {
        return дальше();
    }

    // Нажатие засчитывается только с Ctrl. Без этой проверки
    // клавиша `H` срабатывала бы сама по себе и перехватывала набор
    // текста.
    let с_модификаторами = unsafe { зажат(VK_CONTROL) };
    match событие {
        Событие::Нажата => {
            if !с_модификаторами {
                return дальше();
            }
            // Автоповтор при удержании приходит отдельным
            // WM_KEYDOWN. Повтор — не новое нажатие.
            if НАЖАТА.swap(true, Ordering::SeqCst) {
                return дальше();
            }
            послать(Событие::Нажата);
        }
        Событие::Отпущена => {
            // Отпускание ловим без проверки модификаторов: человек
            // мог отпустить клавишу вместе с Alt, и запись всё
            // равно надо остановить.
            if НАЖАТА.swap(false, Ordering::SeqCst) {
                послать(Событие::Отпущена);
            }
        }
    }

    дальше()
}

/// Зажата ли клавиша прямо сейчас.
unsafe fn зажат(клавиша: VIRTUAL_KEY) -> bool {
    // Старший бит означает «нажата сейчас»; младший — «была
    // нажата с последнего вызова». Нас интересует именно старший,
    // иначе удержание любой клавиши когда-то оставило бы след.
    //
    // Маска через `as i32`, а не через константу `0x8000` того же
    // типа: `GetAsyncKeyState` отдаёт `i16`, и литерал 0x8000 в
    // него не влезает - компилятор правомерно отказывает.
    (unsafe { GetAsyncKeyState(клавиша.0 as i32) } as i32) & 0x8000 != 0
}

/// Отправить событие, не паникуя из хука.
///
/// Хук не имеет права паниковать: паника в нём уносит с собой всё
/// приложение. Если канала нет, событие просто теряется — и это
/// лучше, чем краш.
fn послать(событие: Событие) {
    if let Ok(к) = КАНАЛ.lock() {
        if let Some(отпр) = к.as_ref() {
            let _ = отпр.send(событие);
        }
    }
}

/// Поток с хуком и циклом сообщений.
fn цикл(встал: Arc<AtomicBool>, _сочетание: String) {
    unsafe {
        // Глобальный низкоуровневый хук: `dwThreadId` ноль, модуль
        // не нужен. Хук работает в контексте нашего процесса.
        let хук = match SetWindowsHookExW(WH_KEYBOARD_LL, Some(обработать), None, 0) {
            Ok(х) => х,
            Err(_) => return,
        };
        ЖИВ.store(true, Ordering::SeqCst);
        УСТАНОВЛЕН.store(true, Ordering::SeqCst);
        встал.store(true, Ordering::SeqCst);

        цикл_сообщений();

        let _ = UnhookWindowsHookEx(хук);
    }
}


/// Ожидание сообщений до `WM_QUIT`.
///
/// Отдельная функция, потому что цикл требует `MSG`, а настоящее
/// окно нам не нужно: хук низкого уровня работает и без него,
/// хватит `GetMessageW` в цикле.
unsafe fn цикл_сообщений() {
    let mut сообщение = windows::Win32::UI::WindowsAndMessaging::MSG::default();
    loop {
        // Ноль — это `WM_QUIT`, минус один — ошибка. Различать
        // нечего: и то и другое означает «выходить».
        let получено = unsafe { GetMessageW(&mut сообщение, None, 0, 0) };
        if !получено.as_bool() {
            return;
        }
        unsafe {
            let _ = TranslateMessage(&сообщение);
            let _ = DispatchMessageW(&сообщение);
        }
    }
}

/// Описание сочетания для интерфейса.
pub fn комбинация() -> &'static str {
    УМОЛЧАНИЕ
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Пустое значение настройки не считается ошибкой: человек
    /// ещё ничего не выбирал, и молчаливый отказ сбил бы его с
    /// толку.
    #[test]
    fn пустое_берёт_умолчание() {
        assert_eq!(клавишу_из(УМОЛЧАНИЕ).unwrap(), VK_H.0 as u32);
    }

    /// Регистр и лишние пробелы не должны ломать настройку:
    /// человек набрал `ctrl + g`.
    #[test]
    fn настройка_не_чувствительна_к_регистру_и_пробелам() {
        assert!(клавишу_из("ctrl+h").is_ok());
        assert!(клавишу_из("Ctrl + H").is_ok());
    }

    /// Неизвестное сочетание — ошибка с текстом. Молчание здесь
    /// опаснее: человек решил бы, что переназначил клавишу, а
    /// запись шла бы по старой.
    #[test]
    fn неизвестное_сочетание_даёт_ошибку() {
        let о = клавишу_из("Ctrl+Shift+Z").unwrap_err();
        assert!(о.contains("Ctrl+H"), "{о}");
    }

    /// Хук и канал — глобальное состояние, поэтому проверять их
    /// параллельно нельзя: второй тест увидит хук первого. Проверка
    /// одна и по порядку.
    #[test]
    fn хук_ставится_и_читает_состояние() {
        assert!(!включён(), "хук не должен стоять до постановки");
        let канал = поставить().expect("хук должен встать");
        assert!(включён());
        assert!(канал.try_iter().next().is_none(), "событий быть не должно");

        сменить(УМОЛЧАНИЕ).expect("переназначение на то же сочетание");
        assert!(сменить("Ctrl+Shift+Z").is_err(), "чужая комбинация должна падать");

        снять();
        assert!(!включён());
    }

    /// Хук действительно видит Ctrl+H и присылает нажатие и отпускание.
    ///
    /// Синтетический ввод идёт через `SendInput`, то есть тем же
    /// путём, что и настоящая клавиатура. Тест глобальный и шлёт
    /// клавиши всей машине, поэтому помечен `ignore`: в обычном
    /// прогоне ему нечего делать.
    #[test]
    #[ignore]
    fn ctrl_h_приходит_в_канал() {
        use windows::Win32::UI::Input::KeyboardAndMouse::{
            INPUT, INPUT_0, INPUT_KEYBOARD, KEYBDINPUT, KEYEVENTF_KEYUP, SendInput,
        };

        fn событие(код: u16, вверх: bool) -> INPUT {
            INPUT {
                r#type: INPUT_KEYBOARD,
                Anonymous: INPUT_0 {
                    ki: KEYBDINPUT {
                        wVk: VIRTUAL_KEY(код),
                        wScan: 0,
                        dwFlags: if вверх { KEYEVENTF_KEYUP } else { Default::default() },
                        time: 0,
                        dwExtraInfo: 0,
                    },
                },
            }
        }

        let канал = поставить_с("Ctrl+H").expect("хук должен встать");
        let ввод = [
            событие(0x11, false), // Ctrl
            событие(0x48, false), // H
            событие(0x48, true),
            событие(0x11, true),
        ];
        unsafe { SendInput(&ввод, std::mem::size_of::<INPUT>() as i32) };

        let первое = канал
            .recv_timeout(std::time::Duration::from_secs(2))
            .expect("нажатие не пришло");
        let второе = канал
            .recv_timeout(std::time::Duration::from_secs(2))
            .expect("отпускание не пришло");
        assert!(matches!(первое, Событие::Нажата), "{первое:?}");
        assert!(matches!(второе, Событие::Отпущена), "{второе:?}");
        снять();
    }
}
