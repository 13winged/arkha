// Разрешение одного правила, а не всех. Ниже две `unsafe`-функции —
// это граница с COM: небезопасный контекст в них устанавливается
// один раз на входе, и каждая отдельная обёртка `unsafe { }` внутри
// только засоряла бы чтение, ничего не добавляя. Все вызовы в этих
// функциях — COM из крейта `windows`.
#![allow(unsafe_op_in_unsafe_fn)]

// Запись с микрофона по нажатию клавиши.
//
// Решение владельца: голос включается клавишей, а не словом.
// Разбор источника и применимость — docs/28-push-to-talk.md, там же
// семь решений, которые сюда перенесены.
//
// Почему не VAD и не пробуждение по имени: и то и другое сейчас не
// работает. `voice.wake` занимает 43 байта, гейт openWakeWord на
// настоящем слове дал 1.57e-9 против 1.02e-8 на тишине. При
// push-to-talk вопрос «заговорил ли человек» не возникает: запись
// идёт ровно между нажатием и отпусканием клавиши.
//
// Чего модуль не делает: не распознаёт, не синтезирует и ничего не
// вставляет в чужие окна. Он только даёт звук.

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};
use std::thread::JoinHandle;

/// Частота, которую ждут распознавание и синтез. Всё приводится к
/// ней: моно, 16 кГц, f32.
pub const ЧАСТОТА: u32 = 16_000;

/// Самая длинная одна запись. Не «пока не надоест», а предел: буфер
/// считается вперёд, и без предела он растёт вместе с записью.
pub const МАКСИМУМ: std::time::Duration = std::time::Duration::from_secs(300);

/// CLSID_MMDeviceEnumerator, mmdevapi.h.
///
/// В крейте `windows` идентификатора нет: имя есть у интерфейса
/// `IMMDeviceEnumerator`, а самого класса — нет. Значение опубликовано
/// в mmdevapi.h и не менялось. Проверено пробой 16.10.2026: с этим
/// GUID перечислитель создаётся и микрофон по умолчанию находится,
/// `{0.0.1.00000000}.{ccc66bc4-6a74-43f9-ac19-615ee751f80f}`.
const CLSID_МИКРОФОН: windows::core::GUID =
    windows::core::GUID::from_u128(0xBCDE_0395_E52F_467C_8E3D_C457_9291_692E);

/// `eCapture` в новтипе `EDataFlow(i32)`: 0 — воспроизведение,
/// 1 — захват, 2 — все.
const ЗАХВАТ: windows::Win32::Media::Audio::EDataFlow =
    windows::Win32::Media::Audio::EDataFlow(1);

/// `eConsole` в новтипе `ERole(i32)`: 0 — консоль, 1 — мультимедиа,
/// 2 — связь. Берём консоль: это то, что человек имеет в виду,
/// когда говорит «микрофон».
const КОНСОЛЬ: windows::Win32::Media::Audio::ERole = windows::Win32::Media::Audio::ERole(0);

/// `WAVE_FORMAT_EXTENSIBLE`, mmreg.h. В крейте константы нет.
/// Значение 0xFFFE, проверено поиском по `windows-0.62.2`.
///
/// Отдельной константы для `WAVE_FORMAT_IEEE_FLOAT` здесь нет
/// специально: в общем режиме формат смеси микрофону отдаётся
/// без изменений, и подменять метку нельзя — устройство отвечает
/// `E_INVALIDARG`. Проверено 16.10.2026.
const ФОРМАТ_РАСШИРЕННЫЙ: u16 = 0xFFFE;

/// `KSDATAFORMAT_SUBTYPE_PCM` байтами, как она лежит в памяти.
///
/// Windows всегда little-endian, поэтому GUID сравнивается напрямую,
/// шестнадцатью байтами, без сборки структуры: `GUID` в крейте
/// состоит из `u32`, `u16`, `u16` и восьми байт, и собирать её
/// ради одного сравнения — лишний код с местом для ошибки.
///
/// Порядок: `00000001-0000-0010-8000-00AA00389B71`.
const ПОДФОРМАТ_PCM: [u8; 16] = [
    0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x80, 0x00, 0x00, 0xAA, 0x00, 0x38, 0x9B, 0x71,
];

// --- ошибки ------------------------------------------------------------

fn ошибка(текст: impl Into<String>) -> String {
    format!("микрофон: {}", текст.into())
}

/// Текущая сессия записи. Одна за раз: две одновременные записи с
/// одного микрофона — это не «два раза лучше слышно», а ошибка
/// устройства.
static СЕССИЯ: Mutex<Option<Сессия>> = Mutex::new(None);

struct Сессия {
    остановить: Arc<AtomicBool>,
    поток: JoinHandle<Result<Vec<f32>, String>>,
}

/// Идёт ли запись. Интерфейсу нужно, чтобы показать «идёт».
pub fn идёт() -> bool {
    СЕССИЯ.lock().map(|s| s.is_some()).unwrap_or(false)
}

// --- пуск -------------------------------------------------------------

/// Начать запись.
///
/// `устройство` — идентификатор микрофона из настроек, `None` —
/// микрофон по умолчанию в Windows. Устройство ищется в момент
/// старта, а не заранее: человек мог переподключить микрофон, и
/// искать надо тогда, когда запись начинается.
pub fn начать(устройство: Option<String>) -> Result<(), String> {
    use windows::Win32::System::Com::{
        CoInitializeEx, CoUninitialize, COINIT_MULTITHREADED,
    };

    let mut слот = СЕССИЯ
        .lock()
        .map_err(|e| ошибка(format!("состояние занято: {e}")))?;
    if слот.is_some() {
        return Err(ошибка("запись уже идёт"));
    }

    // COM инициализируется на этом потоке и снимается в `остановить`,
    // когда сессия кончится. Счётчик в COM своя величина на поток,
    // поэтому поток захвата инициализирует его отдельно — и
    // снимает сам.
    let _ = unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) };

    let готово = match unsafe { подготовить(устройство.as_deref()) } {
        Ok(г) => г,
        Err(о) => {
            // Не снимать COM при ошибке нельзя: счётчик уедет и
            // следующая инициализация в этом потоке станет
            // непредсказуемой.
            unsafe { CoUninitialize() };
            return Err(о);
        }
    };

    let остановить = Arc::new(AtomicBool::new(false));
    let флаг = остановить.clone();
    let поток = std::thread::Builder::new()
        .name("микрофон".to_string())
        .spawn(move || unsafe { читать(готово, флаг) })
        .map_err(|e| {
            unsafe { CoUninitialize() };
            ошибка(format!("поток записи не начался: {e}"))
        })?;

    *слот = Some(Сессия {
        остановить,
        поток,
    });
    Ok(())
}

/// Остановить запись и отдать звук: моно, 16 кГц, f32.
///
/// Возвращает пустой вектор, если запись была короче пакета: это
/// бывает при очень коротком нажатии и это не ошибка, а пустой
/// результат.
pub fn остановить() -> Result<Vec<f32>, String> {
    use windows::Win32::System::Com::CoUninitialize;

    let mut слот = СЕССИЯ
        .lock()
        .map_err(|e| ошибка(format!("состояние занято: {e}")))?;
    let Some(сессия) = слот.take() else {
        return Err(ошибка("запись не идёт"));
    };

    // Сессия забирается целиком, а не читается по ссылке: `join`
    // забирает дескриптор потока, а он не копируется, и через ссылку
    // его не отдать. Побочный плюс: слот освобождается сразу, и
    // повторный вызов не увидит «идущей» уже остановленную запись.

    // Флаг ставится до ожидания потока. Обратный порядок означал бы,
    // что поток читает флаг только после уже случившегося ожидания,
    // то есть никогда.
    сессия.остановить.store(true, Ordering::SeqCst);
    // `join` возвращает `Result` внутри `Result`: внешний — про панику
    // в потоке, внутренний — про ошибку записи. Свёртка одним
    // `and_then`, иначе вложенность пришлось бы разбирать дважды.
    let результат = сессия
        .поток
        .join()
        .map_err(|_| ошибка("поток записи завершился неудачей"))
        .and_then(|внутри| внутри);

    // Освобождение устройства происходит в потоке, и оно может
    // занять время. Новая запись не начнётся раньше, чем закончится
    // текущая, и об этом сказано в ошибке, а не оставлено как
    // молчаливая задержка.
    unsafe { CoUninitialize() };
    результат
}

/// Бросить запись, ничего не возвращая.
pub fn отменить() {
    use windows::Win32::System::Com::CoUninitialize;
    if let Ok(mut слот) = СЕССИЯ.lock() {
        if let Some(сессия) = слот.take() {
            сессия.остановить.store(true, Ordering::SeqCst);
            let _ = сессия.поток.join();
            unsafe { CoUninitialize() };
        }
    }
}

// --- устройство --------------------------------------------------------

/// Открытое устройство, готовое к чтению.
struct Готово {
    клиент: windows::Win32::Media::Audio::IAudioClient,
    захват: windows::Win32::Media::Audio::IAudioCaptureClient,
    каналов: u16,
    частота: u32,
    бит: u16,
    /// `true`, когда данные приходят как `float`, а не как целые.
    плав: bool,
}

// Интерфейсы COM — это указатели, а не владение ресурсами
// Windows. Создаются они в одном потоке, читаются в другом, и это
// допустимо: COM-подъём здесь многопоточный, а поток захвата
// инициализирует COM сам. Без этой пометки компилятор откажется
// отправлять сессию в поток, и это правильно по общему правилу.
unsafe impl Send for Готово {}

/// Открыть устройство и привести клиента к готовому состоянию.
///
/// Общий режим обязателен: иначе микрофон занимается целиком и
/// человек не сможет пользоваться им вместе с нами.
unsafe fn подготовить(устройство: Option<&str>) -> Result<Готово, String> {
    use windows::Win32::Media::Audio::IMMDeviceEnumerator;
    use windows::Win32::System::Com::{CoCreateInstance, CLSCTX_ALL};

    let перечис: IMMDeviceEnumerator = CoCreateInstance(&CLSID_МИКРОФОН, None, CLSCTX_ALL)
        .map_err(|e| ошибка(format!("перечислитель устройств не создан: {e}")))?;

    // Устройства, которые попробуем по очереди.
    //
    // Слепо верить «микрофону по умолчанию» нельзя: на этой машине
    // среди прочих стоят виртуальные устройства, и устройство по
    // умолчанию может оказаться как раз таким — оно открывается,
    // но отвечает `AUDCLNT_E_DEVICE_INVALIDATED`, то есть
    // «устройство аннулировано». Проверено 16.10.2026.
    let mut кандидаты: Vec<windows::Win32::Media::Audio::IMMDevice> = Vec::new();

    if let Some(имя) = устройство {
        if !имя.is_empty() {
            let широкая = windows::core::HSTRING::from(имя);
            match перечис.GetDevice(&широкая) {
                Ok(d) => кандидаты.push(d),
                // Микрофон из настроек отключили. Молча падать
                // нельзя: человек ничего не менял, он думал, что
                // выбрал другое устройство.
                Err(_) => {
                    return Err(ошибка(format!("микрофон из настроек недоступен: {имя}")))
                }
            }
        }
    }

    // Даже если человек выбрал устройство, а оно не ожило, пробуем
    // остальные: запись лучше с чужого микрофона, чем никакая.
    if let Ok(список) = перечис.EnumAudioEndpoints(
        ЗАХВАТ,
        windows::Win32::Media::Audio::DEVICE_STATE_ACTIVE,
    ) {
        let количество = список.GetCount().unwrap_or(0);
        for n in 0..количество {
            if let Ok(d) = список.Item(n) {
                let уже_есть = кандидаты.iter().any(|к| {
                    к.GetId()
                        .map(|a| d.GetId().map(|b| a == b).unwrap_or(false))
                        .unwrap_or(false)
                });
                if !уже_есть {
                    кандидаты.push(d);
                }
            }
        }
    }

    // Микрофон по умолчанию идёт первым: человек его скорее всего
    // и хочет, а список активных может начинаться с чего угодно.
    if кандидаты.is_empty() {
        if let Ok(d) = перечис.GetDefaultAudioEndpoint(ЗАХВАТ, КОНСОЛЬ) {
            кандидаты.push(d);
        }
    }
    if кандидаты.is_empty() {
        return Err(ошибка("в системе нет ни одного микрофона"));
    }

    открыть_первый(&кандидаты)
}

/// Разобранный формат смеси: структура для `Initialize` плюс четыре
/// числа, из которых считается звук.

/// Причина отказа человеческим языком вместо кода.
///
/// Код `0x88890008` человеку ничего не говорит, а означает он одно:
/// устройство аннулировано. Такое бывает у виртуальных и отключённых
/// микрофонов, а без расшифровки человек читает ошибку как «программа
/// сломалась» и идёт чинить не то.
fn причина(ошибка: &windows::core::Error) -> String {
    match ошибка.code().0 as u32 {
        0x8889_0008 => "устройство аннулировано — виртуальный или отключённый микрофон".to_string(),
        0x8007_0057 => "параметр задан неверно".to_string(),
        0x8889_0004 => "устройство недоступно — оно выключено или занято другим".to_string(),
        _ => format!("{ошибка}"),
    }
}

/// Открыть первое устройство, которое встало.
///
/// Перебор, а не один вызов, потому что на машине человека могут
/// стоять виртуальные микрофоны — Steam, NVIDIA, мониторы с
/// микрофоном — и устройство по умолчанию вполне может оказаться
/// как раз таким. Проверено 16.10.2026: первый по умолчанию отвечает
/// `0x88890008`, и запись работает только после перебора.
unsafe fn открыть_первый(
    кандидаты: &[windows::Win32::Media::Audio::IMMDevice],
) -> Result<Готово, String> {
    use windows::Win32::Media::Audio::{IAudioCaptureClient, IAudioClient};
    use windows::Win32::System::Com::CLSCTX_ALL;

    let mut отказы = Vec::new();
    for устройство in кандидаты {
        let имя = устройство.GetId().ok().and_then(|и| и.to_string().ok());

        let клиент: Result<IAudioClient, _> = устройство.Activate(CLSCTX_ALL, None);
        let клиент = match клиент {
            Ok(к) => к,
            Err(о) => {
                отказы.push(format!("{}: {}", имя_для_человека(имя.as_deref()), причина(&о)));
                continue;
            }
        };

        let формат = match разобрать_формат(&клиент) {
            Ok(ф) => ф,
            Err(о) => {
                отказы.push(format!("{}: {о}", имя_для_человека(имя.as_deref())));
                continue;
            }
        };

        // Буфер в 100 мс — размер, который система сама предлагает
        // для микрофонов. Просить больше можно, но незачем: наш цикл
        // читает пакеты по мере появления, и большой буфер лишь добавит
        // задержку между нажатием клавиши и первым услышанным звуком.
        if let Err(о) = клиент.Initialize(
            windows::Win32::Media::Audio::AUDCLNT_SHAREMODE_SHARED,
            0,
            100_000_000i64,
            0,
            &формат.0,
            None,
        ) {
            отказы.push(format!("{}: {}", имя_для_человека(имя.as_deref()), причина(&о)));
            continue;
        }

        match клиент.GetService::<IAudioCaptureClient>() {
            Ok(захват) => {
                return Ok(Готово {
                    клиент,
                    захват,
                    каналов: формат.1,
                    частота: формат.2,
                    бит: формат.3,
                    плав: формат.4,
                })
            }
            Err(о) => отказы.push(format!("{}: {}", имя_для_человека(имя.as_deref()), причина(&о))),
        }
    }

    Err(ошибка(format!(
        "ни один микрофон не открылся: {}",
        if отказы.is_empty() {
            "список устройств пуст".to_string()
        } else {
            отказы.join("; ")
        }
    )))
}

/// Имя устройства для сообщения человеку.
///
/// Идентификатор вида `{0.0.1.00000000}.{ccc66bc4-...}` в ошибке
/// бесполезен: человек по нему ничего не найдёт. Поэтому в сообщение
/// идёт позиция в списке, а полный идентификатор остаётся в
/// настройках, где он нужен для выбора устройства.
fn имя_для_человека(идентификатор: Option<&str>) -> String {
    match идентификатор {
        Some(и) if !и.is_empty() => format!("микрофон {и}"),
        _ => "микрофон".to_string(),
    }
}

/// Разобранный формат смеси: структура для `Initialize` плюс четыре
/// числа, из которых считается звук.
type Разбор = (
    windows::Win32::Media::Audio::WAVEFORMATEX,
    u16,
    u32,
    u16,
    bool,
);

/// Разобрать смешанный формат устройства.
///
/// Смесь приходит как `WAVEFORMATEXTENSIBLE` — расширение обычной
/// структуры с указателем на подформат. Без разбора расширения
/// определить, `float` это или целые числа, нечем, и звук вышел бы
/// шумом. Это отмечено и у источника, откуда взят подход.
unsafe fn разобрать_формат(клиент: &windows::Win32::Media::Audio::IAudioClient) -> Result<Разбор, String> {
    use windows::Win32::Media::Audio::WAVEFORMATEX;

    let указатель = клиент
        .GetMixFormat()
        .map_err(|e| ошибка(format!("формат смеси недоступен: {e}")))?;
    if указатель.is_null() {
        return Err(ошибка("формат смеси пуст"));
    }

    // `wav` дальше не меняется: структура уходит в `Initialize` ровно
    // такой, какой её вернул `GetMixFormat`. Отсюда и отсутствие
    // `mut` — метку формата подменять здесь нельзя, устройство на
    // подмену отвечает `E_INVALIDARG`.
    let wav: WAVEFORMATEX = *указатель;
    let mut плав = wav.wFormatTag != windows::Win32::Media::Audio::WAVE_FORMAT_PCM as u16;

    if wav.wFormatTag == ФОРМАТ_РАСШИРЕННЫЙ {
        // Смещение до `SubFormat` считается руками, и это не
        // перестраховка, а необходимость:
        //
        //   * `WAVEFORMATEXTENSIBLE` в крейте объявлен
        //     `#[repr(C, packed(1))]`, поэтому его поля стоят без
        //     выравнивания, и брать ссылку на `SubFormat` нельзя —
        //     компилятор правомерно роняет программу на
        //     невыровненном адресе;
        //   * `size_of::<WAVEFORMATEX>()` даёт 20, а в C структура
        //     занимает 18: четыре байта добираются выравниванием под
        //     `u32`, которого в настоящем формате нет.
        //
        // Считаем по-настоящему: 18 базовых + 2 объединение Samples
        // + 4 маска каналов = 24.
        const СМЕЩЕНИЕ_ПОДФОРМАТА: usize = 18 + 2 + 4;

        let начало = (указатель as *const u8).add(СМЕЩЕНИЕ_ПОДФОРМАТА);
        // Чтение идёт байтами: `GUID` требует выравнивания, а память
        // под ним упакована.
        let mut байты = [0u8; 16];
        std::ptr::copy_nonoverlapping(начало, байты.as_mut_ptr(), 16);

        плав = байты != ПОДФОРМАТ_PCM;
        // `wav` здесь намеренно не трогаем. В общем режиме микрофону
        // отдают формат смеси ровно таким, каким его вернул
        // `GetMixFormat`. Подмена `wFormatTag` на `IEEE_FLOAT` или
        // `PCM` выглядит логично, но устройство проверяет исходную
        // структуру и отвечает `E_INVALIDARG`, то есть «параметр
        // задан неверно». Проверено 16.10.2026.
    }

    Ok((
        wav,
        wav.nChannels,
        wav.nSamplesPerSec,
        wav.wBitsPerSample,
        плав,
    ))
}

// --- чтение ------------------------------------------------------------

/// Горячий цикл: читать пакеты, пока не попросили остановиться.
unsafe fn читать(готово: Готово, остановить: Arc<AtomicBool>) -> Result<Vec<f32>, String> {
    use windows::Win32::System::Com::{CoInitializeEx, CoUninitialize, COINIT_MULTITHREADED};

    let _ = CoInitializeEx(None, COINIT_MULTITHREADED);

    let итог = цикл(&готово, &остановить);

    let _ = готово.клиент.Stop();
    CoUninitialize();
    итог
}

/// Сам цикл без учёта COM: так его видно целиком на одном экране.
unsafe fn цикл(готово: &Готово, остановить: &Arc<AtomicBool>) -> Result<Vec<f32>, String> {
    готово
        .клиент
        .Start()
        .map_err(|e| ошибка(format!("поток микрофона не запущен: {e}")))?;

    let предел = ((готово.частота as u64) * (МАКСИМУМ.as_secs_f64().round() as u64)
        * (готово.каналов as u64)
        * ((готово.бит as u64) / 8)) as usize;
    let mut накопитель: Vec<u8> = Vec::with_capacity(16000 * 4);

    while !остановить.load(Ordering::SeqCst) {
        let пакет = готово
            .захват
            .GetNextPacketSize()
            .map_err(|e| ошибка(format!("размер следующего пакета недоступен: {e}")))?;

        if пакет == 0 {
            // Пакеты приходят примерно по 10 мс. Если не ждать вовсе,
            // цикл блокируется на каждом пакете и буфер переполняется;
            // если ждать дольше нужного, он жжёт ядро. Пять
            // миллисекунд — середина между «не успел» и «кручусь».
            std::thread::sleep(std::time::Duration::from_millis(5));
            continue;
        }

        let mut данные: *mut u8 = std::ptr::null_mut();
        let mut кадров: u32 = 0;
        let mut флагов: u32 = 0;
        let получен = готово.захват.GetBuffer(
            &mut данные,
            &mut кадров,
            &mut флагов,
            // Позиции нас не интересуют: нужны только байты звука.
            None,
            None,
        );
        if получен.is_err() {
            return Err(ошибка("буфер захвата не отдан"));
        }

        // Проверка на предел идёт до копирования, а не после:
        // иначе на пределе данные копировались бы и выбрасывались.
        let байт_на_кадр = (готово.каналов as usize) * ((готово.бит as usize) / 8);
        let нужно = (кадров as usize) * байт_на_кадр;
        if !данные.is_null() && нужно > 0 && накопитель.len() + нужно <= предел {
            let кусок = std::slice::from_raw_parts(данные as *const u8, нужно);
            накопитель.extend_from_slice(кусок);
        }

        let _ = готово.захват.ReleaseBuffer(кадров);
    }

    в_моно_16к(
        &накопитель,
        готово.каналов,
        готово.частота,
        готово.бит,
        готово.плав,
    )
}

// --- приведение к моно 16 кГц ----------------------------------------

/// Байты устройства → моно, 16 кГц, f32.
///
/// Порядок обязателен: сначала моно, потом пересчёт. Если сначала
/// пересчитать, а потом свести каналы, каналы считаются уже с разной
/// частотой и сведение даёт расстройку.
pub fn в_моно_16к(
    байты: &[u8],
    каналов: u16,
    частота: u32,
    бит: u16,
    плав: bool,
) -> Result<Vec<f32>, String> {
    if байты.is_empty() {
        return Ok(Vec::new());
    }
    if каналов == 0 || частота == 0 || бит == 0 {
        return Err(ошибка("устройство сообщило нулевые каналы, частоту или разрядность"));
    }

    let шаг = (бит as usize / 8) * (каналов as usize);
    if шаг == 0 {
        return Err(ошибка("разрядность меньше байта"));
    }
    let образцов = байты.len() / шаг;
    let mut моно = Vec::with_capacity(образцов);

    for n in 0..образцов {
        let начало = n * шаг;
        let mut сумма = 0.0f32;
        for канал in 0..каналов as usize {
            сумма += прочитать_образец(&байты[начало + канал * (бит as usize / 8)..], бит, плав);
        }
        моно.push(сумма / каналов as f32);
    }

    if частота == ЧАСТОТА {
        return Ok(моно);
    }
    Ok(пересчитать_из(&моно, частота, ЧАСТОТА))
}

/// Один образец из двух или четырёх байт.
fn прочитать_образец(байты: &[u8], бит: u16, плав: bool) -> f32 {
    match (бит, плав) {
        (16, true) => f32::from_bits(u16::from_le_bytes([байты[0], байты[1]]) as u32),
        (32, true) => f32::from_le_bytes([байты[0], байты[1], байты[2], байты[3]]),
        (16, false) => i16::from_le_bytes([байты[0], байты[1]]) as f32 / 32768.0,
        (32, false) => {
            i32::from_le_bytes([байты[0], байты[1], байты[2], байты[3]]) as f32 / 2147483648.0
        }
        _ => 0.0,
    }
}

/// Пересчёт из известной частоты в известную.
///
/// В отличие от `vad::пересчитать`, здесь известно, откуда и куда.
/// Та функция считает, что исходник уже 16 кГц, и потому в опыте
/// 15.10 превратилась в пустую операцию: 61 440 образцов на входе,
/// столько же на выходе.
///
/// Пока это линейная интерполяция, и это осознанный долг, а не
/// решение: на линейной интерполяции верхний спектр складывается
/// обратно в голос, и фильтр нужен. Настоящий ресемплер — работа
/// отдельная.
pub fn пересчитать_из(образцы: &[f32], из: u32, в: u32) -> Vec<f32> {
    if из == в || образцы.is_empty() {
        return образцы.to_vec();
    }
    // Отношение для позиции и для длины — разные, и путать их
    // дорого: на 48 кГц → 16 кГц длина выходила в 143 998 образцов
    // вместо 16 000, то есть в девять раз больше нужного.
    // Позиция идёт по исходнику с шагом `из / в`, а длина считается
    // по исходнику, делённому на тот же шаг.
    let шаг = из as f64 / в as f64;
    let сколько = ((образцы.len() as f64) / шаг).round() as usize;
    let последний = образцы.len() - 1;
    let mut выход = Vec::with_capacity(сколько);
    for n in 0..сколько {
        let позиция = n as f64 * шаг;
        let целая_позиция = позиция.floor();
        let целая = (целая_позиция as usize).min(последний);
        let дробная = (позиция - целая_позиция) as f32;
        let левый = образцы[целая];
        let правый = образцы[(целая + 1).min(последний)];
        выход.push(левый + (правый - левый) * дробная);
    }
    выход
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Пустой звук даёт пустой результат, а не ошибку.
    #[test]
    fn пустой_звук_даёт_пустой_результат() {
        assert!(в_моно_16к(&[], 2, 48_000, 16, true).unwrap().is_empty());
    }

    /// Два канала среднего равны одному каналу того же среднего.
    ///
    /// Проверка сведения каналов на равномерном сигнале: если
    /// каналы считаются неверно, среднее уедет.
    #[test]
    fn два_канала_сводятся_к_одному() {
        let mut байты = Vec::new();
        for _ in 0..8 {
            байты.extend_from_slice(&1000i16.to_le_bytes());
            байты.extend_from_slice(&3000i16.to_le_bytes());
        }
        let моно = в_моно_16к(&байты, 2, 16_000, 16, false).unwrap();
        assert_eq!(моно.len(), 8);
        let ожидаемое = 2000.0 / 32768.0;
        for v in &моно {
            assert!((v - ожидаемое).abs() < 1e-6, "{v} против {ожидаемое}");
        }
    }

    /// Пересчёт вниз даёт ожидаемое число образцов.
    #[test]
    fn пересчёт_вниз_меняет_длину() {
        let образцы: Vec<f32> = (0..48_000).map(|i| (i % 100) as f32 / 100.0).collect();
        assert_eq!(пересчитать_из(&образцы, 48_000, 16_000).len(), 16_000);
    }

    /// Пересчёт вверх тоже даёт ожидаемое число образцов.
    #[test]
    fn пересчёт_вверх_меняет_длину() {
        let образцы: Vec<f32> = (0..8_000).map(|i| (i % 50) as f32 / 50.0).collect();
        assert_eq!(пересчитать_из(&образцы, 8_000, 16_000).len(), 16_000);
    }

    /// Одинаковые частоты не трогают сигнал.
    ///
    /// Отдельно, потому что это самый частый вызов на машине, где
    /// устройство уже отдаёт 16 кГц, и лишний проход по звуку там
    /// только портит его.
    #[test]
    fn та_же_частота_возвращает_тот_же_звук() {
        let образцы = vec![0.1f32, -0.2, 0.3, 0.0];
        assert_eq!(пересчитать_из(&образцы, 16_000, 16_000), образцы);
    }

    /// Пересчёт не теряет последний кадр.
    ///
    /// Длина считается от «последний индекс минус один», иначе на
    /// ровном делении выход обрезался бы на один образец и конец
    /// фразы пропадал бы.
    #[test]
    fn пересчёт_не_теряет_хвост() {
        let образцы: Vec<f32> = (0..480).map(|i| i as f32).collect();
        assert_eq!(пересчитать_из(&образцы, 48_000, 16_000).len(), 160);
    }

    /// Сигнал постоянной частоты не должен обращаться в мусор.
    ///
    /// Самая частая беда дешёвого пересчёта: на синусе интерполяция
    /// даёт ровную синусоиду, а вот на прямоугольных фронтах
    /// рассыпается. Проверяем на прямоугольном.
    #[test]
    fn пересчёт_не_рассыпает_фронты() {
        let образцы: Vec<f32> = (0..4_800)
            .map(|i| if (i / 100) % 2 == 0 { 1.0 } else { -1.0 })
            .collect();
        let выход = пересчитать_из(&образцы, 48_000, 16_000);
        assert_eq!(выход.len(), 1_600);
        // Значения остаются в пределах исходных плюс-минус один:
        // интерполяция между соседями не выходит за их пределы.
        for v in &выход {
            assert!(v.abs() <= 1.0001, "вне диапазона: {v}");
        }
    }

    /// Запись с настоящего микрофона.
    ///
    /// Тест помечен `#[ignore]`, потому что он зависит от машины: на
    /// чужом компьютере микрофона может не быть, а на этом — может
    /// не оказаться того, которым человек пользуется. В общий набор
    /// он не входит и время сборки не ест.
    ///
    /// Что он проверяет и почему это стоит держать: всё, что можно
    /// сломать между `начать` и `остановить`, не видно в остальных
    /// тестах. За полгода работы модуля здесь ломалось трижды подряд —
    /// невыровненное чтение `SubFormat` роняло процесс, подмена
    /// метки формата давала `E_INVALIDARG`, а микрофон по умолчанию
    /// оказался виртуальным и отвечал «устройство аннулировано».
    /// Ни одно из этих трёх не поймал бы обычный прогон тестов.
    ///
    /// Запуск: `cargo test --manifest-path src-tauri/Cargo.toml --lib \
    ///   запись_с_настоящего_микрофона -- --ignored --nocapture`
    #[test]
    #[ignore = "нужен настоящий микрофон"]
    fn запись_с_настоящего_микрофона() {
        let сколько_секунд = 3;

        начать(None).expect("микрофон не открылся");

        assert!(идёт(), "запись началась, а `идёт` говорит об обратном");

        std::thread::sleep(std::time::Duration::from_secs(сколько_секунд));

        let звук = остановить().expect("запись не остановилась");

        assert!(!идёт(), "запись кончилась, а `идёт` говорит об обратном");

        // Три секунды дают примерно 48 000 образцов. Проверяем с
        // запасом: точное число зависит от того, как устройство
        // нарезает пакеты, и от того, успел ли человек отпустить
        // клавишу.
        let ожидалось = сколько_секунд as usize * ЧАСТОТА as usize;
        let получено = звук.len();
        assert!(
            получено > ожидалось / 2 && получено < ожидалось * 2,
            "за {сколько_секунд} секунд ожидалось около {ожидалось} образцов, получено {получено}"
        );

        // Значения обязаны лежать в пределах ±1. Выход за них означает
        // не «громко», а «формат прочитан неверно» — например, целые
        // числа, прочитанные как `float`.
        let максимум = звук.iter().cloned().fold(0.0f32, f32::max);
        let минимум = звук.iter().cloned().fold(0.0f32, f32::min);
        assert!(
            максимум <= 1.0 && минимум >= -1.0,
            "значения вне ±1: от {минимум} до {максимум} — формат прочитан неверно"
        );

        // Известная беда WASAPI: вторую запись сразу после первой
        // начать нельзя, пока устройство не освободилось. Наша
        // остановка ждёт поток, поэтому повтор обязан пройти.
        начать(None).expect("повторный старт не удался");
        std::thread::sleep(std::time::Duration::from_millis(300));
        остановить().expect("повторная остановка не удалась");
    }
}
