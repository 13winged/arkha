// --- диктовка по клавише ----------------------------------------------

/// Что получилось из записи.
#[derive(Debug, Clone, Serialize)]
pub struct Диктовка {
    /// Распознанный текст. Пустая строка означает «запись была, но
    /// слов в ней не разобрали» — это не ошибка, а результат.
    pub текст: String,
    /// Секунд записано. Отдаётся отдельно, потому что человек
    /// должен видеть, что его услышали, даже если слов не
    /// разобрали: молчание иначе неотличимо от поломки.
    pub секунд: f32,
    /// Говорил ли человек. Отличается от «текст пуст» тем, что
    /// при тишине в микрофоне распознавание всё равно что-то
    /// вернёт.
    pub был_звук: bool,
}

/// Команда: начать запись по нажатию клавиши.
///
/// Клавиша ловит хук, а не интерфейс: запись должна идти, когда
/// человек говорит в другое окно. Эта команда нужна для проверки
/// вручную и для интерфейса, который сам хочет управлять записью.
#[tauri::command]
pub fn voice_record_start() -> Result<(), ГолосОшибка> {
    record::начать(микрофон_из_настроек()).map_err(ошибка)
}

/// Команда: остановить запись, распознать и вернуть текст.
#[tauri::command]
pub fn voice_record_stop(г: tauri::State<'_, Голос>) -> Result<Диктовка, ГолосОшибка> {
    let звук = record::остановить().map_err(ошибка)?;
    разобрать_запись(&г, звук)
}

/// Команда: включить запись по клавише.
///
/// После вызова хук живёт до конца процесса, и нажатие клавиши
/// само начинает и кончает запись. Второй вызов ничего не
/// делает: хук глобальный, второй поверх первого только замедлит
/// машину.
#[tauri::command]
pub fn voice_hotkey_enable(
    app: tauri::AppHandle,
    г: tauri::State<'_, Голос>,
) -> Result<String, ГолосОшибка> {
    let канал = hotkey::поставить().map_err(ошибка)?;

    std::thread::Builder::new()
        .name("диктовка".to_string())
        .spawn(move || слушать_клавишу(канал, app))
        .map_err(|e| ошибка(format!("поток диктовки не начался: {e}")))?;

    Ok(hotkey::комбинация().to_string())
}

/// Событие, которое уходит в интерфейс после распознавания.
pub const СОБЫТИЕ_ДИКТОВКИ: &str = "голос-диктовка";

/// Читать события хука и вести запись.
///
/// Здесь весь смысл клавиши: нажатие начинает запись, отпускание
/// останавливает и распознаёт. Результат уходит событием, потому
/// что человек говорит в другое окно и ждёт ответа там же.
///
/// Поток отдельный от хука: хук не имеет права ждать, пока идёт
/// распознавание. Задержка в хуке видна всему компьютеру как
/// подвисание ввода, и страдает даже то, что человек печатает в
/// этот момент в другой программе.
fn слушать_клавишу(
    канал: std::sync::mpsc::Receiver<hotkey::Событие>,
    app: tauri::AppHandle,
) {
    use tauri::{Emitter, Manager};

    // Состояние берётся внутри потока, а не передаётся в него.
    // Ссылка из команды живёт до конца вызова команды и в поток не
    // уезжает; `AppHandle` живёт до конца приложения, поэтому берём
    // состояние уже на месте.
    let г = app.state::<Голос>();

    // Приложение закрылось — канал закрылся, и цикл заканчивается
    // сам. Отдельного признака остановки не нужно.
    for событие in канал {
        match событие {
            hotkey::Событие::Нажата => {
                if let Err(о) = record::начать(микрофон_из_настроек()) {
                    // Ошибку отправляем, а не молчим: человек
                    // нажал и ждёт, а молчание он прочтёт как
                    // поломку микрофона.
                    let _ = app.emit(
                        СОБЫТИЕ_ДИКТОВКИ,
                        Диктовка { текст: о, секунд: 0.0, был_звук: false },
                    );
                }
            }
            hotkey::Событие::Отпущена => {
                let звук = match record::остановить() {
                    Ok(з) => з,
                    Err(о) => {
                        let _ = app.emit(
                            СОБЫТИЕ_ДИКТОВКИ,
                            Диктовка { текст: о, секунд: 0.0, был_звук: false },
                        );
                        continue;
                    }
                };
                let итог = match разобрать_запись(&г, звук) {
                    Ok(и) => и,
                    Err(о) => Диктовка { текст: о, секунд: 0.0, был_звук: false },
                };
                let _ = app.emit(СОБЫТИЕ_ДИКТОВКИ, итог);
            }
        }
    }
}

