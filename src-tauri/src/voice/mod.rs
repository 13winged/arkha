// Голос: синтез и распознавание, по вызову человека.
//
// Почему голос включается вручную, а не всегда. Три модели на
// восьмигигабайтной карте не помещаются: замер показывает, что при
// поднятом распознавании агент сваливается в разделяемую память уже
// на 16 слоях, а без него спокойно работает на 24. Человек включает
// голос тогда, когда он заговорил, и выключает, когда замолчал. Всё
// остальное время эти 143 МиБ на процессе и слот на порту просто не
// заняты.
//
// Что здесь есть сейчас: включение, выключение, синтез текста,
// распознавание файла. Чего нет: запись с микрофона и живой диалог —
// это следующий шаг, и он не должен был тянуть за собой проверку
// того, что распознавание вообще работает.

pub mod stt;
pub mod tts;

use std::path::{Path, PathBuf};
use std::process::Child;
use std::sync::atomic::{AtomicU32, Ordering};
use std::sync::Mutex;

use serde::Serialize;

/// Ошибка голоса. Отдельный тип, чтобы интерфейс отличал «не
/// получилось» от «получилось, но человек этого ещё не разрешал».
pub type ГолосОшибка = String;

/// Обёртка над ошибкой. Существует ради читаемости: `Err(ошибка(..))`
/// читается как «ошибка» в сигнатуре, а `Err(String)` — как строка,
/// и разница теряется.
pub fn ошибка(сообщение: impl Into<String>) -> ГолосОшибка {
    сообщение.into()
}

/// Состояние голоса: поднято ли распознавание.
///
/// Имена полей латиницей, как во всех остальных структурах, что
/// уходят в интерфейс. Не из вкуса, а из-за serde: `rename_all =
/// "camelCase"` переводит кириллицу по байтам и падает на границе
/// символа — проверено, макрос падает при компиляции.
#[derive(Debug, Clone, Serialize)]
pub struct ГолосСостояние {
    /// Голос включён человеком.
    pub on: bool,
    /// Распознавание реально отвечает. Отличается от `on`:
    /// человек мог нажать, а сервер не поднялся.
    pub listening: bool,
    /// Сколько мегабайт занимает включённый голос. Известно только
    /// после включения: пока голос выключен, он не занимает ничего.
    pub weight_mb: Option<u64>,
}

/// Общее состояние голоса на всё приложение.
pub struct Голос {
    /// Поднятый сервер распознавания, если он есть.
    процесс: Mutex<Option<Child>>,
    /// Счётчик имён для временных файлов: два ответа подряд не
    /// должны делить один файл.
    счётчик: AtomicU32,
}

impl Голос {
    pub fn новый() -> Self {
        Self { процесс: Mutex::new(None), счётчик: AtomicU32::new(0) }
    }

    /// Следующий номер временного файла.
    pub fn счётчик_следующий(&self) -> u32 {
        self.счётчик.fetch_add(1, Ordering::SeqCst)
    }

    /// Путь к исполняемому файлу движка.
    pub fn путь_к(&self, имя: &str) -> Result<PathBuf, ГолосОшибка> {
        let путь = crate::model_manager::bin_dir().join("llama").join(имя);
        if путь.exists() {
            Ok(путь)
        } else {
            Err(ошибка(format!(
                "нет файла движка {имя}.\n  искали: {}\n  положи его через знакомство",
                путь.display()
            )))
        }
    }

    /// Путь к файлу модели.
    pub fn модель(&self, имя: &str) -> Result<PathBuf, ГолосОшибка> {
        let путь = crate::model_manager::models_dir().join(имя);
        if путь.exists() {
            Ok(путь)
        } else {
            Err(ошибка(format!(
                "нет модели {имя}.\n  папка моделей: {}",
                crate::model_manager::models_dir().display()
            )))
        }
    }

    /// Поднят ли сервер распознавания.
    pub fn поднят(&self) -> bool {
        matches!(self.процесс.lock().ok().map(|з| з.is_some()), Some(true))
    }

    pub fn сохранить_процесс(&self, ребёнок: Child) {
        if let Ok(mut з) = self.процесс.lock() {
            *з = Some(ребёнок);
        }
    }

    pub fn забрать_процесс(&self) -> Option<Child> {
        // `take` внутри `and_then` вернул бы ссылку на локальную
        // блокировку: замок живёт только до конца замыкания, и
        // компилятор это справедливо отвергает.
        let mut з = self.процесс.lock().ok()?;
        з.take()
    }

    /// Что сейчас с голосом, для интерфейса.
    pub fn состояние(&self) -> ГолосСостояние {
        let поднят = self.поднят();
        ГолосСостояние {
            on: поднят,
            listening: поднят,
            // Пока голос выключен, он не занимает ничего: это и
            // есть смысл включать его вручную.
            weight_mb: поднят.then_some(143),
        }
    }
}

impl Default for Голос {
    fn default() -> Self {
        Self::новый()
    }
}

/// Команда: что с голосом.
#[tauri::command]
pub fn voice_status(г: tauri::State<'_, Голос>) -> ГолосСостояние {
    г.состояние()
}

/// Команда: включить голос.
///
/// Голос включается по нажатию человека, и это единственный вход.
#[tauri::command]
pub fn voice_enable(г: tauri::State<'_, Голос>) -> Result<ГолосСостояние, ГолосОшибка> {
    stt::включить(&г)?;
    Ok(г.состояние())
}

/// Команда: выключить голос и освободить место.
#[tauri::command]
pub fn voice_disable(г: tauri::State<'_, Голос>) -> ГолосСостояние {
    stt::выключить(&г);
    г.состояние()
}

/// Команда: произнести текст.
#[derive(Serialize)]
pub struct Сказано {
    /// Куда записан звук.
    pub path: String,
    /// Размер файла в мегабайтах.
    pub mb: f64,
}

#[tauri::command]
pub fn voice_say(г: tauri::State<'_, Голос>, текст: String) -> Result<Сказано, ГолосОшибка> {
    let (путь, размер) = tts::синтез(&г, &текст)?;
    Ok(Сказано {
        path: путь.to_string_lossy().to_string(),
        mb: (размер as f64 / (1024.0 * 1024.0) * 100.0).round() / 100.0,
    })
}

/// Команда: распознать записанный звук.
#[tauri::command]
pub fn voice_hear(г: tauri::State<'_, Голос>, путь: String) -> Result<String, ГолосОшибка> {
    stt::распознать(&г, Path::new(&путь))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Выключенный голос не занимает ничего — в этом весь смысл
    /// ручного включения. Тест ловит возврат к «всегда включено».
    #[test]
    fn выключенный_голос_ничего_не_занимает() {
        let с = Голос::новый().состояние();
        assert!(!с.on);
        assert_eq!(с.weight_mb, None, "выключенный голос не должен весить ничего");
    }

    /// Ошибка обязана называть папку, где искали модель.
    /// «Файл не найден» без пути — это просьба догадаться.
    #[test]
    fn отсутствие_модели_называет_папку() {
        let г = Голос::новый();
        let e = г.модель("нет-такой-модели.gguf").unwrap_err();
        assert!(e.contains("папка моделей"), "{e}");
    }

    /// Ошибка движка обязана называть, где искали.
    #[test]
    fn отсутствие_движка_называет_путь() {
        let г = Голос::новый();
        let e = г.путь_к("нет-такого-движка.exe").unwrap_err();
        assert!(e.contains("искали"), "{e}");
    }
}