/// Команда: сохранить выбор звука.
///
/// Выбранное проверяется по списку устройств, а не принимается на
/// слово: человек мог отключить микрофон после того, как выбрал
/// его, и тогда настройка молча указывала бы в никуда.
#[tauri::command]
pub fn voice_audio_set(микрофон: Option<String>, вывод: Option<String>, горячая_клавиша: Option<String>) -> Result<devices::Аудио, ГолосОшибка> {
    let выбор = devices::Аудио { микрофон, вывод, горячая_клавиша };

    if let (Some(имя), Ok(доступные)) = (&выбор.микрофон, devices::микрофоны()) {
        if !доступные.iter().any(|у| &у.id == имя) {
            return Err(ошибка(format!("микрофон «{имя}» больше недоступен")));
        }
    }
    if let (Some(имя), Ok(доступные)) = (&выбор.вывод, devices::выводы()) {
        if !доступные.iter().any(|у| &у.id == имя) {
            return Err(ошибка(format!("устройство вывода «{имя}» больше недоступно")));
        }
    }
    if let Some(сочетание) = &выбор.горячая_клавиша {
        hotkey::сменить(сочетание).map_err(ошибка)?;
    }

    devices::сохранить(&выбор).map_err(ошибка)?;
    Ok(выбор)
}

/// Каким микрофоном писать: тот, что выбрал человек.
///
/// Микрофон — настройка человека, и молча взять другой значило бы
/// писать не туда, куда он думает. Если файла настроек нет, берётся
/// микрофон по умолчанию в Windows.
fn микрофон_из_настроек() -> Option<String> {
    devices::выбранный_микрофон()
}

/// Разобрать записанный звук и вернуть текст.
fn разобрать_запись(г: &Голос, звук: Vec<f32>) -> Result<Диктовка, ГолосОшибка> {
    let секунд = звук.len() as f32 / record::ЧАСТОТА as f32;

    // Звука нет вовсе. Это не ошибка: человек нажал и сразу
    // отпустил клавишу, или микрофон молчит. Распознавать нечего,
    // и звать ради этого движок дорого.
    if звук.is_empty() {
        return Ok(Диктовка { текст: String::new(), секунд, был_звук: false });
    }

    // Был ли вообще звук. Порог низкий и осознанный: тишина комнаты
    // даёт среднеквадратное около 0.00005, а речь — единицы. Число
    // взято с замера тишины комнаты на этой машине.
    let сумма: f64 = звук.iter().map(|с| (*с as f64) * (*с as f64)).sum();
    let среднеквадратное = (сумма / звук.len() as f64).sqrt();
    let был_звук = среднеквадратное > 0.002;

    if !был_звук {
        return Ok(Диктовка { текст: String::new(), секунд, был_звук: false });
    }

    // Запись уходит во временный файл, потому что распознавание
    // читает файл. Имя собирается из счётчика, чтобы два ответа
    // подряд не делили один путь.
    let имя = format!("arkha-dict-{}", г.счётчик_следующий());
    let путь = std::env::temp_dir().join(имя).with_extension("wav");
    record::записать_wav(&путь, &звук).map_err(ошибка)?;

    let итог = stt::распознать(г, &путь);
    // Временный файл убирается в любом случае: распознавание
    // могло упасть, а мусор в `%TEMP%` копится незаметно.
    let _ = std::fs::remove_file(&путь);

    Ok(Диктовка { текст: итог?, секунд, был_звук: true })
}

