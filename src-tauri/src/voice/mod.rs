/// Команда: произнести текст.
#[derive(Serialize)]
pub struct Сказано {
    /// Куда записан звук.
    pub path: String,
    /// Размер файла в мегабайтах.
    pub mb: f64,
    /// На чём сыграно. Пусто, если не игралось: файл создан, но
    /// звук не отдан. Различать надо, потому что «создал файл» и
    /// «заговорил» — разные вещи, и человек должен знать, какая
    /// вышла.
    pub сказано: Option<play::Сыграно>,
}

#[tauri::command]
pub fn voice_say(г: tauri::State<'_, Голос>, текст: String) -> Result<Сказано, ГолосОшибка> {
    let (путь, размер) = tts::синтез(&г, &текст)?;

    // Голос играется сразу, на устройстве, которое назвал
    // человек. Раньше синтез только писал файл, и звука не было
    // вовсе: файл возвращался, а играть его было некому.
    //
    // Ошибка воспроизведения файл не отменяет: файл на диске, и
    // человек может послушать его сам. Поэтому ошибка уходит в
    // `сказано` как отсутствие, а не как отказ всей команды.
    let сказано = play::сыграть_файл(&путь, devices::выбранный_вывод()).ok();

    Ok(Сказано {
        path: путь.to_string_lossy().to_string(),
        mb: (размер as f64 / (1024.0 * 1024.0) * 100.0).round() / 100.0,
        сказано,
    })
}

