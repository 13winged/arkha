// Голос: синтез и распознавание, по вызову человека.
//
// Почему голос включается вручную, а не всегда. Три модели на
// восьмигигабайтной карте не помещаются: замер показывает, что при
// поднятом распознавании агент сваливается в разделяемую память уже
// на 16 слоях, а без него спокойно работает на 24. Человек включает
// голос тогда, когда он заговорил, и выключает, когда замолчал. Всё
// остальное время эти 143 МиБ на процессе и слот на порту просто не
// заняты.
//
// Что здесь есть сейчас: включение, выключение, синтез текста,
// распознавание файла. Чего нет: запись с микрофона и живой диалог —
// это следующий шаг, и он не должен был тянуть за собой проверку
// того, что распознавание вообще работает.

pub mod stt;
pub mod tts;
