use std::path::{Path, PathBuf};
use std::process::Child;
use std::sync::atomic::{AtomicU32, Ordering};
use std::sync::Mutex;

use serde::Serialize;

/// Ошибка голоса. Отдельный тип, чтобы интерфейс отличал «не
/// получилось» от «получилось, но человек этого ещё не разрешал».
pub type ГолосОшибка = String;

/// Обёртка над ошибкой. Существует ради читаемости: `Err(ошибка(..))`
/// читается как «ошибка» в сигнатуре, а `Err(String)` — как строка,
/// и разница теряется.
pub fn ошибка(сообщение: impl Into<String>) -> ГолосОшибка {
    сообщение.into()
}

/// Состояние голоса: поднято ли распознавание.
///
/// Имена полей латиницей, как во всех остальных структурах, что
/// уходят в интерфейс. Не из вкуса, а из-за serde: `rename_all =
/// "camelCase"` переводит кириллицу по байтам и падает на границе
/// символа — проверено, макрос падает при компиляции.
#[derive(Debug, Clone, Serialize)]
pub struct ГолосСостояние {
    /// Голос включён человеком.
    pub on: bool,
    /// Распознавание реально отвечает. Отличается от `on`:
    /// человек мог нажать, а сервер не поднялся.
    pub listening: bool,
    /// Сколько мегабайт занимает включённый голос. Известно только
    /// после включения: пока голос выключен, он не занимает ничего.
    pub weight_mb: Option<u64>,
}

/// Общее состояние голоса на всё приложение.
pub struct Голос {
    /// Поднятый сервер распознавания, если он есть.
    процесс: Mutex<Option<Child>>,
    /// Счётчик имён для временных файлов: два ответа подряд не
    /// должны делить один файл.
    счётчик: AtomicU32,
}

impl Голос {
    pub fn новый() -> Self {
        Self { процесс: Mutex::new(None), счётчик: AtomicU32::new(0) }
    }

    /// Следующий номер временного файла.
    pub fn счётчик_следующий(&self) -> u32 {
        self.счётчик.fetch_add(1, Ordering::SeqCst)
    }

    /// Путь к исполняемому файлу движка.
    pub fn путь_к(&self, имя: &str) -> Result<PathBuf, ГолосОшибка> {
        let путь = crate::model_manager::bin_dir().join("llama").join(имя);
        if путь.exists() {
            Ok(путь)
        } else {
            Err(ошибка(format!(
                "нет файла движка {имя}.\n  искали: {}\n  положи его через знакомство",
                путь.display()
            )))
        }
    }

    /// Путь к файлу модели.
    pub fn модель(&self, имя: &str) -> Result<PathBuf, ГолосОшибка> {
        let путь = crate::model_manager::models_dir().join(имя);
        if путь.exists() {
            Ok(путь)
        } else {
            Err(ошибка(format!(
                "нет модели {имя}.\n  папка моделей: {}",
                crate::model_manager::models_dir().display()
            )))
        }
    }

    /// Поднят ли сервер распознавания.
    pub fn поднят(&self) -> bool {
        matches!(self.процесс.lock().ok().map(|з| з.is_some()), Some(true))
    }

    pub fn сохранить_процесс(&self, ребёнок: Child) {
        if let Ok(mut з) = self.процесс.lock() {
            *з = Some(ребёнок);
        }
    }

    pub fn забрать_процесс(&self) -> Option<Child> {
        // `take` внутри `and_then` вернул бы ссылку на локальную
        // блокировку: замок живёт только до конца замыкания, и
        // компилятор это справедливо отвергает.
        let mut з = self.процесс.lock().ok()?;
        з.take()
    }

    /// Что сейчас с голосом, для интерфейса.
    pub fn состояние(&self) -> ГолосСостояние {
        let поднят = self.поднят();
        ГолосСостояние {
            on: поднят,
            listening: поднят,
            // Пока голос выключен, он не занимает ничего: это и
            // есть смысл включать его вручную.
            weight_mb: поднят.then_some(143),
        }
    }
}

impl Default for Голос {
    fn default() -> Self {
        Self::новый()
    }
}

