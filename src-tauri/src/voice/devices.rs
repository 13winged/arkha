// Устройства звука: перечисление и выбор человеком.
//
// Зачем это. У человека на машине больше одного микрофона и больше
// одного вывода: наушники, колонки, монитор со встроенным звуком,
// микрофон гарнитуры. Пока приложение берёт «устройство по
// умолчанию», оно пишет не туда, куда человек думает, и это
// молча: звук идёт, а человек его слышит не там.
//
// Чего модуль не делает: не переключает системное устройство по
// умолчанию. Переключение «звука по умолчанию» в Windows меняет
// машину целиком и живёт в панели управления; мы выбираем только
// то, чем пользуемся сами, и это невидимо для остальных программ.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};
use windows::Win32::Devices::FunctionDiscovery::PKEY_Device_FriendlyName;
use windows::Win32::Foundation::PROPERTYKEY;
use windows::Win32::System::Com::{
    CoCreateInstance, CoInitializeEx, CoUninitialize, CLSCTX_ALL, COINIT_MULTITHREADED,
    STGM_READ,
};

use super::record::CLSID_МИКРОФОН;

/// Устройства и выбор: всё, что нужно настройкам за один раз.
#[derive(Debug, Clone, Serialize)]
pub struct Устройства {
    pub микрофоны: Vec<Устройство>,
    pub выводы: Vec<Устройство>,
    /// Что выбрано сейчас. Отдаётся вместе со списком, чтобы
    /// интерфейс не делал второй запрос только ради этого.
    pub выбор: Option<Аудио>,
}

/// Устройство звука так, как его видит человек.
#[derive(Debug, Clone, Serialize, PartialEq)]
pub struct Устройство {
    /// Идентификатор Windows. Его храним в настройках, человеку не
    /// показываем: он нечитаем и меняется при переподключении.
    pub id: String,
    /// Имя, под которым устройство знает человек.
    pub имя: String,
    /// Устройство по умолчанию для этого направления. Помечено,
    /// чтобы интерфейс мог показать его первым и не заставлять
    /// человека искать его глазами.
    pub по_умолчанию: bool,
}

/// Что человек выбрал.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Аудио {
    /// Идентификатор микрофона. `None` — устройство по умолчанию.
    #[serde(default)]
    pub микрофон: Option<String>,
    /// Идентификатор вывода. `None` — устройство по умолчанию.
    #[serde(default)]
    pub вывод: Option<String>,
    /// Сочетание клавиши диктовки. `None` — умолчание.
    #[serde(default)]
    pub горячая_клавиша: Option<String>,
}

/// Куда лежат настройки звука.
///
/// Рядом с остальным: `%APPDATA%\ArkHa\audio.json`. Отдельным
/// файлом, а не в `permissions.json`, потому что это не разрешение
/// и не профиль железа: у человека может быть внешний микрофон на
/// одной машине и тот же выбор на другой, и тащить его в профиль
/// железа незачем.
pub fn путь_настроек() -> PathBuf {
    crate::profile::config_dir().join("audio.json")
}

/// Прочитать выбор человека.
///
/// Отсутствие файла — не ошибка: значит человек ничего не выбирал
/// и работает то, что было до настроек.
pub fn настройки() -> Аудио {
    let Ok(текст) = std::fs::read_to_string(путь_настроек()) else {
        return Аудио::default();
    };
    serde_json::from_str(&текст).unwrap_or_default()
}

/// Сохранить выбор человека.
pub fn сохранить(настройки: &Аудио) -> Result<(), String> {
    let путь = путь_настроек();
    if let Some(родитель) = путь.parent() {
        std::fs::create_dir_all(родитель)
            .map_err(|e| format!("папка настроек не создалась: {e}"))?;
    }
    let текст = serde_json::to_string_pretty(настройки)
        .map_err(|e| format!("настройки не записались: {e}"))?;
    std::fs::write(&путь, текст)
        .map_err(|e| format!("настройки не записались {}: {e}", путь.display()))
}

/// Каким микрофоном писать.
pub fn выбранный_микрофон() -> Option<String> {
    настройки().микрофон
}

/// Каким выводом играть.
pub fn выбранный_вывод() -> Option<String> {
    настройки().вывод
}

/// Перечислить микрофоны.
pub fn микрофоны() -> Result<Vec<Устройство>, String> {
    перечислить(super::record::ЗАХВАТ)
}

/// Перечислить устройства вывода.
pub fn выводы() -> Result<Vec<Устройство>, String> {
    перечислить(super::record::ВОСПРОИЗВЕДЕНИЕ)
}

/// Перечислить устройства одного направления.
///
/// Перечисление идёт под COM, и COM инициализируется и снимается
/// здесь же: поток вызова короткий, и оставлять инициализацию
/// висящей нельзя - тогда следующий вызов на этом потоке получит
/// неожиданную квартиру.
fn перечислить(
    поток: windows::Win32::Media::Audio::EDataFlow,
) -> Result<Vec<Устройство>, String> {
    let _ = unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) };
    let итог = unsafe { перечислить_под(поток) };
    unsafe { CoUninitialize() };
    итог
}

unsafe fn перечислить_под(
    поток: windows::Win32::Media::Audio::EDataFlow,
) -> Result<Vec<Устройство>, String> {
    use windows::Win32::Media::Audio::{
        IMMDeviceEnumerator, DEVICE_STATE_ACTIVE,
    };

    let перечис: IMMDeviceEnumerator = unsafe {
        CoCreateInstance(&CLSID_МИКРОФОН, None, CLSCTX_ALL)
            .map_err(|e| format!("устройства звука не перечислились: {e}"))?
    };

    let устройство_по_умолчанию = unsafe {
        перечис
            .GetDefaultAudioEndpoint(поток, super::record::КОНСОЛЬ)
            .ok()
            .and_then(|d| d.GetId().ok())
            .and_then(|s| s.to_string().ok())
    };

    let сбор = unsafe { перечис.EnumAudioEndpoints(поток, DEVICE_STATE_ACTIVE) }
        .map_err(|e| format!("список устройств пуст: {e}"))?;

    let количество = unsafe { сбор.GetCount() }.unwrap_or(0);
    let mut список = Vec::new();

    for номер in 0..количество {
        let Ok(устройство) = (unsafe { сбор.Item(номер) }) else { continue };
        // Идентификатор обязателен: без него выбор не сохранится,
        // а устройство без имени в списке настроек бесполезно вдвое.
        let идентификатор = match unsafe { устройство.GetId() } {
            Ok(строка) => match unsafe { строка.to_string() } {
                Ok(т) => т,
                Err(_) => continue,
            },
            Err(_) => continue,
        };
        список.push(Устройство {
            id: идентификатор.clone(),
            имя: unsafe { читаемое_имя(&устройство) },
            по_умолчанию: устройство_по_умолчанию.as_deref() == Some(идентификатор.as_str()),
        });
    }

    // Устройство по умолчанию идёт первым: человек скорее всего
    // хочет именно его, а порядок перечисления Windows ничего не
    // обещает.
    список.sort_by(|а, б| б.по_умолчанию.cmp(&а.по_умолчанию).then(а.имя.cmp(&б.имя)));
    Ok(список)
}

/// Человеческое имя устройства.
///
/// Идентификатор вида `{0.0.1.00000000}.{ccc66bc4-…}` в списке
/// настроек бесполезен: человек по нему ничего не найдёт, а искать
/// своё устройство по буквам он не станет. Имя лежит в свойстве
/// устройства; если свойство недоступно, отдаём пустую строку и
/// интерфейс покажет «без имени», а не мусор.
unsafe fn читаемое_имя(устройство: &windows::Win32::Media::Audio::IMMDevice) -> String {
    use windows::Win32::System::Com::StructuredStorage::{
        PropVariantClear, PropVariantToStringAlloc,
    };

    let Ok(хранилище) = (unsafe { устройство.OpenPropertyStore(STGM_READ) }) else {
        return String::new();
    };
    let ключ: PROPERTYKEY = PKEY_Device_FriendlyName;
    let Ok(mut значение) = (unsafe { хранилище.GetValue(&ключ) }) else {
        return String::new();
    };

    let имя = unsafe {
        PropVariantToStringAlloc(&значение)
            .ok()
            .and_then(|строка| строка.to_string().ok())
            .unwrap_or_default()
    };
    // Освобождение обязательно: строка выделена системой, и без
    // `PropVariantClear` она остаётся висеть до конца процесса.
    let _ = unsafe { PropVariantClear(&mut значение) };
    имя
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Пустой выбор — это не ошибка, а «работай как раньше».
    #[test]
    fn пустой_выбор_читается_как_умолчание() {
        let н = Аудио::default();
        assert!(н.микрофон.is_none());
        assert!(н.вывод.is_none());
    }

    /// Файл настроек без нужных полей читается, а не отвергается.
    ///
    /// Проверка на живой записи человека: добавление нового поля в
    /// настройки не должно ломать старый файл, иначе после
    /// обновления выбор человека молча пропадёт.
    #[test]
    fn старый_файл_читается_без_новых_полей() {
        let старый = r#"{"микрофон":"abc"}"#;
        let разобранный: Аудио = serde_json::from_str(старый).expect("старый файл должен читаться");
        assert_eq!(разобранный.микрофон.as_deref(), Some("abc"));
        assert!(разобранный.вывод.is_none(), "отсутствующее поле не должно ломать чтение");
    }

    /// Битый файл не должен ронять приложение при старте.
    #[test]
    fn битый_файл_даёт_умолчания() {
        let разобранный: Result<Аудио, _> = serde_json::from_str("{ это не json");
        assert!(разобранный.is_err(), "битый файл обязан быть отвергнут разбором");
        // А `настройки()` на такой файл отдаёт умолчания, потому
        // что разбор обёрнут в `unwrap_or_default`.
    }

    /// Круг записи: что сохранили, то и прочитали.
    #[test]
    fn круг_записи_и_чтения() {
        let куда = std::env::temp_dir().join("arkha-audio-roundtrip.json");
        let выбор = Аудио {
            микрофон: Some("{0.0.1.00000000}.{микро}".to_string()),
            вывод: Some("{0.0.2.00000000}.{динамик}".to_string()),
            горячая_клавиша: Some("Ctrl+Alt+M".to_string()),
        };
        let текст = serde_json::to_string_pretty(&выбор).expect("сериализация");
        std::fs::write(&куда, &текст).expect("запись");
        let прочитанный: Аудио =
            serde_json::from_str(&std::fs::read_to_string(&куда).expect("чтение")).expect("разбор");
        let _ = std::fs::remove_file(&куда);
        assert_eq!(прочитанный, выбор);
    }

    /// Имя устройства по умолчанию не должно быть пустым после
    /// перечисления - иначе интерфейс покажет «без имени» для
    /// устройства, которым человек пользуется.
    ///
    /// Тест на живой машине: если звуковых устройств нет, он не
    /// применим и это не беда.
    #[test]
    fn перечисление_даёт_устройства() {
        let захват = микрофоны().expect("микрофоны должны перечислиться");
        let воспроизведение = выводы().expect("выводы должны перечислиться");
        assert!(!захват.is_empty(), "в системе должен быть хоть один микрофон");
        assert!(!воспроизведение.is_empty(), "в системе должен быть хоть один вывод");
        // Идентификатор не пустой: без него выбор не сохранится.
        assert!(захват.iter().all(|д| !д.id.is_empty()));
    }
}