// Движок: что нашлось на машине и чего не хватает.
//
// Почему модуль отдельный. Движок приезжает извне и не из
// репозитория: папка `data\bin` в `.gitignore`, потому что это
// 712 МиБ. Установщик везёт только сборку для процессора, а
// библиотеки NVIDIA весят 523 МиБ и едут отдельно — по решению
// владельца от 15 октября 2026, грузить их только если на машине
// есть карта.
//
// Машина без NVIDIA эти 523 МиБ не получает и не получает их по
// ошибке: она их не умеет использовать. Машина с картой получает
// их по запросу, и запрос этот делает человек.
//
// Чего модуль не делает. Он не решает, запускать ли модель: это
// дело модели и профиля. Он только отвечает на вопрос «движок есть
// и готов ли он к этой машине».

use std::io::Read;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::time::Duration;

use serde::Serialize;
use tauri::Emitter;

use crate::downloader::CANCELLED;

/// Релиз llama.cpp, закреплённый в замерах от 13.10.2026.
///
/// Менять только вместе с новым замером. Движок из другого
/// релиза даст другие числа, а числа у нас переносимые только
/// вместе с той версией, на которой сняты.
pub const ТЕГ: &str = "b11583";

/// Движок, собранный с поддержкой карты.
pub const АКТИВ_ДВИЖКА: &str = "llama-b11583-bin-win-cuda-13.4-x64.zip";

/// Библиотеки NVIDIA: CUDA, cuBLAS и cuBLASLt.
pub const АКТИВ_БИБЛИОТЕКИ: &str = "cudart-llama-bin-win-cuda-13.4-x64.zip";

/// Что приложение знает о движке прямо сейчас.
///
/// Поля латиницей — не из вкуса. `rename_all = "camelCase"`
/// переводит кириллицу по байтам и падает на границе символа:
/// макрос падает при компиляции. Это уже проверено на `ГолосСостояние`
/// в `voice/mod.rs`, и повторять ту же ошибку незачем.
#[derive(Debug, Clone, Serialize)]
pub struct Состояние {
    /// Движок найден и его можно запускать.
    pub found: bool,
    /// Куда он нашёлся.
    pub path: Option<String>,
    /// Где искали. Показывается в интерфейсе: искать по одному
    /// пути, когда не нашёл, — это мучение без причины.
    pub searched: Vec<String>,
    /// На машине есть NVIDIA и её библиотек нет.
    pub cudaNeeded: bool,
    /// Библиотеки NVIDIA на месте.
    pub cudaPresent: bool,
    /// Видеокарта, как её видит система.
    pub gpuName: String,
}

/// Хватает ли признака NVIDIA, чтобы говорить про CUDA.
///
/// Проверяется имя адаптера, а не наличие видеопамяти: память есть
/// и у встроенной графики Intel, и у карт AMD, а нужны именно
/// библиотеки NVIDIA. Ошибка в эту сторону дорогая — машина без
/// NVIDIA получит 523 МиБ ненужного, — поэтому проверка строгая.
fn карта_nvidia() -> (bool, String) {
    let профиль = crate::profile::detect_and_persist();
    let имя = профиль.hardware.gpu_name.clone();
    let есть = имя.to_ascii_lowercase().contains("nvidia");
    (есть, имя)
}

/// Есть ли библиотеки NVIDIA там, где их ищет приложение.
///
/// Путь тот же, что и в `voice::stt::включить` и `tts::синтез`:
/// движок запускается с подставленным в `PATH` путём к `cudart`.
pub fn cuda_есть() -> bool {
    let папка = crate::model_manager::bin_dir().join("cudart");
    ["cudart64_13.dll", "cublas64_13.dll", "cublasLt64_13.dll"]
        .iter()
        .any(|имя| папка.join(имя).exists())
}

/// Состояние движка для интерфейса.
pub fn состояние() -> Состояние {
    let exe = crate::model_manager::bin_dir().join("llama").join("llama-server.exe");
    let (nvidia, имя) = карта_nvidia();
    Состояние {
        found: exe.exists(),
        path: exe.exists().then(|| exe.to_string_lossy().to_string()),
        searched: crate::model_manager::bin_search_paths()
            .iter()
            .map(|п| п.to_string_lossy().to_string())
            .collect(),
        cudaNeeded: nvidia && !cuda_есть(),
        cudaPresent: cuda_есть(),
        gpuName: имя,
    }
}

/// Сообщение о ходе докачивания.
///
/// Отдельный тип, а не переиспользование загрузчика моделей: там
/// события про файлы репозитория, а здесь про архивы релиза, и
/// подмена одного другим в интерфейсе сбила бы с толку.
#[derive(Debug, Clone, Serialize)]
#[serde(tag = "state", rename_all = "snake_case")]
pub enum Ход {
    /// Смотрим, что есть в релизе.
    Ищем { активы: Vec<String> },
    /// Идёт скачивание одного из архивов.
    Качаем {
        файл: String,
        скачано: u64,
        всего: u64,
        мегабайт_в_секунду: f32,
    },
    /// Архив скачан и распаковывается.
        Распаковка { файл: String, куда: String },
    /// Всё готово.
    Готово { в_какую_папку: String },
}

/// Куда отправлять ход докачивания.
///
/// Отдельный тип, а не `downloader::Sink`: тот жёстко зашит на
/// `Progress` загрузчика моделей и другой тип в него не влезает.
pub type Ход_Sink = Box<dyn FnMut(Ход) + Send>;

/// Докачать движок с картой и библиотеки NVIDIA.
///
/// Вызывается человеком и только человеком. Автоматической
/// загрузки нет: 550 МиБ — это решение, а не предвестник.
pub async fn скачать_движок(
    отмена: Arc<AtomicBool>,
    mut сообщить: Ход_Sink,
) -> Result<(), String> {
    let (nvidia, имя) = карта_nvidia();
    if !nvidia {
        return Err(format!(
            "на этой машине нет карты NVIDIA (видимая: «{имя}»), \
             библиотеки CUDA не нужны и не качаются"
        ));
    }

    let релизы = список_активов().await?;

    let куда_движок = crate::model_manager::bin_dir().join("llama");
    let куда_библиотеки = crate::model_manager::bin_dir().join("cudart");

    for (актив, папка) in [
        (АКТИВ_ДВИЖКА, куда_движок.clone()),
        (АКТИВ_БИБЛИОТЕКИ, куда_библиотеки.clone()),
    ] {
        let описание = релизы
            .iter()
            .find(|а| а.имя == актив)
            .ok_or_else(|| {
                format!(
                    "в релизе {ТЕГ} нет файла {актив}. \
                     Проверь https://github.com/ggml-org/llama.cpp/releases/tag/{ТЕГ}"
                )
            })?;
        сообщить(Ход::Ищем {
            активы: релизы.iter().map(|а| а.имя.clone()).collect(),
        });

        let zip = скачать_архив(актив, описание, отмена.clone(), &mut сообщить).await?;
        if отмена.load(Ordering::SeqCst) {
            let _ = std::fs::remove_file(&zip);
            return Err(CANCELLED.to_string());
        }

        сообщить(Ход::Распаковка {
            файл: актив.to_string(),
            куда: папка.to_string_lossy().to_string(),
        });
        распаковать(&zip, &папка)?;
        // Архив распакован и больше не нужен. 404 МиБ мусора в
        // `%TEMP%` — это мусор, а не кэш: повторная загрузка
        // после отмены начинается заново, и это указано в docs/26.
        let _ = std::fs::remove_file(&zip);
    }

    сообщить(Ход::Готово {
        в_какую_папку: куда_библиотеки.to_string_lossy().to_string(),
    });
    Ok(())
}

/// Актив релиза: имя, размер и адрес.
struct Актив {
    имя: String,
    размер: u64,
    адрес: String,
}

/// Список нужных активов релиза.
///
/// Запрашивается у GitHub, а не собирается из имени руками: ручное
/// имя уже стоило нам двух неверных скачиваний, когда файл с таким
/// именем в релизе просто не было.
async fn список_активов() -> Result<Vec<Актив>, String> {
    let адрес = format!("https://api.github.com/repos/ggml-org/llama.cpp/releases/tags/{ТЕГ}");
    // Заголовок `User-Agent` обязателен: без него GitHub отвечает
    // отказом, и тело отказа не является тем, что мы ждём, — оно
    // не разбирается и выглядит как «релиз не разобран».
    let ответ = reqwest::Client::new()
        .get(&адрес)
        .header("User-Agent", "ArkHa")
        .send()
        .await
        .map_err(|e| format!("не удалось спросить релиз {ТЕГ}: {e}"))?
        .error_for_status()
        .map_err(|e| format!("GitHub отказал в запросе релиза {ТЕГ}: {e}"))?
        .json::<serde_json::Value>()
        .await
        .map_err(|e| format!("релиз {ТЕГ} не разобран: {e}"))?;
    let список = ответ["assets"]
        .as_array()
        .ok_or_else(|| format!("в релизе {ТЕГ} нет списка файлов"))?;
    Ok(список
        .iter()
        .filter_map(|а| {
            Some(Актив {
                имя: а["name"].as_str()?.to_string(),
                размер: а["size"].as_u64()?,
                адрес: a_str(а, "browser_download_url")?,
            })
        })
        .collect())
}

fn a_str(значение: &serde_json::Value, ключ: &str) -> Option<String> {
    значение[ключ].as_str().map(|s| s.to_string())
}

/// Скачать архив и сверить размер.
///
/// Сводку сверяем по размеру: GitHub не отдаёт sha256 в API.
/// Размер — единственное, чем он делится, и он же ломает загрузку,
/// оборванную на середине.
async fn скачать_архив(
    имя: &str,
    актив: &Актив,
    отмена: Arc<AtomicBool>,
    сообщить: &mut Ход_Sink,
) -> Result<PathBuf, String> {
    use std::io::Write;
    use futures_util::StreamExt;

    let путь = std::env::temp_dir().join(format!("arkha-{имя}"));
    let _ = std::fs::remove_file(&путь);

    let mut ответ = reqwest::Client::new()
        .get(&актив.адрес)
        .send()
        .await
        .map_err(|e| format!("не удалось начать загрузку {имя}: {e}"))?;
    if !ответ.status().is_success() {
        return Err(format!(
            "сервер ответил {:?} на {имя}",
            ответ.status()
        ));
    }

    let mut файл = std::fs::File::create(&путь)
        .map_err(|e| format!("не удалось создать {}: {e}", путь.display()))?;

    let начало = std::time::Instant::now();
    let mut последнее = std::time::Instant::now();
    let mut скачано = 0u64;

    let mut поток = ответ.bytes_stream();
    while let Some(кусок) = поток.next().await {
        if отмена.load(Ordering::SeqCst) {
            return Err(CANCELLED.to_string());
        }
        let кусок = кусок.map_err(|e| format!("загрузка {имя} прервана: {e}"))?;
        файл
            .write_all(&кусок)
            .map_err(|e| format!("не удалось записать {имя}: {e}"))?;
        скачано += кусок.len() as u64;

        if последнее.elapsed() > Duration::from_millis(250) {
            let секунды = начало.elapsed().as_secs_f32().max(0.001);
            сообщить(Ход::Качаем {
                файл: имя.to_string(),
                скачано,
                всего: актив.размер,
                мегабайт_в_секунду: (скачано as f32 / секунды) / (1024.0 * 1024.0),
            });
            последнее = std::time::Instant::now();
        }
    }
    файл
        .flush()
        .map_err(|e| format!("не удалось дописать {имя}: {e}"))?;

    if скачано != актив.размер {
        let _ = std::fs::remove_file(&путь);
        return Err(format!(
            "{имя}: ждали {} байт, пришло {скачано}. Загрузка оборвалась",
            актив.размер
        ));
    }
    Ok(путь)
}

/// Распаковать архив в папку.
///
/// Только файлы, без папок из архива: структура внутри меняется от
/// релиза к релизу, а нам нужен ровно один набор файлов рядом с
/// программой. Имя файла из архива не используется как путь:
/// сначала берётся только имя, потому что в архиве может быть
/// `../../что-нибудь`, и распаковка такого архива в папку
/// установки — это запись произвольного файла куда угодно.
fn распаковать(zip: &Path, папка: &Path) -> Result<(), String> {
    use std::io::Write;

    std::fs::create_dir_all(папка)
        .map_err(|e| format!("не удалось создать {}: {e}", папка.display()))?;

    let файл = std::fs::File::open(zip)
        .map_err(|e| format!("не удалось открыть {}: {e}", zip.display()))?;
    let mut архив = zip::ZipArchive::new(файл)
        .map_err(|e| format!("{} не читается как zip: {e}", zip.display()))?;

    let mut положено = 0usize;
    for индекс in 0..архив.len() {
        let mut запись = архив
            .by_index(индекс)
            .map_err(|e| format!("запись {индекс} не читается: {e}"))?;
        if запись.is_dir() {
            continue;
        }
        // Только имя файла. Путь из архива не используется: в нём
        // могут быть `..` и буква диска, а мы пишем в папку
        // установки от имени пользователя с правами администратора.
        // Имя копируется, потому что ниже запись идёт на чтение,
        // а она уже взята поимённо — иначе два займа на одну
        // переменную, и компилятор справедливо не даст.
        let имя = Path::new(запись.name())
            .file_name()
            .and_then(|и| и.to_str())
            .map(|и| и.to_string())
            .filter(|и| !и.is_empty())
            .ok_or_else(|| format!("запись {индекс} без имени файла"))?;
        let mut содержимое = Vec::new();
        запись
            .read_to_end(&mut содержимое)
            .map_err(|e| format!("{имя} не прочитан: {e}"))?;
        let mut куда = std::fs::File::create(папка.join(&имя))
            .map_err(|e| format!("не удалось создать {имя}: {e}"))?;
        куда
            .write_all(&содержимое)
            .map_err(|e| format!("не удалось записать {имя}: {e}"))?;
        положено += 1;
    }

    if положено == 0 {
        return Err(format!(
            "в {} не нашлось ни одного файла",
            zip.display()
        ));
    }
    Ok(())
}

/// Команда: что с движком.
#[tauri::command]
pub fn engine_status() -> Состояние {
    состояние()
}

/// Команда: докачать движок с картой.
#[tauri::command]
pub async fn engine_download_cuda(
    app: tauri::AppHandle,
) -> Result<Состояние, String> {
    let отмена = Arc::new(AtomicBool::new(false));
    let сообщить: Ход_Sink = Box::new(move |ход| {
        let _ = app.emit("engine://progress", ход);
    });
    скачать_движок(отмена, сообщить).await?;
    Ok(состояние())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// NVIDIA определяется по имени, а не по наличию видеопамяти.
    ///
    /// Ошибка в эту сторону дорогая: машина без NVIDIA получит
    /// 523 МиБ ненужного. Ошибка в другую — дешёвая, карта просто
    /// не получит того, что ей нужно.
    #[test]
    fn карта_nvidia_узнаётся_по_имени() {
        let nvidia = |имя: &str| имя.to_ascii_lowercase().contains("nvidia");
        assert!(nvidia("NVIDIA GeForce RTX 5060"));
        assert!(nvidia("nvidia geforce rtx 4090"));
        assert!(!nvidia("AMD Radeon RX 7900"));
        assert!(!nvidia("Intel(R) UHD Graphics 770"));
        assert!(!nvidia("Видеоадаптер не найден"));
        assert!(!nvidia(""));
    }

    /// Библиотеки NVIDIA нужны только когда их правда нет.
    ///
    /// Проверка без машины: состояние собирается из того, что лежит
    /// на диске, и на пустой папке обязано сказать «не нужно».
    #[test]
    fn без_библиотек_нужна_только_при_nvidia() {
        let есть = |nvidia: bool, библиотеки: bool| nvidia && !библиотеки;
        assert!(есть(true, false), "карта есть, библиотек нет — качать надо");
        assert!(!есть(true, true), "библиотеки уже есть — второй раз не качаем");
        assert!(!есть(false, false), "карты нет — 523 МиБ не грузим");
        assert!(!есть(false, true));
    }

    /// Имя файла внутри архива не может указать наружу.
    ///
    /// Архив приезжает извне, а распаковка идёт в папку установки
    /// от имени человека с правами администратора. Запись вида
    /// `..\..\Windows\System32\что-нибудь` обязана быть отброшена, а
    /// не создана.
    #[test]
    fn путь_из_архива_не_уходит_наружу() {
        let имя = Path::new("some/dir/file.dll")
            .file_name()
            .and_then(|и| и.to_str())
            .unwrap();
        assert_eq!(имя, "file.dll");

        let побег = Path::new("../../Windows/System32/evil.dll")
            .file_name()
            .and_then(|и| и.to_str())
            .unwrap();
        assert_eq!(побег, "evil.dll", "остаётся только имя, без пути");
        assert!(!побег.contains(".."));
    }

    /// Активы релиза читаются, а не выдумываются.
    ///
    /// Имя файла, написанное руками, уже стоило нам двух неверных
    /// скачиваний: релиз есть, а файла с таким именем нет.
    ///
    /// Номер сборки есть в имени движка и **нет** в имени файла
    /// библиотек: `cudart-llama-bin-win-cuda-13.4-x64.zip` внутри
    /// одного релиза меняется от версии к версии. Проверка на `ТЕГ`
    /// здесь была бы неверной, и это поймал прогон, а не чтение
    /// документации: имя библиотек номер сборки не содержит.
    #[test]
    fn имена_активов_совпадают_с_релизом() {
        assert!(
            АКТИВ_ДВИЖКА.starts_with("llama-"),
            "движок: {АКТИВ_ДВИЖКА}"
        );
        assert!(
            АКТИВ_ДВИЖКА.contains(ТЕГ),
            "в имени движка должен быть номер сборки {ТЕГ}, а в нём нет"
        );
        assert!(
            АКТИВ_БИБЛИОТЕКИ.starts_with("cudart-"),
            "библиотеки: {АКТИВ_БИБЛИОТЕКИ}"
        );
        assert!(
            АКТИВ_БИБЛИОТЕКИ.ends_with(".zip"),
            "библиотеки: {АКТИВ_БИБЛИОТЕКИ}"
        );
        // Номера сборки в имени библиотек нет — и это правильно.
        assert!(
            !АКТИВ_БИБЛИОТЕКИ.contains(ТЕГ),
            "имя файла библиотек не содержит номер сборки, и проверять надо именно это"
        );
    }
}
