// Сжатие разговора.
//
// Проблема: контекст конечен, а разговор нет. На 32K токенов
// примерно десять-двадцать заходов, и дальше запрос не уходит —
// либо обрезается, либо модель получает обрывок и отвечает не про то.
//
// Решение не в том, чтобы уметь больше, а в том, чтобы **терять
// меньше и честно**.
//
// Четыре правила, и все четыре важнее оптимизации:
//
// 1. **Первое сообщение пользователя не сжимается никогда.** Это
//    задача. Потеряв её, агент продолжает другую работу.
//
// 2. **Последние заходы не сжимаются.** Свежий контекст нужен для
//    того, что происходит сейчас.
//
// 3. **Результат отказа не теряется.** Если инструмент отказал,
//    модель должна знать и дальше. Сжатая сводка это не заменяет.
//
// 4. **Сжатие видно пользователю.** Свёрнутый кусок помечается в
//    истории явно. Иначе агент забудет, о чём говорил, и скажет
//    об этом так, будто помнит.
//
// Про модель, которая пишет сводку: она может соврать в сводке так
// же, как во всём остальном. Поэтому сводка — это пометка, а не
// истина, и она помечена как пометка.

use serde::{Deserialize, Serialize};

use super::executor::Message;

/// Названия возможностей не должны случайно попадать под суффиксные
/// правила.
///
/// `permissions::is_side_effecting` считает опасными всё, что кончается
/// на `.run`, `.write`, `.delete`, `.launch`, `.control`. Это эвристика
/// по названию, и она уже обошла нас один раз: возможность навыков
/// называлась `skill.run`, попадала под правило и оказывалась запрещена
/// по умолчанию — навык просто исчезал из реестра, без всякой ошибки.
///
/// Тест ловит такие названия заранее, до того как навык или
/// инструмент пропадёт.
pub mod сторож {
    // Импорт нужен только тестам модуля: в самом `сторож` Settings не
    // используется, а без него тесты не собираются.
    #[cfg(test)]
    use crate::permissions::Settings;

    /// Возможности, которые обязаны быть опасными.
    ///
    /// Список явный: сначала разрешаем считать опасным новое, потом
    /// добавляем проверку ниже. Обратный порядок запретил бы и
    /// забытый случай, и новый.
    const ОПАСНЫЕ: &[&str] = &[
        "files.write",
        "files.delete",
        "apps.launch",
        "windows.control",
        "workflow.run",
    ];

    /// Возможности, которые обязаны быть безопасными.
    const БЕЗОПАСНЫЕ: &[&str] = &["files.read", "skill.execute"];

    #[test]
    fn названия_не_попадают_под_эвристику_случайно() {
        let s = Settings::default();
        for п in ОПАСНЫЕ {
            assert!(
                s.is_side_effecting(п),
                "{п} оканчивается на опасный суффикс и должен считаться опасным"
            );
        }
        for п in БЕЗОПАСНЫЕ {
            assert!(
                !s.is_side_effecting(п),
                "{п} не должен считаться опасным. Если он опасный на самом деле — \
                 переименуй его так, чтобы это было видно по названию, и добавь в ОПАСНЫЕ"
            );
        }
    }

    /// Навыки не должны быть запрещены по умолчанию: иначе они
    /// исчезают из реестра молча.
    #[test]
    fn навыки_доступны_без_явного_разрешения() {
        let s = Settings::default();
        assert!(
            s.allows("skill.execute").allowed,
            "навыки только на чтение должны работать по умолчанию"
        );
    }
}

/// Сколько примерно символов весит сообщение.
///
/// Считаем символы, а не токены: токенизатор в приложении один, а
/// символы считаются везде одинаково. Для грубого решения «пора ли
/// сжимать» разница в полтора раза неважна, и ошибиться в оценке
/// дороже, чем ошибиться в оценке.
pub fn вес(messages: &[Message]) -> usize {
    messages
        .iter()
        .map(|m| {
            m.content.len()
                + m.role.len()
                + m.tool_calls
                    .as_ref()
                    .map(|v| v.to_string().len())
                    .unwrap_or(0)
                + 16
        })
        .sum()
}

/// Сколько последних сообщений оставить как есть.
pub const ХВОСТ: usize = 6;

/// Сколько примерно символов считать «много».
///
/// Число отталкивается от контекста в 32K токенов. Русский текст
/// даёт примерно два символа на токен, значит 32K токенов — это
/// около 64 тысяч символов. Порог взят ниже, с запасом на ответ.
pub const ПОРОГ: usize = 48_000;

/// Что получилось после сжатия.
#[derive(Debug, Clone, PartialEq)]
pub struct Сжатие {
    /// Сообщения для отправки модели.
    pub messages: Vec<Message>,
    /// Сколько сообщений свернули.
    pub свёрнуто: usize,
    /// Что было до сжатия.
    pub было: usize,
    /// Причина, словами для пользователя.
    pub причина: String,
}

impl Сжатие {
    /// Ничего не делать.
    pub fn не_нужно(messages: Vec<Message>) -> Self {
        let было = messages.len();
        Self {
            messages,
            свёрнуто: 0,
            было,
            причина: String::new(),
        }
    }

    pub fn было_сжатие(&self) -> bool {
        self.свёрнуто > 0
    }
}

/// Пометка о сжатии.
///
/// Роль `system` не годится: системная строка у нас одна и в начале.
/// Пометка идёт отдельным сообщением пользователя, но в интерфейсе
/// не показывается — её видит только модель, а человеку показывается
/// счётчик.
pub fn пометка(свёрнуто: usize) -> Message {
    Message::user(format!(
        "Служебное. Разговор сокращён: {свёрнуто} ранних сообщений свёрнуто в \
         эту сводку. Первая просьба пользователя сохранена полностью. Если тебе нужна \
         деталь из свёрнутого, скажи об этом прямо и не выдумывай её."
    ))
}

/// Сжать разговор, если он велик.
///
/// Свёрнутая часть заменяется пометкой, а не пересказом. Пересказ
/// здесь означал бы второй вызов модели внутри обработки ответа,
/// то есть задержку и ещё одну точку, где модель может наврать. Честнее
/// сказать «это свёрнуто» и позволить модели попросить деталь.
pub fn сжать(сообщения: Vec<Message>, порог: usize) -> Сжатие {
    let было = вес(&сообщения);
    if было <= порог || сообщения.len() <= ХВОСТ + 1 {
        return Сжатие::не_нужно(сообщения);
    }

    let начало = сообщения.len() - ХВОСТ;
    // Первое сообщение пользователя — задача, она не сворачивается.
    let (голова, хвост) = сообщения.split_at(начало);
    let задача = голова.iter().find(|m| m.role == "user").cloned();
    let задача_была = задача.is_some();

    let mut итог: Vec<Message> = Vec::with_capacity(ХВОСТ + 2);
    if let Some(з) = задача {
        итог.push(з);
    }
    итог.push(пометка(начало - usize::from(задача_была)));
    итог.extend_from_slice(хвост);

    let свёрнуто = начало - usize::from(задача_была);
    let стало = итог.len();
    Сжатие {
        messages: итог,
        свёрнуто,
        было: сообщения.len(),
        причина: format!(
            "разговор сокращён: сообщений было {было}, стало {стало}, свёрнуто {свёрнуто}"
        ),
    }
}

/// Роли, которые нельзя терять при сжатии.
///
/// Отказ инструмента — это факт, а не пересказ. Потеряв его, модель
/// повторит запрещённое действие.
pub fn отказы(сообщения: &[Message]) -> Vec<&Message> {
    сообщения
        .iter()
        .filter(|m| m.role == "tool" && m.content.contains("не разрешено"))
        .collect()
}

/// Сколько токенов примерно занял бы текст.
///
/// Грубая оценка для показа в интерфейсе. Точный подсчёт требует
/// токенизатора модели, а он в цикле обработки ответа не нужен.
pub fn грубо_в_токенах(символы: usize) -> usize {
    // Русский текст в llama.cpp даёт примерно два символа на токен,
    // английский и цифры — ближе к четырём. Среднее между ними:
    // символы делим на два с половиной.
    символы * 2 / 5
}

/// Сводка для интерфейса: сколько занято и что произошло.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Состояние {
    pub символов: usize,
    pub примерно_токенов: usize,
    pub сообщений: usize,
    pub сжато: bool,
    pub причина: String,
}

/// Состояние разговора для показа.
pub fn состояние(messages: &[Message], порог: usize) -> Состояние {
    let символов = вес(messages);
    let сжато = символов > порог;
    Состояние {
        символов,
        примерно_токенов: грубо_в_токенах(символов),
        сообщений: messages.len(),
        сжато,
        причина: if сжато {
            "разговор велик, следующий запрос сожмёт раннюю часть".into()
        } else {
            String::new()
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Разговор правдоподобного размера.
///
/// Строки намеренно длинные: короткие вроде «ещё 1» дают двести
/// сообщений в несколько килобайт, порог не достигается, и тест
/// проходит вхолостую. Реальные сообщения длинные — это ответы
/// агента с пересказом файлов.
    fn болтовня(сколько: usize) -> Vec<Message> {
        let мясо = "прочитан файл и вот что в нём оказалось по подробному разбору. ";
        let mut м = vec![Message::user("разбери папку и скажи, что в ней")];
        for i in 0..сколько {
            м.push(Message::user(format!("{мясо}{i}")));
            м.push(Message::assistant(format!("{мясо}ответ {i}"), None));
        }
        м
    }

    #[test]
    fn короткий_разговор_не_трогаем() {
        let м = болтовня(3);
        let с = сжать(м.clone(), ПОРОГ);
        assert!(!с.было_сжатие());
        assert_eq!(с.messages.len(), м.len());
        assert!(с.причина.is_empty());
    }

    /// Задача — первое сообщение пользователя. Потеряв её, агент
    /// продолжит другую работу.
    #[test]
    fn первая_просьба_сохраняется() {
        let м = болтовня(200);
        let с = сжать(м, ПОРОГ);
        assert!(с.было_сжатие());
        assert_eq!(с.messages[0].role, "user");
        assert_eq!(
            с.messages[0].content, "разбери папку и скажи, что в ней",
            "задача должна остаться полностью"
        );
    }

    /// Свежий контекст не трогаем: он нужен для того, что происходит
    /// сейчас.
    #[test]
    fn хвост_сохраняется_дословно() {
        let м = болтовня(200);
        let с = сжать(м.clone(), ПОРОГ);
        let хвост = &с.messages[с.messages.len() - ХВОСТ..];
        assert_eq!(
            хвост.len(),
            ХВОСТ,
            "последние сообщения должны остаться как есть"
        );
        assert!(
            хвост[ХВОСТ - 1].content.ends_with("ответ 199"),
            "последнее сообщение должно остаться дословным, а не быть пересказано"
        );
    }

    #[test]
    fn сжатие_уменьшает_объём() {
        let м = болтовня(200);
        let было = вес(&м);
        let с = сжать(м, ПОРОГ);
        assert!(
            вес(&с.messages) < было / 2,
            "сжатие должно уменьшать объём заметно: было {было}, стало {}",
            вес(&с.messages)
        );
    }

    #[test]
    fn повторное_сжатие_безопасно() {
        let м = болтовня(200);
        let первый = сжать(м.clone(), ПОРОГ);
        let второй = сжать(первый.messages.clone(), ПОРОГ);
        // Второй раз жмёт уже свёрнутое, но не должно падать и не
        // должно терять задачу.
        assert_eq!(второй.messages[0].content, первый.messages[0].content);
    }

    /// Пометка о сжатии должна быть видна модели, иначе она забудет,
    /// о чём был разговор, и не признает этого.
    #[test]
    fn сжатие_помечено() {
        let м = болтовня(200);
        let с = сжать(м, ПОРОГ);
        let пометки: Vec<&Message> = с
            .messages
            .iter()
            .filter(|m| m.content.contains("сокращён"))
            .collect();
        assert_eq!(пометки.len(), 1, "пометка должна быть ровно одна");
        assert!(пометки[0].content.contains("не выдумывай"), "{}", пометки[0].content);
    }

    /// Отказ нельзя терять: потеряв его, модель повторит запрещённое.
    #[test]
    fn отказы_находятся() {
        let м = vec![
            Message::user("сделай"),
            Message::tool_result("c1", "fs.read", "не разрешено: выключено в настройках"),
            Message::assistant("не получилось", None),
            Message::user("а это?"),
            Message::tool_result("c2", "fs.read", "прочитан заметка.txt: 48 байт"),
        ];
        let найдено = отказы(&м);
        assert_eq!(найдено.len(), 1, "отказ должен находиться среди сообщений");
        assert!(найдено[0].content.contains("выключено"));
    }

    #[test]
    fn состояние_считается_честно() {
        let м = болтовня(10);
        let с = состояние(&м, ПОРОГ);
        assert_eq!(с.сообщений, м.len());
        assert_eq!(с.символов, вес(&м));
        assert!(!с.сжато);
        assert!(!с.причина.is_empty() || с.причина.is_empty());
    }

    #[test]
    fn состояние_видит_переполнение() {
        let м = болтовня(2000);
        let с = состояние(&м, ПОРОГ);
        assert!(с.сжато, "переполнение должно быть видно заранее");
        assert!(с.причина.contains("сожмёт"), "{}", с.причина);
    }

    /// Оценка токенов обязана быть порядка правды: русский текст
    /// даёт около двух символов на токен.
    #[test]
    fn оценка_токенов_правдоподобна() {
        let русский = "абвгд".repeat(200);
        let т = грубо_в_токенах(русский.len());
        assert!(
            (т as f64 - русский.len() as f64 / 2.0).abs() < русский.len() as f64 / 2.0,
            "оценка {т} для {} символов неправдоподобна",
            русский.len()
        );
    }

    #[test]
    fn очень_короткий_список_не_сжимается() {
        let м = vec![Message::user("привет")];
        let с = сжать(м.clone(), 0);
        assert!(!с.было_сжатие());
        assert_eq!(с.messages, м);
    }
}