// Подтверждения S7.
//
// Три вещи, которые тут решаются, и все три — из уже написанного, а не
// новые требования:
//
// 1. **Уровень опасности.** Способность сама по себе не говорит, что
//    опасно: `files.write` меняет один файл, `files.delete` стирает
//    необратимо. Уровень считается из возможности и аргументов.
//
// 2. **Область подтверждения.** Один вопрос на десять шагов — десять
//    модалок, и пользователь начинает подтверждать не глядя. Значит
//    одно «да» покрывает всю операцию. Отдельная кнопка «только
//    этот раз» оставлена для тех случаев, когда и это слишком широко.
//
// 3. **Повтор после отказа.** Модель, которой отказали, часто звонит
//    снова то же самое. Это не настойчивость, это следствие того, что
//    отказ не всегда доходит до неё. Здесь отказ всегда доходит, а
//    повтор запрещён явно.
//
// Про уровни из [docs/05-безопасность.md](../../docs/05-безопасность.md):
// L1 — внешние эффекты, L2 — изменение состояния, L3 — только чтение.

use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;

use crate::permissions::{ApprovalMode, Settings};

/// Насколько действие опасно.
///
/// Числа — не украшение: `L3` читается как «третий уровень», и путать
/// уровни опасности с порядком их перечисления нельзя.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Уровень {
    /// Только чтение. Ничего не меняется.
    L3,
    /// Меняет состояние: создать файл, закрыть процесс.
    L2,
    /// Внешний эффект: удалить, отправить, купить.
    L1,
}

impl Уровень {
    /// Название для интерфейса. Человек не должен знать про L1/L2/L3,
    /// чтобы понять, насколько это опасно.
    pub fn название(self) -> &'static str {
        match self {
            Уровень::L3 => "только чтение",
            Уровень::L2 => "изменение на компьютере",
            Уровень::L1 => "внешнее действие",
        }
    }

    /// Что будет изменено, словами.
    pub fn пояснение(self) -> &'static str {
        match self {
            Уровень::L3 => "ничего на компьютере не изменится",
            Уровень::L2 => "файл или программа на вашем компьютере будут изменены",
            Уровень::L1 => "это необратимо: действие нельзя отменить",
        }
    }

    /// Нужно ли подтверждение при таком режиме.
    ///
    /// Зависит от режима пользователя, но не от настроек возможности:
    /// режим выбран один раз и применяется ко всему.
    pub fn спрашивает(self, режим: ApprovalMode) -> bool {
        match режим {
            ApprovalMode::Auto => false,
            ApprovalMode::Confirm => true,
            ApprovalMode::Risky => self != Уровень::L3,
        }
    }
}

/// Уровень опасности по возможности и аргументам.
///
/// Аргументы смотрятся не для красоты: удаление одного файла и
/// удаление папки — разный риск, хотя возможность одна.
pub fn уровень(capability: &str, args: &serde_json::Value) -> Уровень {
    match capability {
        // Необратимое.
        "files.delete" => {
            // Папка целиком опаснее файла: восстановить содержимое
            // каталога из корзины можно, но не всегда.
            let много = args
                .get("recursive")
                .and_then(|v| v.as_bool())
                .unwrap_or(false);
            if много {
                Уровень::L1
            } else {
                Уровень::L2
            }
        }
        "web.fetch" | "apps.launch" | "windows.control" | "workflow.run" => Уровень::L1,
        // Меняет состояние.
        "files.write" => Уровень::L2,
        // Всё остальное — чтение.
        _ => Уровень::L3,
    }
}

/// Ответ пользователя на вопрос.
///
/// Имена заданы **явно**, а не через `rename_all = "kebab-case"`.
/// Разделитель CamelCase `kebab-case` расставляет правильно, но
/// регистр для кириллицы не меняет: из `ОдинРаз` получается
/// `Один-Раз`, а интерфейс ждёт `один-раз`. Расхождение вылезло бы
/// только при нажатии кнопки, поэтому зафиксировано тестом.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Решение {
    /// Только этот вызов.
    #[serde(rename = "один-раз")]
    ОдинРаз,
    /// Вся операция в этом запуске.
    #[serde(rename = "всю-задачу")]
    ВсюЗадачу,
    /// Отказать.
    #[serde(rename = "отказ")]
    Отказ,
}

impl Решение {
    pub fn разрешает(self) -> bool {
        !matches!(self, Решение::Отказ)
    }

    pub fn действие(self) -> &'static str {
        match self {
            Решение::ОдинРаз => "только этот раз",
            Решение::ВсюЗадачу => "на всю задачу",
            Решение::Отказ => "запретить",
        }
    }
}

/// Что покрыто разрешением на задачу.
///
/// Хранится не по возможности, а по возможности и уровню: «разрешить
/// на задачу» для записи и для удаления — не одно и то же, а
/// возможности у них разные, а вот уровни бывают одинаковыми.
#[derive(Debug, Clone, Default)]
pub struct Разрешения {
    /// Возможности, разрешённые на всю задачу.
    pub возможности: BTreeSet<String>,
}

impl Разрешения {
    pub fn пусто() -> Self {
        Self::default()
    }

    /// Разрешена ли возможность на всю задачу.
    pub fn даёт(&self, capability: &str) -> bool {
        self.возможности.contains(capability)
    }

    /// Запомнить решение пользователя.
    ///
    /// Решение действует только внутри задачи: при новом запуске всё
    /// спрашивается заново. Постоянное разрешение — это уже не
    /// подтверждение, а выданный доступ, и выдавать его молча нельзя.
    pub fn запомнить(&mut self, capability: &str, решение: Решение) {
        if решение == Решение::ВсюЗадачу {
            self.возможности.insert(capability.to_string());
        }
    }
}

/// Нужно ли спрашивать про этот вызов.
///
/// Отдельная функция, чтобы решение принималось в одном месте. Проверка
/// размазана по трём слоям — циклу, команде и инструменту — и тогда
/// непонятно, кто же на самом деле спросил пользователя.
pub fn спрашивать(
    capability: &str,
    args: &serde_json::Value,
    settings: &Settings,
    разрешения: &Разрешения,
) -> Option<Уровень> {
    let ур = уровень(capability, args);
    if !ур.спрашивает(settings.approval_mode) {
        return None;
    }
    // Уже разрешено на задачу — не спрашиваем второй раз.
    if разрешения.даёт(capability) {
        return None;
    }
    Some(ур)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn настройки(режим: ApprovalMode) -> Settings {
        let mut s = Settings::default();
        s.approval_mode = режим;
        s
    }

    #[test]
    fn чтение_не_опасно_при_любом_режиме() {
        assert_eq!(уровень("files.read", &json!({"path": "x"})), Уровень::L3);
        assert!(!Уровень::L3.спрашивает(ApprovalMode::Risky));
        assert!(!Уровень::L3.спрашивает(ApprovalMode::Confirm) == false);
    }

    /// Режим «всегда спрашивать» пользователь выбрал сам — он должен
    /// действовать и на чтении.
    #[test]
    fn всегда_спрашивает_и_на_чтении() {
        assert!(Уровень::L3.спрашивает(ApprovalMode::Confirm));
    }

    #[test]
    fn не_спрашивает_при_режиме_без_подтверждений() {
        assert!(!Уровень::L1.спрашивает(ApprovalMode::Auto));
        assert!(!Уровень::L2.спрашивает(ApprovalMode::Auto));
    }

    /// Режим по умолчанию: спрашиваем про изменение, не спрашиваем про
    /// чтение.
    #[test]
    fn по_умолчанию_спрашиваем_про_изменение() {
        let р = ApprovalMode::Risky;
        assert!(!Уровень::L3.спрашивает(р));
        assert!(Уровень::L2.спрашивает(р));
        assert!(Уровень::L1.спрашивает(р));
    }

    /// Необратимые действия — L1, изменяющие — L2. Ошибка здесь стоит
    /// пользователю данных, поэтому проверка отдельная.
    #[test]
    fn удаление_опаснее_записи() {
        assert_eq!(уровень("files.delete", &json!({})), Уровень::L2);
        assert_eq!(
            уровень("files.delete", &json!({"recursive": true})),
            Уровень::L1
        );
        assert_eq!(уровень("files.write", &json!({})), Уровень::L2);
        assert_eq!(уровень("web.fetch", &json!({})), Уровень::L1);
        assert_eq!(уровень("apps.launch", &json!({})), Уровень::L1);
    }

    /// Уровни должны идти в порядке опасности, иначе сравнение `<`
    /// в сортировке перевернёт смысл.
    #[test]
    fn уровни_упорядочены_по_опасности() {
        assert!(Уровень::L1 > Уровень::L2);
        assert!(Уровень::L2 > Уровень::L3);
    }

    /// Одно «на всю задачу» покрывает последующие вызовы. Иначе
    /// десятьшаговая операция даст десять вопросов, и защита станет
    /// театральной.
    #[test]
    fn разрешение_на_задачу_покрывает_повторные_вызовы() {
        let s = настройки(ApprovalMode::Risky);
        let арг = json!({"path": "a.txt"});
        let mut разр = Разрешения::пусто();

        assert!(спрашивать("files.write", &арг, &s, &разр).is_some());
        разр.запомнить("files.write", Решение::ВсюЗадачу);
        assert!(спрашивать("files.write", &арг, &s, &разр).is_none());
    }

    /// «Только этот раз» не должен запоминаться: иначе кнопка с таким
    /// названием врёт.
    #[test]
    fn решение_на_один_раз_не_запоминается() {
        let s = настройки(ApprovalMode::Risky);
        let mut разр = Разрешения::пусто();
        разр.запомнить("files.write", Решение::ОдинРаз);
        assert!(разр.возможности.is_empty());
        assert!(
            спрашивать("files.write", &json!({}), &s, &разр).is_some(),
            "после «только этот раз» должно спрашивать снова"
        );
    }

    /// Разрешение на одну возможность не должно тихо разрешать другую.
    #[test]
    fn разрешение_не_распространяется_на_другие_возможности() {
        let s = настройки(ApprovalMode::Risky);
        let mut разр = Разрешения::пусто();
        разр.запомнить("files.write", Решение::ВсюЗадачу);
        assert!(спрашивать("files.delete", &json!({}), &s, &разр).is_some());
        assert!(спрашивать("apps.launch", &json!({}), &s, &разр).is_some());
    }

    /// Имена решений на проводе.
///
/// Интерфейс отправляет `один-раз`, `всю-задачу`, `отказ`. Если
/// `kebab-case` для кириллицы даст что-то другое, кнопки перестанут
/// работать — и это выяснится только при нажатии. Поэтому имена
/// зафиксированы тестом, а не взяты «как получится».
#[test]
fn имена_решений_совпадают_с_интерфейсом() {
    for (решение, ожидаемое) in [
        (Решение::ОдинРаз, "один-раз"),
        (Решение::ВсюЗадачу, "всю-задачу"),
        (Решение::Отказ, "отказ"),
    ] {
        let текст = serde_json::to_string(&решение).expect("сериализация решения");
        assert_eq!(
            текст.trim_matches('"'),
            ожидаемое,
            "интерфейс ждёт «{ожидаемое}», Rust отдаёт {текст}"
        );
    }
}

#[test]
fn отказ_ничего_не_разрешает() {
        assert!(!Решение::Отказ.разрешает());
        assert!(Решение::ОдинРаз.разрешает());
        assert!(Решение::ВсюЗадачу.разрешает());
    }

    /// Название и пояснение не должны совпадать: интерфейс показывает
    /// оба, и совпадение читается как «выводится повторно».
    #[test]
    fn название_и_пояснение_различаются() {
        for ур in [Уровень::L1, Уровень::L2, Уровень::L3] {
            assert_ne!(ур.название(), ур.пояснение());
            assert!(!ур.название().is_empty() && !ур.пояснение().is_empty());
        }
    }
}