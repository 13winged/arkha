// Дерево доступности: второй способ найти элемент окна.
//
// Зачем он нужен при живом `EnumChildWindows`. Окна Win32 — это
// «встроенные» элементы: кнопка в диалоге, поле ввода, пункт меню —
// всё это отдельное окно со своим дескриптором. Приложения, которые
// рисуют интерфейс сами — Chrome, Telegram, VS Code, Discord, —
// дочерних окон не создают вообще. Всё у них нарисованное, и
// `EnumChildWindows` возвращает пустоту. На живой проверке так не
// нашлось ни «Сохранить», ни «ОК» в этих программах.
//
// UI Automation решает это иначе: программа, уважающая
// доступность, отдаёт те же кнопки как элементы дерева. Electron
// отдаёт, потому иначе им нечем пользоваться голосовым управлением
// и скринридерами.
//
// Здесь две вещи, которых нет у окон.
//
// **Нажатие без фокуса.** У элемента есть `InvokePattern`:
// приложение само выполняет действие. Окно не выходит вперёд,
// чужой ввод не перехватывается, и блокировка фокуса Windows
// становится непричастной. Это же снимает настоящую причину отказов
// `windows.focus`, а не маскирует её.
//
// **Поиск по имени элемента.** Имя кнопки — её надпись, и именно
// её видит человек. Это тот же контракт, что у окон: агент называет
// текст, а не координату.
//
// Чего здесь нет. Клика по координатам: если элемент найден, но
// `InvokePattern` у него нет, мы не вычисляем точку и не тыкаем в
// неё — возвращаем отказ с типом элемента. Молчаливый переход на
// координату означал бы, что защита держится на честности вызывающего
// кода, а не на устройстве API.

use windows::Win32::Foundation::{HWND, RECT};
use windows::Win32::System::Com::{
    CLSCTX_INPROC_SERVER, COINIT_MULTITHREADED, CoCreateInstance, CoInitializeEx, CoUninitialize,
};
use windows::Win32::UI::Accessibility::{
    CUIAutomation8, IUIAutomation, IUIAutomationElement, IUIAutomationInvokePattern,
    TreeScope_Descendants, UIA_ButtonControlTypeId, UIA_CheckBoxControlTypeId,
    UIA_EditControlTypeId, UIA_HyperlinkControlTypeId, UIA_InvokePatternId,
    UIA_ListItemControlTypeId, UIA_MenuItemControlTypeId, UIA_RadioButtonControlTypeId,
    UIA_TabItemControlTypeId, UIA_TextControlTypeId,
};

/// Типы элементов, которые имеет смысл нажимать или в которые писать.
///
/// Список закрытый намеренно. Дерево Electron может содержать
/// тысячи узлов, а нажатие нужно в единицах. Пропуск редкого типа
/// стоит одного отказа «элемент не найден», а не обхода всей
/// программы на каждый клик.
const ДЕЙСТВИТЕЛЬНЫЕ_ТИПЫ: &[(i32, &str)] = &[
    (UIA_ButtonControlTypeId.0, "кнопка"),
    (UIA_HyperlinkControlTypeId.0, "ссылка"),
    (UIA_MenuItemControlTypeId.0, "пункт меню"),
    (UIA_CheckBoxControlTypeId.0, "флажок"),
    (UIA_RadioButtonControlTypeId.0, "переключатель"),
    (UIA_TabItemControlTypeId.0, "вкладка"),
    (UIA_ListItemControlTypeId.0, "элемент списка"),
    (UIA_EditControlTypeId.0, "поле ввода"),
    (UIA_TextControlTypeId.0, "текст"),
];

/// Больше этого — повод не искать, а ждать. Зависшая программа
/// держит дерево открытым и обход не возвращается: действие L1
/// обязано быть ограничено по времени, иначе секретарь замирает
/// на чужой сломанной программе.
const ПОТОЛОК_ЭЛЕМЕНТОВ: i32 = 3000;

/// COM на текущем потоке, со снятием.
///
/// Отдельная структура, а не два вызова `CoInitializeEx` в разных
/// местах: забытый `CoUninitialize` оставляет счётчик на потоке
/// навсегда, и следующая инициализация сделает вид, что COM уже есть.
pub struct Com {
    /// Снимать ли по завершении.
    снимать: bool,
}

impl Com {
    fn поднять() -> Self {
        let код = unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) };
        // `S_FALSE` — COM на потоке уже есть, но мы его запросили и
        // обязательно должны снять. `RPC_E_CHANGED_MODE` — поток уже
        // в STA, там снимать нечего и нельзя.
        Self { снимать: код.is_ok() || код == windows::Win32::Foundation::S_FALSE }
    }
}

impl Drop for Com {
    fn drop(&mut self) {
        if self.снимать {
            unsafe { CoUninitialize() };
        }
    }
}

/// Элемент дерева доступности, подходящий под запрос.
pub struct Элемент {
    /// Надпись — её человек и видит.
    pub текст: String,
    /// Тип на человеческом языке, для отказа и для модели.
    pub вид: &'static str,
    /// Числовой тип из API: для разбора причин отказа.
    pub код_вида: i32,
    /// Прямоугольник в экранных координатах. Для отчёта, не для
    /// клика: координаты не передаются наружу.
    pub рамка: RECT,
    /// Сам элемент: чтобы нажать без поиска заново.
    pub элемент: IUIAutomationElement,
}

/// Найденные элементы вместе с COM, который их держит.
///
/// Порядок полей здесь не случайность, а требование COM. Поле
/// `элементы` объявлено **первым**, а `guard` — вторым, потому что
/// Rust снимает поля сверху вниз: сначала умирает объект
/// автоматизации внутри элементов, и только потом снимается COM на
/// потоке. Обратный порядок — вызов `CoUninitialize` при живом
/// объекте — роняет процесс с нарушением доступа, и это проверено
/// на живой машине: тест падал именно так.
pub struct Найденные {
    pub элементы: Vec<Элемент>,
    guard: Com,
}

impl Элемент {
    fn вид_по_коду(код: i32) -> &'static str {
        ДЕЙСТВИТЕЛЬНЫЕ_ТИПЫ
            .iter()
            .find(|(к, _)| *к == код)
            .map(|(_, имя)| *имя)
            .unwrap_or("элемент")
    }

    fn годится(&self) -> bool {
        // За границей экрана нажать нельзя: приложение не сработает,
        // а человек увидит «секретарь нажал и ничего не произошло».
        // Недоступные свойства читаем как «не годится»: элемент,
        // про который ничего не известно, — это элемент, о котором
        // нельзя честно сказать, что он нажимаем.
        let включён = unsafe { self.элемент.CurrentIsEnabled() }
            .map(|и| и.as_bool())
            .unwrap_or(false);
        if !включён {
            return false;
        }
        let за_экраном = unsafe { self.элемент.CurrentIsOffscreen() }
            .map(|и| и.as_bool())
            .unwrap_or(true);
        if за_экраном {
            return false;
        }
        let р = &self.рамка;
        // Нулевая рамка — свёрнутое или невидимое. В Win32-пути эту
        // же проверку делает `GetWindowRect`; здесь она обязана быть
        // своей, потому что рамка приходит из другого API и о пустом
        // прямоугольнике там не сообщают.
        р.right > р.left && р.bottom > р.top
    }
}

/// Автоматизация для одного окна. Живёт недолго и только на время
/// одного действия: держать COM-объект постоянно незачем, а утечка
/// делает дерево окна «занятым» для следующего нашего же поиска.
struct Автоматизация {
    /// Объект. Объявлен **первым**, чтобы снимался раньше `guard`.
    объект: IUIAutomation,
    guard: Com,
}

impl Автоматизация {
    fn создать() -> Option<Self> {
        let guard = Com::поднять();
        // Идентификатор передаётся по ссылке, а `None` вместо внешнего
        // агрегирования — потому что мы не оборачиваем объект в свой.
        let объект = unsafe { CoCreateInstance(&CUIAutomation8, None, CLSCTX_INPROC_SERVER) }.ok()?;
        Some(Self { объект, guard })
    }
}

/// Найти элементы с подходящей надписью внутри окна.
///
/// Обход дерева целиком с фильтром здесь, а не условие по имени в
/// API: у UI Automation нет поиска по подстроке, условие умеет
/// только точное совпадение. А человек и агент говорят «Сохранить»,
/// имея в виду «Сохранить как…» и «Сохранить проект».
///
/// Пустой `текст` означает «перечислить видимое» — этим пользуется
/// отказ, чтобы показать модели, что в окне вообще есть.
pub fn найти(родитель: HWND, текст: &str) -> Найденные {
    let игла = текст.trim().to_lowercase();
    let mut элементы = Vec::new();
    let Some(авто) = Автоматизация::создать() else {
        // Нет автоматизации — значит, дерева не будет. Это не
        // ошибка, а «здесь нечего искать»: вызывающий решает сам.
        return Найденные { элементы, guard: Com::поднять() };
    };
    if let Ok(корень) = unsafe { авто.объект.ElementFromHandle(родитель) }
        && let Ok(условие) = unsafe { авто.объект.CreateTrueCondition() }
        && let Ok(все) = unsafe { корень.FindAll(TreeScope_Descendants, &условие) }
    {
        let длина = unsafe { все.Length() }.unwrap_or(0).min(ПОТОЛОК_ЭЛЕМЕНТОВ);
        for индекс in 0..длина {
            let Ok(элемент) = (unsafe { все.GetElement(индекс) }) else {
                // Элемент мог исчезнуть между обходом и чтением:
                // список интерфейса меняется сам. Пропускаем.
                continue;
            };
            let код_вида = match unsafe { элемент.CurrentControlType() } {
                Ok(к) => к.0,
                Err(_) => continue,
            };
            if !ДЕЙСТВИТЕЛЬНЫЕ_ТИПЫ.iter().any(|(к, _)| *к == код_вида) {
                continue;
            }
            let Ok(надпись) = (unsafe { элемент.CurrentName() }) else {
                continue;
            };
            let текст_элемента = надпись.to_string().trim().to_string();
            if текст_элемента.is_empty() {
                continue;
            }
            if !игла.is_empty() && !текст_элемента.to_lowercase().contains(&игла) {
                continue;
            }
            let Ok(рамка) = (unsafe { элемент.CurrentBoundingRectangle() }) else {
                continue;
            };
            let найденный = Элемент {
                текст: текст_элемента,
                вид: Элемент::вид_по_коду(код_вида),
                код_вида,
                рамка,
                элемент,
            };
            if найденный.годится() {
                элементы.push(найденный);
            }
        }
    }
    // `guard` переезжает из `авто` сюда, а вместе с ним и COM: к
    // этому моменту обход закончен, но элементы ещё будут нажаты.
    Найденные { элементы, guard: авто.guard }
}

/// Нажать элемент через `InvokePattern`, без перехвата фокуса.
///
/// Что произошло внутри, остаётся на стороне приложения: мы не
/// знаем и не должны знать, что именно оно сделало. Значит, и
/// проверить результат можно было бы только после — но для нажатия
/// это лишнее: успех вызова `Invoke` и есть результат.
///
/// Ошибка приходит текстом от Windows, и это полезно: в отказе видно
/// «элемент не поддерживает нажатие» или «нет доступа», и модель
/// знает, что делать дальше.
pub fn нажать(э: &Элемент) -> Result<(), String> {
    let шаблон: IUIAutomationInvokePattern = match unsafe {
        э.элемент.GetCurrentPatternAs(UIA_InvokePatternId)
    } {
        Ok(ш) => ш,
        Err(о) => {
            return Err(format!(
                "{} не нажимается напрямую: у элемента нет действия «нажать» ({о})",
                э.вид
            ));
        }
    };
    unsafe { шаблон.Invoke() }.map_err(|о| format!("приложение отклонило нажатие: {о}"))
}

/// Подписи для отказа: что вообще нашлось.
///
/// Отдельная функция, а не `найти(окно, "")` в вызывающем коде:
/// пустой поиск меняет смысл аргумента на «всё подряд», и однажды
/// кто-то это вызовет с пробелом и получит не отказ, а пустоту.
pub fn подписи(родитель: HWND) -> Vec<String> {
    let перечисленные = найти(родитель, "");
    let mut видимые: Vec<String> = перечисленные
        .элементы
        .into_iter()
        .map(|э| format!("{} «{}»", э.вид, э.текст))
        .collect();
    // Порядок дерева неустойчив между прогонами: приложение
    // перестраивает узлы. Для модели важно множество подписей, а не
    // их порядок, но нестабильный список всё равно мешает читать
    // отказ, поэтому сортируем.
    видимые.sort();
    видимые.dedup();
    видимые
}

/// Сколько узлов в дереве. Только для диагностики и тестов: пустой
/// результат поиска при непустом дереве означает, что фильтр по типу
/// слишком узок, а не что элемента нет.
pub fn размер_дерева(родитель: HWND) -> i32 {
    let Some(авто) = Автоматизация::создать() else {
        return -1;
    };
    let Ok(корень) = (unsafe { авто.объект.ElementFromHandle(родитель) }) else {
        return -1;
    };
    let Ok(условие) = (unsafe { авто.объект.CreateTrueCondition() }) else {
        return -1;
    };
    unsafe { корень.FindAll(TreeScope_Descendants, &условие) }
        .ok()
        .and_then(|в| unsafe { в.Length() }.ok())
        .unwrap_or(-1)
}

/// Признак того, что окно отдаёт дерево доступности.
///
/// Нужен гейту: «инструмент вернул пусто» и «у окна нет дерева» —
/// разные вещи, и путать их в отказе нельзя.
pub fn окно_живое(родитель: HWND) -> bool {
    размер_дерева(родитель) > 0
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Типы, которые мы умеем нажимать, обязаны быть узнаваемы.
    /// Неизвестный код возвращается как «элемент», и это молча
    /// ломает отказ: вместо «это флажок» модель получит «элемент»
    /// и не поймёт, что нажимать можно было.
    #[test]
    fn каждый_разрешённый_тип_имеет_название() {
        for (код, имя) in ДЕЙСТВИТЕЛЬНЫЕ_ТИПЫ {
            assert_eq!(Элемент::вид_по_коду(*код), *имя);
            assert!(!имя.is_empty());
        }
    }

    /// Тип вне списка остаётся «элемент» и не должен совпасть ни с
    /// одним настоящим названием: иначе отказ врёт о том, что это.
    #[test]
    fn неизвестный_тип_не_выдаёт_себя_за_известный() {
        assert_eq!(Элемент::вид_по_коду(99999), "элемент");
    }

    /// Потолок обхода обязан быть положительным и разумным: ноль
    /// означал бы «не искать ничего», а миллион — «зависнуть на
    /// сломанной программе».
    #[test]
    fn потолок_обхода_разумный() {
        assert!(ПОТОЛОК_ЭЛЕМЕНТОВ > 0, "потолок не должен быть нулём");
        assert!(ПОТОЛОК_ЭЛЕМЕНТОВ <= 10_000, "потолок слишком высок, обход затянется");
    }

    /// Пустой поиск не должен паниковать на окне без дерева:
    /// у обычного «Блокнота» дерево есть, у консоли — может не быть.
    #[test]
    fn поиск_на_несуществующем_окне_пуст_а_не_опасен() {
        let фантом = HWND(0xFFFF_FFFFu32 as *mut core::ffi::c_void);
        assert!(найти(фантом, "Сохранить").элементы.is_empty());
        assert!(размер_дерева(фантом) <= 0);
    }
}