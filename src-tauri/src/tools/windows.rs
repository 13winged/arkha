// Чтение окон. Только чтение.
//
// Почему отдельный файл и отдельная возможность, а не всё в
// `windows.control`: управление — L1 («это необратимо»), и подтверждение
// спрашивается каждый раз. Список окон необратимым быть не может: он
// ничего не меняет. Если отнести чтение к `windows.control`, то
// секретарь, который просто посмотрел, что открыто, будет спрашивать
// разрешение — и человек перестанет читать ответы.
//
// Ничего здесь не меняет состояние компьютера. Ни клика, ни ввода, ни
// запуска процесса — всё это в соседних модулях и под L1.

use serde_json::{json, Value};

use windows::core::BOOL;
use windows::Win32::Foundation::{HWND, LPARAM};
use windows::Win32::UI::WindowsAndMessaging::{
    EnumWindows, GetForegroundWindow, GetWindowTextLengthW, GetWindowTextW, IsWindowVisible,
};

use super::{Tool, ToolError, ToolOutput, ToolSpec};
use crate::permissions::Settings;

/// Окно, как его видит человек.
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct Окно {
    /// Числовой дескриптор. Модели он бесполезен, но нужен для
    /// следующих действий — вернуть фокус именно этому окну.
    pub hwnd: isize,
    /// Заголовок, как в панели задач.
    pub заголовок: String,
    /// Видно ли окно. Скрытые окна перечисляются, но выбирать их
    /// нельзя: фокус на невидимом окне выглядит как «ничего не
    /// произошло».
    pub видимое: bool,
}

/// Все видимые окна с непустым заголовком.
///
/// Заголовок обязателен: без него в списке оказываются служебные
/// окна, и модель пытается переключиться на «Program Manager», что
/// для человека выглядит как поломка.
pub fn окна() -> Vec<Окно> {
    // Параметр колбэка — сырой указатель на вектор. Он всегда
    // валиден: перебор вызывается только внутри этой функции, и
    // вектор живёт до её конца.
    let mut список: Vec<Окно> = Vec::new();

    unsafe extern "system" fn перебор(hwnd: HWND, lparam: LPARAM) -> BOOL {
        let список = unsafe { &mut *(lparam.0 as *mut Vec<Окно>) };

        let длина = unsafe { GetWindowTextLengthW(hwnd) };
        if длина > 0 {
            let mut буфер = vec![0u16; длина as usize + 1];
            let получено = unsafe { GetWindowTextW(hwnd, &mut буфер) };
            if получено > 0 {
                let заголовок = String::from_utf16_lossy(&буфер[..получено as usize]);
                let заголовок = заголовок.trim().to_string();
                if !заголовок.is_empty() {
                    список.push(Окно {
                        hwnd: hwnd.0 as isize,
                        заголовок,
                        видимое: unsafe { IsWindowVisible(hwnd) }.as_bool(),
                    });
                }
            }
        }
        // TRUE: продолжать перебор. FALSE остановил бы его на первом
        // же окне, и список был бы из одной строки.
        BOOL(1)
    }

    unsafe {
        let _ = EnumWindows(
            Some(перебор),
            LPARAM(&mut список as *mut Vec<Окно> as isize),
        );
    }
    // Порядок с диска произволен и меняется от запуска к запуску.
    // Список уходит модели — и в кэш префиксов, поэтому сортируем.
    список.sort_by(|а, б| а.заголовок.cmp(&б.заголовок));
    список
}

/// Заголовок окна, на котором сейчас фокус.
pub fn активное() -> Option<Окно> {
    let hwnd = unsafe { GetForegroundWindow() };
    if hwnd.0.is_null() {
        return None;
    }
    let длина = unsafe { GetWindowTextLengthW(hwnd) };
    if длина <= 0 {
        return None;
    }
    let mut буфер = vec![0u16; длина as usize + 1];
    let получено = unsafe { GetWindowTextW(hwnd, &mut буфер) };
    if получено <= 0 {
        return None;
    }
    Some(Окно {
        hwnd: hwnd.0 as isize,
        заголовок: String::from_utf16_lossy(&буфер[..получено as usize])
            .trim()
            .to_string(),
        видимое: true,
    })
}

/// Окна, которые имеет смысл показывать человеку.
///
/// Перебор системных окон возвращает сотни записей: `Default IME`,
/// `BroadcastListenerWindow`, окна .NET. У них есть заголовок, но
/// человек их не видит и не может о них думать. Список из двухсот
/// таких окон не помогает — в нём невозможно найти нужное, а модель
/// тратит на него окно целиком.
///
/// Поэтому наружу идут только видимые окна с непустым заголовком.
pub fn видимые() -> Vec<Окно> {
    окна()
        .into_iter()
        .filter(|о| о.видимое)
        .collect()
}

/// Сколько окон показывать за раз.
///
/// Число от бренда, а не от расчёта: за столько окон человек
/// различает нужное взглядом, не читая. Дальше он всё равно просит
/// показать конкретное. Значение выведено здесь намеренно, чтобы
/// увеличение выглядело решением, а не правкой константы по ходу.
pub const МАКСИМУМ: usize = 40;

/// Найти окно по куску заголовка.
///
/// Подстрока, а не точное совпадение: человек скажет «блокнот», а в
/// заголовке «Блокнот — заметка.txt». Возвращаем все совпавшие, чтобы
/// модель увидела, что выбор неоднозначен, и спросила, а не угадала.
///
/// Только видимые: переключиться на скрытое окно нельзя, и поиск
/// среди них только мешает.
pub fn найти(подстрока: &str) -> Vec<Окно> {
    let игла = подстрока.trim().to_lowercase();
    if игла.is_empty() {
        return Vec::new();
    }
    видимые()
        .into_iter()
        .filter(|о| о.заголовок.to_lowercase().contains(&игла))
        .collect()
}

/// Список открытых окон.
pub struct СписокОкон;

impl Tool for СписокОкон {
    fn spec(&self, _s: &Settings) -> ToolSpec {
        ToolSpec {
            id: "windows.list".into(),
            // Отдельная возможность от `windows.control`: чтение
            // ничего не меняет и не должно спрашивать разрешения.
            capability: "windows.read".into(),
            name: "Список окон".into(),
            description: "Показать открытые окна и то, на котором сейчас фокус. \
                          Ничего не меняет. Пользуйся перед переключением: нельзя \
                          переключиться на окно, которого нет."
                .into(),
            parameters: json!({ "type": "object", "properties": {}, "required": [] }),
            side_effecting: false,
        }
    }

    fn call(&self, _args: &Value, _s: &Settings) -> Result<ToolOutput, ToolError> {
        let всё = видимые();
        let активное = активное();
        let hwnd_активного = активное.as_ref().map(|а| а.hwnd);
        if всё.is_empty() {
            return Ok(ToolOutput::read(
                "Открытых окон с заголовками нет.".to_string(),
                "окон: 0",
            ));
        }
        let показан: Vec<String> = всё
            .iter()
            .take(МАКСИМУМ)
            .map(|о| {
                let метка = match hwnd_активного {
                    Some(h) if h == о.hwnd => " ← сейчас открыто",
                    _ => "",
                };
                format!("- [{}] {}{}", о.hwnd, о.заголовок, метка)
            })
            .collect();
        let текст = показан.join("\n");
        // Об усечении говорим прямо: иначе модель решит, что других
        // окон нет, и не спросит про нужное.
        let текст = if всё.len() > МАКСИМУМ {
            format!(
                "{текст}\n\nПоказаны первые {МАКСИМУМ} из {} окон. Остальные найди через \
                 windows.find по названию.",
                всё.len()
            )
        } else {
            текст
        };
        Ok(ToolOutput::read(текст, format!("окон: {}", всё.len())))
    }
}

/// Найти окно по названию.
pub struct НайтиОкно;

impl Tool for НайтиОкно {
    fn spec(&self, _s: &Settings) -> ToolSpec {
        ToolSpec {
            id: "windows.find".into(),
            capability: "windows.read".into(),
            name: "Найти окно".into(),
            description: "Найти открытое окно по части названия. Возвращает все \
                          совпавшие: если их больше одного, выбор неоднозначен и \
                          нужно спросить человека, а не выбрать первое. Ничего не \
                          меняет."
                .into(),
            parameters: json!({
                "type": "object",
                "properties": {
                    "title": { "type": "string", "description": "часть заголовка окна" }
                },
                "required": ["title"]
            }),
            side_effecting: false,
        }
    }

    fn call(&self, args: &Value, _s: &Settings) -> Result<ToolOutput, ToolError> {
        let Some(имя) = args.get("title").and_then(|v| v.as_str()) else {
            return Err(ToolError::BadArgs("нет поля title".into()));
        };
        let найденные = найти(имя);
        if найденные.is_empty() {
            // Показываем, что есть: иначе модель будет угадывать
            // названия по нескольку заходов.
            let открытые = видимые();
            let есть: Vec<&str> = открытые.iter().map(|о| о.заголовок.as_str()).collect();
            return Err(ToolError::Unknown(format!(
                "окна с «{имя}» в названии нет. Открыто: {}",
                if есть.is_empty() {
                    "ни одного".to_string()
                } else {
                    есть.join("; ")
                }
            )));
        }
        let текст = найденные
            .iter()
            .map(|о| format!("- [{}] {}", о.hwnd, о.заголовок))
            .collect::<Vec<_>>()
            .join("\n");
        Ok(ToolOutput::read(
            текст,
            format!("найдено окон: {}", найденные.len()),
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Перебор окон не должен падать и не должен отдавать пустые
    /// заголовки: служебные окна без заголовка в список не попадают.
    #[test]
    fn перебор_окон_не_падает() {
        let всё = окна();
        for о in &всё {
            assert!(!о.заголовок.is_empty(), "окно без заголовка: {о:?}");
            assert_ne!(о.hwnd, 0, "нулевой дескриптор окна");
        }
    }

    /// Порядок не должен зависеть от порядка в системе: список уходит
    /// модели и в кэш префиксов.
    #[test]
    fn список_отсортирован() {
        let a = окна();
        let b = окна();
        let имена: Vec<&str> = a.iter().map(|о| о.заголовок.as_str()).collect();
        let mut отсортированные = имена.clone();
        отсортированные.sort();
        assert_eq!(имена, отсортированные, "окна должны идти по алфавиту");
        assert_eq!(a, b, "два перебора должны совпасть");
    }

    /// Поиск подстрокой, а не точным совпадением: человек говорит
    /// «блокнот», а в заголовке «Блокнот — заметка.txt».
    #[test]
    fn поиск_нечувствителен_к_регистру() {
        let всё = видимые();
        let Some(первое) = всё.first() else { return };
        let кусок: String = первое.заголовок.chars().take(3).collect();
        if кусок.trim().is_empty() {
            return;
        }
        let строчными = кусок.to_lowercase();
        let результат = найти(&строчными);
        assert!(
            результат.iter().any(|о| о.hwnd == первое.hwnd),
            "поиск по «{строчными}» должен найти «{}»",
            первое.заголовок
        );
    }

    /// Служебные окна не должны попадать ни в список, ни в поиск.
    ///
    /// Без фильтра перебор отдаёт сотни записей: `Default IME`,
    /// `BroadcastListenerWindow`, окна .NET. Заголовок у них есть,
    /// человек их не видит, а модель в них тонет. На живой машине
    /// список содержал больше двухсот таких окон.
    #[test]
    fn видимые_отбрасывают_служебные() {
        let всё = окна();
        assert!(
            всё.len() > видимые().len(),
            "на этой машине должны быть невидимые окна, иначе тест ничего не проверяет"
        );
        for о in &видимые() {
            assert!(о.видимое, "в видимых попало невидимое окно: {о:?}");
        }
    }

    /// Поиск не должен выдавать невидимые окна: переключиться на
    /// скрытое нельзя, и такая попытка выглядит как «ничего не
    /// произошло».
    #[test]
    fn поиск_не_выдаёт_невидимые() {
        let все = окна();
        let скрытые: Vec<&Окно> = все.iter().filter(|о| !о.видимое).collect();
        let Some(скрытое) = скрытые.first() else { return };
        let кусок = скрытое
            .заголовок
            .chars()
            .take(4)
            .collect::<String>()
            .to_lowercase();
        if кусок.trim().is_empty() {
            return;
        }
        assert!(
            найти(&кусок).iter().all(|о| о.видимое),
            "поиск вернул невидимое окно по «{кусок}»"
        );
    }

    #[test]
    fn пустой_запрос_не_находит_ничего() {
        assert!(найти("").is_empty());
        assert!(найти("   ").is_empty());
    }

    /// Список окон не должен спрашивать разрешения: он ничего не
    /// меняет. Проверяем уровень напрямую, а не через инструмент.
    #[test]
    fn чтение_окон_не_требует_подтверждения() {
        use crate::agent::approvals::{уровень, Уровень};
        use crate::permissions::ApprovalMode;
        assert_eq!(уровень("windows.read", &json!({})), Уровень::L3);
        assert!(!Уровень::L3.спрашивает(ApprovalMode::Risky));
    }
}
