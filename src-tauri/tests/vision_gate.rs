//! Гейт зрения на живом железе.
//!
//! Юнит-тесты доказывают, что из байтов собирается запрос. Это не
//! говорит о главном: **увидит ли модель картинку**.
//!
//! Здесь две разные вещи, и их нельзя смешивать.
//!
//! Первая — сама зрящая модель. GLM-4.6V-Flash отвечает на картинку
//! напрямую, минуя агента. Проверяется, что она вообще видит: ответ
//! сверяется с тем, что нарисовано на испытательной картинке, где
//! правильный ответ известен заранее.
//!
//! Вторая — агент. У него глаз нет, зрение закрыто отдельной моделью,
//! и про это модель обязана знать. Раньше отказы из
//! `capabilities.json` доходили только до интерфейса, и на задаче с
//! картинкой агент отвечал «нет доступа к папке» — правдоподобно и
//! неверно: человек пошёл бы чинить права, которые ни при чём.
//!
//! Запуск:
//! ```text
//! ARCHOTIC_BIN_DIR=data/bin ARCHOTIC_MODELS_DIR=<папка с gguf> \
//! ARCHOTIC_VISION_MODEL=<GLM>.gguf ARCHOTIC_VISION_MMPROJ=<mmproj>.gguf \
//!   ARCHOTIC_TEST_TIER=T3 \
//!   cargo test --test vision_gate -- --nocapture --test-threads=1
//! ```
//!
//! Без `ARCHOTIC_VISION_MODEL` гейт пропускается, а не падает: зрение
//! на профиле без нужной видеопамяти невозможно, и отсутствие модели
//! не поломка проекта.

mod common;

use std::path::{Path, PathBuf};
use std::process::{Child, Command};

const ПОРТ_ЗРЕНИЯ: u16 = 18112;
const ПОРТ_АГЕНТА: u16 = 18113;

/// Надписи на испытательной картинке.
///
/// Русские и латинские вместе: так проверяется и то, что модель видит,
/// и то, что она не путает алфавиты. Цифры — как контроль: цифры
/// не переводятся в другие символы, так что ошибка на них означает
/// не «не разобрала шрифт», а «не разглядела».
const НАДПИСИ: &[&str] = &["КОТ", "7 3 9", "ПРИВЕТ"];

/// Папка с испытательной картинкой.
fn папка() -> PathBuf {
    let d = std::env::temp_dir().join(format!("archotic-vision-{}", std::process::id()));
    std::fs::create_dir_all(&d).expect("папка для картинки");
    d
}

/// Нарисовать испытательную картинку.
///
/// Скрипт с кириллицей обязан быть в UTF-8 **с BOM**: PowerShell 5.1
/// без метки читает файл как ANSI и рисует мусор вместо букв. Тогда
/// гейт падал бы с «зрение не работает», а на самом деле не работала
/// бы разметка файла.
fn нарисовать(путь: &Path) -> Child {
    let скрипт = r#"Add-Type -AssemblyName System.Drawing
$b = New-Object System.Drawing.Bitmap 900, 620
$g = [System.Drawing.Graphics]::FromImage($b)
$g.Clear([System.Drawing.Color]::White)
$f1 = New-Object System.Drawing.Font("Arial", 90, [System.Drawing.FontStyle]::Bold)
$g.DrawString("КОТ", $f1, [System.Drawing.Brushes]::Black, 40, 30)
$f2 = New-Object System.Drawing.Font("Georgia", 110, [System.Drawing.FontStyle]::Bold)
$g.DrawString("7 3 9", $f2, [System.Drawing.Brushes]::Black, 40, 200)
$f3 = New-Object System.Drawing.Font("Verdana", 64, [System.Drawing.FontStyle]::Bold)
$g.DrawString("ПРИВЕТ", $f3, [System.Drawing.Brushes]::Black, 40, 420)
$g.Dispose()
$b.Save($PSCommandPath.Replace('.ps1', '.png'), [System.Drawing.Imaging.ImageFormat]::Png)
$b.Dispose()
"#;
    let ps = путь.with_extension("ps1");
    // BOM обязателен, см. выше.
    let mut байты = vec![0xEF, 0xBB, 0xBF];
    байты.extend_from_slice(скрипт.as_bytes());
    std::fs::write(&ps, байты).expect("записать скрипт");
    let png = ps.with_extension("png");
    let _ = std::fs::remove_file(&png);
    let ребёнок = Command::new("powershell")
        .arg("-NoProfile")
        .arg("-ExecutionPolicy")
        .arg("Bypass")
        .arg("-File")
        .arg(&ps)
        .spawn()
        .expect("запустить рисование");
    for _ in 0..50 {
        if png.exists() {
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(200));
    }
    assert!(png.exists(), "картинка не нарисовалась: {}", png.display());
    ребёнок
}

/// Модель зрения. `None` — гейт пропускается.
fn зрящая() -> Option<(PathBuf, PathBuf)> {
    let модель = std::env::var_os("ARCHOTIC_VISION_MODEL").map(PathBuf::from)?;
    let mmproj = std::env::var_os("ARCHOTIC_VISION_MMPROJ").map(PathBuf::from)?;
    if !модель.exists() {
        eprintln!("ПРОПУЩЕНО: нет модели зрения {}", модель.display());
        return None;
    }
    if !mmproj.exists() {
        eprintln!("ПРОПУЩЕНО: нет зрителя {}", mmproj.display());
        return None;
    }
    Some((модель, mmproj))
}

/// Процесс сайдкара зрения, который гасится сам.
///
/// `Child` при падении не убивает процесс, а гейт поднимает сервер в
/// четырёх тестах подряд. Без явного `kill` на втором тесте порт был бы
/// занят предыдущим, и гейт проверял бы не то.
struct Сервер {
    ребёнок: Child,
    порт: u16,
}

impl Сервер {
    fn base(&self) -> String {
        format!("http://127.0.0.1:{}", self.порт)
    }
}

impl Drop for Сервер {
    fn drop(&mut self) {
        let _ = self.ребёнок.kill();
        let _ = self.ребёнок.wait();
    }
}

/// Поднять llama-server с произвольными аргументами.
///
/// Одна функция на обе модели намеренно: агент и зрящая отличаются
/// только флагами, а две копии запуска разъедутся — так уже было с
/// адаптером модели в `s6_gate` и `common`.
///
/// `cudart` обязателен в PATH: без него сервер **молча** уходит на
/// процессор и показывает правдоподобную, но неверную скорость. Это
/// стоило получаса: 1229 МиБ видеопамяти при модели на 3.3 ГиБ — число
/// выглядит возможным, но им быть не может.
fn поднять(модель: &Path, порт: u16, флаги: &[String]) -> Сервер {
    let exe = archotic_lib::model_manager::llama_server_exe();
    let cudart = archotic_lib::model_manager::bin_dir().join("cudart");
    let mut cmd = std::process::Command::new(&exe);
    cmd.current_dir(archotic_lib::model_manager::bin_dir())
        .env(
            "PATH",
            match std::env::var("PATH") {
                Ok(p) => format!("{};{p}", cudart.display()),
                Err(_) => cudart.display().to_string(),
            },
        )
        .arg("-m")
        .arg(модель)
        .arg("-c")
        .arg("4096")
        .arg("--host")
        .arg("127.0.0.1")
        .arg("--port")
        .arg(порт.to_string())
        .arg("-np")
        .arg("1");
    for ф in флаги {
        cmd.arg(ф);
    }
    let ребёнок = cmd
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .expect("сайдкар не запустился");

    // Порт открывается раньше, чем модель загрузится: сервер слушает
    // сразу, а отвечать начинает через несколько секунд. Проверка «порт
    // открыт» проходила мгновенно, и первый запрос уходил в
    // `503 Loading model`. Готовность — это `ok` от `/health`.
    let край = std::time::Instant::now() + std::time::Duration::from_secs(180);
    loop {
        std::thread::sleep(std::time::Duration::from_millis(700));
        if готов(порт) {
            return Сервер { ребёнок, порт };
        }
        if std::time::Instant::now() > край {
            let _очистить = Сервер { ребёнок, порт };
            panic!("сайдкар на порту {порт} не поднялся за 180 секунд");
        }
    }
}

/// Модель загрузилась и готова отвечать.
fn готов(порт: u16) -> bool {
    let Ok(клиент) = reqwest::blocking::Client::builder()
        .timeout(std::time::Duration::from_secs(5))
        .build()
    else {
        return false;
    };
    клиент
        .get(format!("http://127.0.0.1:{порт}/health"))
        .send()
        .map(|r| {
            r.json::<serde_json::Value>()
                .ok()
                .and_then(|v| v["status"].as_str().map(|s| s == "ok"))
                .unwrap_or(false)
        })
        .unwrap_or(false)
}

/// Сколько слоёв зрящей модели класть на карту.
///
/// По умолчанию 0: слои в оперативке, на карте только зритель. Так
/// обе модели гарантированно помещаются рядом, и гейт проверяет
/// совместную работу, а не одиночную скорость.
///
/// `ARCHOTIC_VISION_NGL` задаёт другое. Нужен, чтобы померить, сколько
/// стоит перенос части весов на карту: у крупного кванта слой дороже,
/// и лимит считается от размера файла, а не от числа слоёв.
fn слои_зрения() -> String {
    std::env::var("ARCHOTIC_VISION_NGL").unwrap_or_else(|_| "0".to_string())
}

/// Флаги зрящей модели.
///
/// По умолчанию слои в оперативке, зритель на карте. Измерено
/// 13 октября 2026 — 3418 МиБ против 6743 МиБ при полном офлоаде.
/// Разбор в docs/10-замеры.md.
fn флаги_зрения(mmproj: &Path) -> Vec<String> {
    vec![
        "--mmproj".into(),
        mmproj.display().to_string(),
        "-ngl".into(),
        слои_зрения(),
        "--mmproj-offload".into(),
        "--jinja".into(),
    ]
}

/// Спросить зрящую модель про картинку.
fn спросить(порт: u16, png: &Path, вопрос: &str) -> String {
    let байты = std::fs::read(png).expect("прочитать картинку");
    let data = base64(&байты);
    let тело = serde_json::json!({
        "model": "local",
        "messages": [{
            "role": "user",
            "content": [
                {"type": "text", "text": вопрос},
                {"type": "image_url", "image_url": {"url": format!("data:image/png;base64,{data}")}}
            ]
        }],
        "max_tokens": 300,
        "temperature": 0
    })
    .to_string();
    post(порт, "/v1/chat/completions", &тело)
}

/// Минимальный POST через reqwest.
///
/// Свой TCP-клиент здесь был написан первым и оказался лишним: он
/// молча отдавал пустой ответ, и гейт падал с «зрение не работает»,
/// хотя модель отвечала верно. Пустой JSON разбирается без ошибки,
/// поэтому поломка не выглядела поломкой. Клиент тот же, что в
/// остальных гейтах, — с проверенной сериализацией.
fn post(порт: u16, путь: &str, тело: &str) -> String {
    let client = reqwest::blocking::Client::builder()
        .timeout(std::time::Duration::from_secs(900))
        .build()
        .expect("клиент");
    let resp = client
        .post(format!("http://127.0.0.1:{порт}{путь}"))
        .header("Content-Type", "application/json")
        .body(тело.to_string())
        .send()
        .unwrap_or_else(|e| panic!("запрос не ушёл: {e}"));
    let статус = resp.status();
    let текст = resp.text().unwrap_or_default();
    assert!(
        статус.is_success(),
        "сайдкар зрения ответил {статус}: {}",
        &текст[..текст.len().min(300)]
    );
    текст
}

/// Ответ модели без рассуждений.
///
/// GLM прогоняет рассуждение в `<think>`. Показывать его человеку
/// нельзя, но и выбрасывать надо осознанно: иногда в рассуждении
/// единственное упоминание картинки.
fn чистый(сырой: &str) -> String {
    let v: serde_json::Value = serde_json::from_str(сырой).unwrap_or_else(|_| {
        panic!("ответ не JSON: {}", &сырой[..сырой.len().min(400)])
    });
    let text = v["choices"][0]["message"]["content"].as_str().unwrap_or("");
    let без = match (text.find("<think>"), text.find("</think>")) {
        (Some(a), Some(b)) if b > a => format!("{}{}", &text[..a], &text[b + 8..]),
        _ => text.to_string(),
    };
    без.replace("<|begin_of_box|>", "")
        .replace("<|end_of_box|>", "")
        .trim()
        .to_string()
}

fn base64(данные: &[u8]) -> String {
    const АЛФАВИТ: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut вывод = String::with_capacity(данные.len().div_ceil(3) * 4);
    for кусок in данные.chunks(3) {
        let b = [кусок[0], *кусок.get(1).unwrap_or(&0), *кусок.get(2).unwrap_or(&0)];
        let n = ((b[0] as u32) << 16) | ((b[1] as u32) << 8) | b[2] as u32;
        вывод.push(АЛФАВИТ[(n >> 18) as usize & 63] as char);
        вывод.push(АЛФАВИТ[(n >> 12) as usize & 63] as char);
        вывод.push(if кусок.len() > 1 {
            АЛФАВИТ[(n >> 6) as usize & 63] as char
        } else {
            '='
        });
        вывод.push(if кусок.len() > 2 {
            АЛФАВИТ[n as usize & 63] as char
        } else {
            '='
        });
    }
    вывод
}

/// Сколько видеопамяти занято на карте целиком, МиБ.
fn vram_всего() -> Option<u64> {
    let вывод = std::process::Command::new("nvidia-smi")
        .arg("--query-gpu=memory.used")
        .arg("--format=csv,noheader,nounits")
        .output()
        .ok()?;
    String::from_utf8_lossy(&вывод.stdout)
        .trim()
        .parse()
        .ok()
}

/// Разделяемое видеопамяти для процесса, МиБ.
///
/// Возвращает `None`, если счётчика нет. Это осознанно: отсутствие
/// счётчика — повод пропустить проверку, а не повод объявить
/// переполнение. Ошибочное «нет переполнения» опаснее «не проверили».
fn shared_мб(pid: u32) -> Option<u64> {
    let вывод = std::process::Command::new("powershell")
        .arg("-NoProfile")
        .arg("-Command")
        .arg(format!(
            "$s=(Get-Counter '\\GPU Process Memory(pid_{pid}_*)\\Shared Usage' -ErrorAction SilentlyContinue).CounterSamples | Measure-Object CookedValue -Sum; if($s){{[math]::Round($s.Sum/1MB)}}else{{'нет'}}"
        ))
        .output()
        .ok()?;
    let текст = String::from_utf8_lossy(&вывод.stdout);
    let т = текст.trim();
    if т == "нет" || т.is_empty() {
        None
    } else {
        т.parse().ok()
    }
}

