/// Зрящая модель читает картинку.
///
/// Ответ сверяется с нарисованным: правильный ответ известен заранее,
/// поэтому «модель ответила уверенно» и «модель ответила верно» —
/// разные вещи, и гейт проверяет второе.
#[test]
fn зрение_читает_картинку() {
    let Some((модель, mmproj)) = зрящая() else {
        return;
    };
    let dir = папка();
    let png = dir.join("zrenie.png");
    let _рисунок = нарисовать(&png);

    let сайдкар = поднять(&модель, ПОРТ_ЗРЕНИЯ, &флаги_зрения(&mmproj));

    let ответ = спросить(
        ПОРТ_ЗРЕНИЯ,
        &png,
        "Напиши только текст, который написан на картинке. Без пояснений и без рассуждений.",
    );
    let ответ = чистый(&ответ);
    eprintln!("VISION-1: ответ зрящей модели: {ответ:?}");

    let mut нашлось = Vec::new();
    let mut промахи = Vec::new();
    for надпись in НАДПИСИ {
        if ответ.contains(надпись) {
            нашлось.push(*надпись);
        } else {
            промахи.push(*надпись);
        }
    }
    let shared = shared_мб(pid_на_порту(ПОРТ_ЗРЕНИЯ));
    eprintln!("VISION-1: нашлось {нашлось:?}, промахи {промахи:?}");
    eprintln!(
        "VISION-1: слои зрения {}, shared {:?} МиБ, VRAM всего {:?} МиБ",
        слои_зрения(),
        shared,
        vram_всего()
    );

    // Кириллица обязана читаться по-русски. На GLM-4.6V-Flash в кванте
    // IQ2_XXS она читалась латиницей стабильно, 5 прогонов из 5, и
    // проверка была вынужденно молчаливой. Теперь зрящая модель —
    // Qwen3-VL, где 5 из 5 верно, поэтому утверждать можно.
    //
    // Пробелы не считаются ошибкой: `7 3 9` модель пишет как `739`.
    // Это формат вывода, а не неверное чтение, и иначе гейт будет
    // ругаться на правильный ответ.
    for надпись in НАДПИСИ {
        let иском = надпись_без_пробелов(надпись, &ответ);
        assert!(
            ответ.contains(&иском),
            "на картинке написано {надпись:?}, модель ответила {ответ:?}. \
             Раньше здесь стоял GLM-4.6V-Flash и читал кириллицу латиницей; \
             если он вернулся — почините квант, молчаливая проверка тут не годится"
        );
    }

    drop(сайдкар);
}

/// Кириллица читается устойчиво, а не по случайности.
///
/// Одного прогона мало: на GLM-4.6V-Flash промах был стабильным, 5
/// из 5, поэтому «прочиталось однажды» ничего не доказывает.
/// Здесь три прогона подряд — если модель способна ошибаться, ошибка
/// показывается.
#[test]
fn кириллица_читается_устойчиво() {
    let Some((модель, mmproj)) = зрящая() else {
        return;
    };
    let dir = папка();
    let png = dir.join("zrenie2.png");
    let _рисунок = нарисовать(&png);
    let сайдкар = поднять(&модель, ПОРТ_ЗРЕНИЯ, &флаги_зрения(&mmproj));

    let mut попаданий = 0;
    let mut ответы = Vec::new();
    for _ in 0..3 {
        let ответ = чистый(&спросить(
            ПОРТ_ЗРЕНИЯ,
            &png,
            "Напиши только текст, который написан на картинке. Без пояснений.",
        ));
        ответы.push(ответ.clone());
        let все = НАДПИСИ.iter().all(|н| {
            let иском = надпись_без_пробелов(н, &ответ);
            ответ.contains(&иском)
        });
        if все {
            попаданий += 1;
        }
    }
    eprintln!("VISION-2: ответы {ответы:?}");
    eprintln!("VISION-2: все три надписи сразу в {попаданий} прогонах из 3");

    assert!(
        попаданий >= 2,
        "кириллица прочиталась полностью только в {попаданий} прогонах из 3. \
         На GLM-4.6V-Flash было 0 из 5. Ответы: {ответы:?}"
    );

    drop(сайдкар);
}

/// Пропустить лишние пробелы, которые модель ставит между надписями.
///
/// Без этого `7 3 9` не найдётся в ответе `739`. Пробелы между
/// символами — не ошибка чтения, а формат вывода.
fn надпись_без_пробелов(надпись: &str, ответ: &str) -> String {
    let слитно: String = надпись.chars().filter(|c| !c.is_whitespace()).collect();
    let слитно_ответа: String = ответ.chars().filter(|c| !c.is_whitespace()).collect();
    if слитно_ответа.contains(&слитно) {
        слитно
    } else {
        надпись.to_string()
    }
}

/// Слои агента, когда зрение поднято.
///
/// 30, а не 33. Рецепт профиля кладёт 33 слоя, и при поднятом зрении
/// это перебор: замер 13 октября 2026 дал 406 МиБ разделяемой
/// видеопамяти и 20.1 tok/s. На 30 слоях пересылок нет вовсе, 116 МиБ —
/// базовый расход Windows, он не зависит от числа слоёв.
///
/// 30 против 28 у GLM-4.6V-Flash выигрыш даёт меньший зритель:
/// 0.78 ГБ против 1.79 ГБ.
const СЛОИ_АГЕНТА_ПРИ_ЗРЕНИИ: u32 = 30;

/// Зрящая модель умеет звать инструменты, но ею это не пользуются.
///
/// Проверка не про роли, а про то, что сломано у модели, а не у нас.
/// На GLM-4.6V-Flash в аргументы попадал сырой шаблон разметки,
/// модель зациклилась и выдумала несуществующий файл. У Qwen3-VL
/// этого нет: 5 прогонов из 5 дали чистый JSON, и на задаче «найди
/// файл» она позвала инструмент, а не сочинила результат.
///
/// Если тест перестанет проходить, рецепт «зрящая модель — отдельная
/// модель» можно будет пересмотреть. А пока он остаётся: слышать
/// агентом должен Qwen3.5, у которого вызовы проверены гейтами S2–S8.
#[test]
fn зрящая_модель_зовёт_инструменты_без_мусора() {
    let Some((модель, mmproj)) = зрящая() else {
        return;
    };
    let сайдкар = поднять(&модель, ПОРТ_ЗРЕНИЯ, &флаги_зрения(&mmproj));

    let тело = serde_json::json!({
        "model": "local",
        "tools": [{
            "type": "function",
            "function": {
                "name": "find_files",
                "description": "Найти файлы в папке по подстроке имени.",
                "parameters": {
                    "type": "object",
                    "properties": {
                        "folder": {"type": "string"},
                        "query": {"type": "string"}
                    },
                    "required": ["folder", "query"]
                }
            }
        }],
        "tool_choice": "auto",
        "messages": [
            {"role": "system", "content": "Отвечай по-русски."},
            {"role": "user", "content": "Найди в папке C:\\Документы файлы со словом отчёт"}
        ],
        "max_tokens": 300,
        "temperature": 0
    })
    .to_string();

    let ответ = post(ПОРТ_ЗРЕНИЯ, "/v1/chat/completions", &тело);
    let v: serde_json::Value = serde_json::from_str(&ответ).expect("ответ не JSON");
    let вызов = v["choices"][0]["message"]["tool_calls"][0]["function"].clone();
    let имя = вызов["name"].as_str().unwrap_or_default();
    let аргументы = вызов["arguments"].as_str().unwrap_or_default();
    eprintln!("VISION-5: {имя} {аргументы}");

    assert_eq!(имя, "find_files", "модель позвала не тот инструмент");
    // Мусор в аргументах — главный признак поломки шаблона.
    assert!(
        !аргументы.contains("tool_call"),
        "в аргументы попал сырой шаблон разметки: {аргументы:?}. \
         Так вела себя GLM-4.6V-Flash"
    );
    assert!(
        !аргументы.contains("arg_key"),
        "в аргументы попали теги ключей: {аргументы:?}"
    );
    let разобран: Result<serde_json::Value, _> = serde_json::from_str(аргументы);
    assert!(
        разобран.is_ok(),
        "аргументы не разбираются как JSON: {аргументы:?}"
    );
    let разобран = разобран.unwrap();
    assert_eq!(
        разобран["folder"].as_str(),
        Some("C:\\Документы"),
        "папка передана неверно: {аргументы:?}"
    );
    assert_eq!(
        разобран["query"].as_str(),
        Some("отчёт"),
        "поисковый запрос передан неверно: {аргументы:?}"
    );

    drop(сайдкар);
}

/// Зрение и агент работают одновременно.
///
/// Это главная проверка: обе модели должны поместиться на карте и
/// отвечать вместе. Если не помещаются — зрение придётся включать
/// разменом, и это меняет конструкцию.
#[test]
fn зрение_и_агент_одновременно() {
    let Some((модель, mmproj)) = зрящая() else {
        return;
    };
    let Some(файл_агента) = common::model_файл() else {
        return;
    };
    // Агент поднимаем сами, а не через `common::поднять`: там берётся
    // рецепт профиля, а он кладёт 33 слоя, что при зрении перебор.
    let агент = поднять(
        &файл_агента,
        ПОРТ_АГЕНТА,
        &[
            "-ngl".into(),
            СЛОИ_АГЕНТА_ПРИ_ЗРЕНИИ.to_string(),
            "--jinja".into(),
            "--reasoning".into(),
            "off".into(),
        ],
    );
    let зрение = поднять(&модель, ПОРТ_ЗРЕНИЯ, &флаги_зрения(&mmproj));
    let dir = папка();
    let png = dir.join("zrenie3.png");
    let _рисунок = нарисовать(&png);

    // Оба сервера подняты. Спрашиваем зрение и агента по очереди:
    // важно, что они оба живы на одной карте.
    let ответ_зрения = чистый(&спросить(ПОРТ_ЗРЕНИЯ, &png, "Что написано на картинке? Одно предложение."));
    let shared = shared_мб(pid_на_порту(ПОРТ_АГЕНТА));
    let ответ_агента = common::спросить_текстом(
        &агент.base(),
        "Напиши одним предложением по-русски, что ты умеешь.",
    );
    eprintln!("VISION-3: зрение {ответ_зрения:?}");
    eprintln!("VISION-3: агент {ответ_агента:?}");
    eprintln!("VISION-3: shared агента {shared:?} МиБ");

    assert!(
        !ответ_зрения.is_empty(),
        "зрящая модель промолчала, агент поднялся рядом с ней"
    );
    assert!(
        !ответ_агента.is_empty(),
        "агент промолчал при поднятом зрении — либо не влезает, либо сломался"
    );
    // Слои взяты не из рецепта, а из замера, поэтому переполнения быть
    // не должно. Если есть — замер устарел или машина другая.
    if let Some(мб) = shared {
        assert!(
            мб < 400,
            "у агента {мб} МиБ разделяемой видеопамяти при {СЛОИ_АГЕНТА_ПРИ_ЗРЕНИИ} слоях — \
             начался сброс в оперативку по шине. Замер порога устарел или машина другая. \
             Разбор в docs/22-переполнение-видеопамяти.md"
        );
    } else {
        eprintln!("VISION-3: счётчик разделяемой видеопамяти недоступен, проверка пропущена");
    }

    drop(зрение);
    drop(агент);
}

/// Найти PID процесса сайдкара по порту.
///
/// Нужен, чтобы снять счётчик именно с его процесса: на карте в это
/// время может сидеть что-то ещё, и общий счётчик свалил бы пересылки
/// на нас.
fn pid_на_порту(порт: u16) -> u32 {
    let тбл = std::process::Command::new("powershell")
        .arg("-NoProfile")
        .arg("-Command")
        .arg(format!(
            "$c=Get-NetTCPConnection -LocalPort {порт} -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1; if($c){{$c.OwningProcess}}"
        ))
        .output()
        .expect("netstat");
    String::from_utf8_lossy(&тбл.stdout)
        .trim()
        .parse()
        .unwrap_or(0)
}

/// Агент честно говорит, что зрения у него нет.
///
/// Главный сценарий, ради которого чинился блок слепых зон. Раньше
/// агент отвечал на просьбу посмотреть картинку «нет доступа к
/// папке» — правдоподобно и неверно.
///
/// Проверяется не наличие слов, а отсутствие ложной причины: сказать
/// «я не вижу картинки» можно, сказать «нет доступа к папке» про
/// картинку нельзя.
#[test]
fn агент_не_выдумывает_причину_про_картинку() {
    let Some(файл_агента) = common::model_файл() else {
        return;
    };
    // Здесь слои не урезаются: проверяется поведение агента без
    // поднятого зрения, то есть ровно то, что человек видит сейчас.
    let агент = поднять(
        &файл_агента,
        ПОРТ_АГЕНТА,
        &["-ngl".into(), "33".into(), "--jinja".into(), "--reasoning".into(), "off".into()],
    );
    let ответ = common::спросить_текстом(
        &агент.base(),
        "Посмотри, что на картинке C:\\Users\\me\\Pictures\\скриншот.png",
    );
    eprintln!("VISION-4: ответ агента: {ответ:?}");

    let ложь = [
        "нет доступа к папке",
        "нет доступа к файлу",
        "не разрешена папка",
        "нужно разрешение",
    ];
    for фраза in ложь {
        assert!(
            !ответ.to_lowercase().contains(фраза),
            "агент выдумал причину «{фраза}» про картинку. Зрение недоступно — \
             он должен сказать, что не видит картинки, а не что у него нет прав. Ответ: {ответ:?}"
        );
    }
    drop(агент);
}
