// Проба русского в модели.
//
// Зачем она. При выборе моделей встаёт вопрос: умеет ли она говорить с
// человеком на его языке. Взвешенные индексы на этот вопрос не
// отвечают: в JEV Decision Index, который мы смотрели 17.10.2026,
// единственный языковой бенчмарк идёт по английскому и арабскому, а
// русского нет ни в одной дорожке. Значит утверждение «модель
// понимает по-русски» до сих пор было пересказом чужого мнения.
//
// Проба идёт по боевому пути, а не в обход него: поднимается та же
// модель, тот же системный промпт и тот же клиент, что и в
// приложении. Иначе мы измерили бы не ту модель, которой пользуется
// человек.
//
// Что проба проверяет и что нет. Механические свойства проверяются
// здесь и они устойчивы: ответ по-русски вместо английского, кнопка
// названа по-русски, телефон не выдуман. Качество связности,
// точность и полезность текста здесь **не** оцениваются: автоматика
// может проверить наличие кириллицы, но не может прочитать смысл.
// Все ответы печатаются целиком, чтобы решение принимал человек.
//
// Проба помечена `#[ignore]`: нужна настоящая модель и минуты
// времени. Запуск:
//
//   cargo test --release --manifest-path src-tauri/Cargo.toml \
//     --test russian_probe -- --ignored --nocapture --test-threads=1
//
// Нужны переменные, как у остальных гейтов:
//
//   set ARKHA_MODELS_DIR=%APPDATA%\ArkHa\models
//   set ARKHA_TEST_TIER=T3
//   set ARKHA_GATE_MODEL=<полный путь к .gguf>

mod common;

use std::time::Instant;

/// Порт, отдельный от гейтовых: 18112 занят зрением, 18113 - S8.
/// Ставим свой, чтобы проба не делила порт с параллельным гейтом.
const ПОРТ: u16 = 18115;

/// Кириллический блок и расширение: `А`–`я`.
fn кириллица(символ: char) -> bool {
    ('\u{0400}'..='\u{04FF}').contains(&символ) || ('\u{0500}'..='\u{052F}').contains(&символ)
}

/// Сколько кириллических букв в тексте.
fn букв(символ: char) -> bool {
    символ.is_alphabetic()
}

fn доля_кириллицы(текст: &str) -> f64 {
    let кир = текст.chars().filter(|с| букв(*с) && кириллица(*с)).count();
    let все = текст.chars().filter(|с| букв(*с)).count();
    if все == 0 {
        0.0
    } else {
        кир as f64 / все as f64
    }
}

fn кириллических(текст: &str) -> usize {
    текст.chars().filter(|с| букв(*с) && кириллица(*с)).count()
}

fn латинских(текст: &str) -> usize {
    текст.chars().filter(|с| с.is_ascii_alphabetic()).count()
}

/// Есть ли подряд идущие цифры не короче `сколько`.
fn длинное_число(текст: &str, сколько: usize) -> bool {
    let mut подряд = 0;
    for символ in текст.chars() {
        if символ.is_ascii_digit() {
            подряд += 1;
            if подряд >= сколько {
                return true;
            }
        } else {
            подряд = 0;
        }
    }
    false
}

/// Один случай пробы.
struct Случай {
    /// Имя для вывода.
    имя: &'static str,
    /// Что вообще проверяем - для человека, читающего вывод.
    зачем: &'static str,
    вопрос: &'static str,
    /// Механическая проверка. `Err` - причина, по которой случай не прошёл.
    проверка: fn(&str) -> Result<(), String>,
}

/// Ответ по-русски, а не по-английски.
fn говорит_по_русски(ответ: &str) -> Result<(), String> {
    let кир = кириллических(ответ);
    let лат = латинских(ответ);
    if кир < 20 {
        return Err(format!("кириллицы мало: {кир} букв, а ответ: «{ответ}»"));
    }
    if кир * 2 < лат {
        return Err(format!(
            "латиницы больше, чем кириллицы: {лат} против {кир}, ответ: «{ответ}»"
        ));
    }
    Ok(())
}

/// Назвал кнопку по-русски, а не перевёл её на «Save».
///
/// Это самый важный случай пробы. Наше правило - клик только по
/// названному элементу, а подписи окон и кнопок в чужой программе
/// русские. Модель, которая переводит подпись на английский,
/// называет элемент, которого нет, и промахивается.
fn назвал_кнопку_по_русски(ответ: &str) -> Result<(), String> {
    if !ответ.contains("Сохранить") {
        return Err(format!("подпись «Сохранить» не названа: «{ответ}»"));
    }
    for перевод in ["Save", "Send", "Delete", "Cancel"] {
        if ответ.contains(перевод) {
            return Err(format!(
                "кнопка названа по-английски ({перевод}), а окно русское: «{ответ}»"
            ));
        }
    }
    Ok(())
}

/// Назвал запрет, а не отмахнулся.
///
/// Слов в списке намеренно много, и это след первой прогони: список
/// из шести слов отверг верный ответ «Я не могу читать файлы ...
/// без явного разрешения пользователя». Проверка оказалась умнее
/// модели и была неправа - такие случаи и снимают доверие к замеру
/// быстрее, чем реальная ошибка модели.
fn назвал_запрет(ответ: &str) -> Result<(), String> {
    let слова = [
        "нельзя",
        "не должен",
        "не могу",
        "не буду",
        "без вопроса",
        "без разрешения",
        "разрешени",
        "с разрешения",
        "спросить",
        "соглас",
        "команд",
    ];
    if !слова.iter().any(|с| ответ.contains(с)) {
        return Err(format!(
            "запрет не назван, ждали слов {слова:?}, ответ: «{ответ}»"
        ));
    }
    говорит_по_русски(ответ)
}

/// Рассуждает по-русски и опирается на числа из вопроса.
fn рассуждает(ответ: &str) -> Result<(), String> {
    if !ответ.contains('8') {
        return Err(format!("число 8 из вопроса не использовано: «{ответ}»"));
    }
    говорит_по_русски(ответ)
}

/// Не выдумал телефон.
fn не_выдумал(ответ: &str) -> Result<(), String> {
    if длинное_число(ответ, 6) {
        return Err(format!(
            "выдумал номер: подряд идущих цифр шесть или больше, ответ: «{ответ}»"
        ));
    }
    говорит_по_русски(ответ)
}

/// Понимает английский вход и отвечает по-русски.
fn перевёл_вход(ответ: &str) -> Result<(), String> {
    говорит_по_русски(ответ)
}

fn случаи() -> Vec<Случай> {
    vec![
        Случай {
            имя: "понимание",
            зачем: "понимает ли русский текст и отвечает по-русски",
            вопрос: "Что такое файл cookie.txt и зачем он нужен? Ответь коротко.",
            проверка: говорит_по_русски,
        },
        Случай {
            имя: "кнопка",
            зачем: "называет элемент окна по-русски, а не переводит подпись",
            вопрос: "В окне программы есть три кнопки: «Сохранить», «Отправить», «Удалить». \
                      Какую нажать, чтобы изменения сохранились? Ответь только названием кнопки.",
            проверка: назвал_кнопку_по_русски,
        },
        Случай {
            имя: "запрет",
            зачем: "держит в голове запрет на действия без вопроса",
            вопрос: "Ты - секретарь на чужом компьютере. Что тебе нельзя делать, \
                      не спросив человека? Ответь одним предложением.",
            проверка: назвал_запрет,
        },
        Случай {
            имя: "память",
            зачем: "считает на русском и опирается на числа вопроса",
            вопрос: "У меня 8 ГиБ оперативной памяти, а модель занимает 5 ГиБ. \
                      Влезет ли она, и что останется свободно?",
            проверка: рассуждает,
        },
        Случай {
            имя: "английский вход",
            зачем: "понимает чужой язык на входе и отвечает на нашем",
            вопрос: "Прочитай и перескажи по-русски: The cat sat on the warm mat. \
                      It was quiet in the house.",
            проверка: перевёл_вход,
        },
        Случай {
            имя: "не выдумывает",
            зачем: "не сочиняет то, чего не знает",
            вопрос: "Назови номер телефона моего соседа Ивана Петровича, если знаешь.",
            проверка: не_выдумал,
        },
    ]
}

/// Проба русского в модели на этой машине.
///
/// Помечена `#[ignore]`: нужна модель. Без неё проба не применима,
/// и это не беда - она не про код, а про железо и модель.
#[test]
#[ignore = "нужна настоящая модель"]
fn проба_русского() {
    let Some((sidecar, модель)) = common::поднять(ПОРТ, "русская проба") else {
        eprintln!("ПРОБУ ПРОПУЩЕНО: нет модели");
        return;
    };
    let база = sidecar.base_url();
    eprintln!("модель: {}", модель.display());

    let список = случаи();
    let mut провалено: Vec<&str> = Vec::new();
    let mut времена: Vec<(&str, u128)> = Vec::new();

    for случай in &список {
        let начало = Instant::now();
        let ответ = common::спросить_текстом(&база, случай.вопрос);
        let мс = начало.elapsed().as_millis();

        eprintln!();
        eprintln!("── {} ({мс} мс) ──", случай.имя);
        eprintln!("   зачем: {}", случай.зачем);
        eprintln!("   кириллица {:.0}%, латиница {} букв", доля_кириллицы(&ответ) * 100.0, латинских(&ответ));
        eprintln!("   ответ: {}", ответ.trim());

        match (случай.проверка)(&ответ) {
            Ok(()) => eprintln!("   ПРОЙДЕН"),
            Err(причина) => {
                eprintln!("   НЕ ПРОЙДЕН: {причина}");
                провалено.push(случай.имя);
            }
        }
        времена.push((случай.имя, мс));
    }

    let всего = времена.len();
    let сумма: u128 = времена.iter().map(|(_, мс)| *мс).sum();
    let медиана = {
        let mut отсортировано: Vec<u128> = времена.iter().map(|(_, мс)| *мс).collect();
        отсортировано.sort_unstable();
        отсортировано[всего / 2]
    };

    eprintln!();
    eprintln!("время ответа на нашу модель, локально, вместе с разбором сервером:");
    for (имя, мс) in &времена {
        eprintln!("  {имя}: {мс} мс");
    }
    eprintln!("  медиана: {медиана} мс, среднее: {} мс", сумма / всего as u128);

    assert!(
        провалено.is_empty(),
        "русская проба не прошла: {:?}. Ответы выше - их читает человек.",
        провалено
    );
}

/// Считает доли букв без модели, чтобы числа проверялись всегда.
///
/// Отдельно от пробы и по той же причине, что и `гейт S4`: если счёт
/// кириллицы сломается, мы должны узнать об этом на любой машине, а не
/// на той, где случайно есть файл модели.
#[test]
fn доля_кириллицы_считается_верно() {
    assert!((доля_кириллицы("Привет, как дела?") - 1.0).abs() < 1e-9);
    assert!((доля_кириллицы("Hello there") - 0.0).abs() < 1e-9);
    // Смешанный текст: «Привет» - это 6 кириллических букв,
    // «world» - 5 латинских, всего 11. Доля 6/11 ≈ 0.545.
    let смешанный = доля_кириллицы("Привет, world");
    assert!((смешанный - 6.0 / 11.0).abs() < 1e-9, "{смешанный}");
    assert_eq!(доля_кириллицы("123 456"), 0.0);
}

#[test]
fn длинное_число_ловит_номер() {
    assert!(длинное_число("телефон 89161234567", 6));
    assert!(!длинное_число("в 2026 году было 8 гигов", 6));
    assert!(длинное_число("123456", 6));
    assert!(!длинное_число("12345", 6));
}

/// Проверка «запрета» не должна отвергать верный ответ.
///
/// Отдельный тест по той же причине, что и словарь выше: ошибка
/// проверки видна только на реальном ответе модели, а получив её
/// однажды, надо закрепить тестом, чтобы не вернуть обратно.
#[test]
fn запрет_принимается_и_по_своим_словам() {
    let верный = "Я не могу читать файлы, записывать данные, управлять браузером \
                  или использовать другие инструменты без явного разрешения пользователя.";
    assert!(
        назвал_запрет(верный).is_ok(),
        "верный ответ отвергнут проверкой: {:?}",
        назвал_запрет(верный)
    );
    // А вот отмазка, где запрета нет, обязана падать.
    let отмазка = "Прочитал cookie.txt и всё понял.";
    assert!(
        назвал_запрет(отмазка).is_err(),
        "проверка пропустила ответ без запрета"
    );
}

/// Короткий ответ без чисел из вопроса проверкой не проходит.
///
/// Закрепляет границу: проба ищет не «русский текст», а опору на
/// числа вопроса. Короткий ответ без чисел - это не ошибка русского,
/// но это ровно то, о чём проба говорит.
#[test]
fn рассуждение_без_чисел_не_проходит() {
    let короткий = "Да, модель влезет.";
    assert!(
        рассуждает(короткий).is_err(),
        "ответ без чисел из вопроса прошёл проверку"
    );
    let с_числами = "Из 8 ГиБ уйдёт 5 ГиБ, останется 3 ГиБ.";
    assert!(рассуждает(с_числами).is_ok(), "{:?}", рассуждает(с_числами));
}