//! Гейт UI Automation на живой программе, которая рисует интерфейс сама.
//!
//! Обычный поиск по окнам Win32 проходит мимо Chrome, Telegram, VS Code
//! и Discord: у них под кнопку нет дочернего окна, всё нарисовано.
//! На живой проверке это означало, что в этих программах секретарь
//! не мог нажать ничего — а это самые программы, где человек его
//! зовёт.
//!
//! Проверяется три вещи, по возрастанию строгости.
//!
//! 1. **Разрыв настоящий.** На кнопке в Chrome обычный поиск не
//!    находит ничего. Если он вдруг начнёт находить — тест устарел и
//!    проверяет не то, что был нужен проверить.
//! 2. **Дерево доступности находит.** Кнопка видна по своему тексту.
//! 3. **Нажатие сработало.** Не «элемент найден», а заголовок вкладки
//!    сменился. Именно это отличает настоящую проверку от проверки
//!    того, что функция вернула объект.
//!
//! Прогон:
//! ```text
//! cargo test --test uia_gate -- --nocapture --test-threads=1
//! ```
//!
//! Модель не участвует: это проверка инструмента, а не выбора
//! инструника моделью. Гейт S8 проверяет выбор, этот — исполнение.

use std::path::{Path, PathBuf};
use std::process::{Child, Command};
use std::time::{Duration, Instant};

use archotic_lib::tools::uia;
use windows::Win32::Foundation::HWND;

/// Заголовок вкладки до нажатия и после.
const ДО_НАЖАТИЯ: &str = "Archotic UIA";
const ПОСЛЕ_НАЖАТИЯ: &str = "Archotic UIA нажата";

/// Текст кнопки на странице.
const КНОПКА: &str = "Нажми Archotic";

fn страница() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/electron.html")
}

/// Где искать браузер. Chrome выбран потому, что он точно рисует
/// интерфейс сам, и потому, что его кнопки честно отдают дерево
/// доступности: если не он, то и Telegram не станет лучше.
fn браузер() -> Option<PathBuf> {
    let кандидаты = [
        std::env::var("PROGRAMFILES").ok().map(|p| PathBuf::from(p).join(r"Google\Chrome\Application\chrome.exe")),
        std::env::var("LOCALAPPDATA").ok().map(|p| PathBuf::from(p).join(r"Google\Chrome\Application\chrome.exe")),
        std::env::var("PROGRAMFILES").ok().map(|p| PathBuf::from(p).join(r"Mozilla Firefox\firefox.exe")),
        std::env::var("LOCALAPPDATA").ok().map(|p| PathBuf::from(p).join(r"Programs\Microsoft VS Code\Code.exe")),
    ];
    кандидаты.into_iter().flatten().find(|п| п.exists())
}

/// Chrome переживает тест, если не убить его дерево процессов.
///
/// `Child::kill` убивает только запускавший процесс, а Chrome
/// поднимает дочерние, и они держат профиль и окно. Из-за этого
/// следующий прогон нашёл бы чужое окно и проверил не своё.
/// `taskkill /T` снимает дерево целиком.
struct Браузер {
    ребёнок: Child,
}

impl Drop for Браузер {
    fn drop(&mut self) {
        let _ = Command::new("taskkill")
            .args(["/PID", &self.ребёнок.id().to_string(), "/T", "/F"])
            .output();
        let _ = self.ребёнок.wait();
    }
}

/// Папка профиля, удаляемая после прогона: свой профиль не даёт
/// запущенному рядом Chrome подхватить нашу страницу.
struct Профиль(PathBuf);

impl Drop for Профиль {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// Поднять браузер на нашей странице и дождаться окна.
fn открыть() -> (Браузер, Профиль) {
    let exe = браузер().expect(
        "не найден ни Chrome, ни Firefox, ни VS Code. \
         Поставь один из них или укажи путь переменной ARCHOTIC_UIA_EXE",
    );
    let профиль = std::env::temp_dir().join(format!("archotic-uia-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&профиль);

    let адрес = url_файла(&страница());
    let mut ребёнок = Command::new(&exe)
        .arg(format!("--user-data-dir={}", профиль.display()))
        .arg("--no-first-run")
        .arg("--no-default-browser-check")
        .arg("--new-window")
        .arg(&адрес)
        .spawn()
        .expect("не удалось запустить браузер");

    if ждать_окна(ДО_НАЖАТИЯ, 40).is_none() {
        let видимые = заголовки();
        // Гасим браузер до паники: иначе после падения останется
        // окно на весь следующий прогон.
        let _ = Command::new("taskkill")
            .args(["/PID", &ребёнок.id().to_string(), "/T", "/F"])
            .output();
        let _ = ребёнок.wait();
        panic!("окно «{ДО_НАЖАТИЯ}» не появилось за 40 секунд. Заголовки сейчас: {видимые:?}");
    }
    (Браузер { ребёнок }, Профиль(профиль))
}

/// `HKCU\...\UrlAssociations` нам не нужен, путь в адресной строке
/// Chrome понимает как есть.
fn url_файла(путь: &Path) -> String {
    let текст = путь.display().to_string().replace('\\', "/");
    format!("file:///{}", текст.replace(' ', "%20"))
}

fn заголовки() -> Vec<String> {
    archotic_lib::tools::windows::окна().into_iter().map(|о| о.заголовок).collect()
}

/// Найти окно с подстрокой в заголовке и дождаться его.
fn ждать_окна(подстрока: &str, секунд: u64) -> Option<isize> {
    let край = Instant::now() + Duration::from_secs(секунд);
    loop {
        if let Some(о) = archotic_lib::tools::windows::найти(подстрока)
            .into_iter()
            .find(|о| о.видимое)
        {
            return Some(о.hwnd);
        }
        if Instant::now() > край {
            return None;
        }
        std::thread::sleep(Duration::from_millis(300));
    }
}

/// Дождаться, пока заголовок станет нужным.
fn ждать_заголовка(подстрока: &str, секунд: u64) -> bool {
    let край = Instant::now() + Duration::from_secs(секунд);
    loop {
        if заголовки().iter().any(|з| з.contains(подстрока)) {
            return true;
        }
        if Instant::now() > край {
            return false;
        }
        std::thread::sleep(Duration::from_millis(200));
    }
}

/// Дождаться, пока кнопка появится в дереве доступности.
///
/// Заголовок вкладки ставится раньше, чем отрисуется содержимое
/// страницы, поэтому окна недостаточно: без этого ожидания тест
/// проверяет пустое дерево и падает случайно. На живой машине это
/// и вышло: в одном прогоне кнопка уже была в списке, а следующий
/// вызов `найти` её ещё не видел.
fn ждать_элемента(hwnd: isize, текст: &str, секунд: u64) -> uia::Найденные {
    let дескриптор = HWND(hwnd as *mut _);
    let край = Instant::now() + Duration::from_secs(секунд);
    loop {
        let найденные = uia::найти(дескриптор, текст);
        if !найденные.элементы.is_empty() {
            return найденные;
        }
        if Instant::now() > край {
            panic!(
                "элемент «{текст}» не появился в дереве за {секунд} с. \
                 Что есть: {:?}",
                uia::подписи(дескриптор)
            );
        }
        std::thread::sleep(Duration::from_millis(250));
    }
}

/// Разрыв настоящий: у Chrome под кнопкой нет дочернего окна.
///
/// Без этой проверки тест ниже проходил бы и на обычном окне, то
/// бы доказывал бы уже доказанное и молчал бы, если бы Chrome вдруг
/// начал отдавать дочерние окна.
#[test]
fn обычный_поиск_в_chrome_не_находит_кнопку() {
    let (_браузер, _профиль) = открыть();
    let hwnd = ждать_окна(ДО_НАЖАТИЯ, 20).expect("окно пропало");
    // Сначала убеждаемся, что кнопка вообще есть. Иначе проверка
    // ниже прошла бы на пустом дереве и ничего не доказывала: на
    // живой машине так и вышло — окно появилось раньше страницы.
    ждать_элемента(hwnd, КНОПКА, 20);

    let через_окна = archotic_lib::tools::control::найти_элемент(HWND(hwnd as *mut _), КНОПКА);
    assert!(
        через_окна.is_empty(),
        "Chrome нашёл кнопку обычным поиском: {:?}. Значит, проверка устарела — \
         дыры с дочерними окнами больше нет, и гейт доказывает не то.",
        через_окна.iter().map(|э| &э.текст).collect::<Vec<_>>()
    );
}

/// Дерево доступности находит кнопку, которой нет у окон.
#[test]
fn дерево_доступности_видит_кнопку_в_chrome() {
    let (_браузер, _профиль) = открыть();
    let hwnd = ждать_окна(ДО_НАЖАТИЯ, 20).expect("окно пропало");
    let дескриптор = HWND(hwnd as *mut _);

    let всего = uia::размер_дерева(дескриптор);
    assert!(всего > 0, "Chrome не отдал дерево доступности: {всего}");

    let найденные = ждать_элемента(hwnd, КНОПКА, 20);
    assert_eq!(
        найденные.элементы.len(),
        1,
        "под «{КНОПКА}» нашлось {} штук, ждали одну: {:?}",
        найденные.элементы.len(),
        uia::подписи(дескриптор)
    );
    let э = &найденные.элементы[0];
    assert!(э.текст.contains(КНОПКА), "нашлось не то: «{}»", э.текст);
    assert_eq!(э.вид, "кнопка", "кнопка должна опознаться как кнопка, а не как «{}»", э.вид);
}

/// Нажатие действительно происходит: заголовок вкладки меняется.
#[test]
fn нажатие_через_доступность_меняет_страницу() {
    let (_браузер, _профиль) = открыть();
    let hwnd = ждать_окна(ДО_НАЖАТИЯ, 20).expect("окно пропало");

    assert!(
        !заголовки().iter().any(|з| з.contains(ПОСЛЕ_НАЖАТИЯ)),
        "страница уже нажата до начала проверки — тест ничего не проверяет"
    );

    let найденные = ждать_элемента(hwnd, КНОПКА, 20);
    uia::нажать(&найденные.элементы[0]).unwrap_or_else(|о| panic!("нажатие не удалось: {о}"));

    assert!(
        ждать_заголовка(ПОСЛЕ_НАЖАТИЯ, 15),
        "после нажатия заголовок не сменился. Сейчас: {:?}",
        заголовки()
    );
}

/// Нажатие не требует фокуса окна.
///
/// Это главное свойство дерева доступности, и без этой проверки
/// остальное бессмысленно: если бы фокус всё равно перехватывался,
/// пришлось бы возвращаться к блокировке Windows, которая уже
/// показала себя ненадёжной.
#[test]
fn нажатие_не_требует_перехвата_фокуса() {
    let (_браузер, _профиль) = открыть();
    let hwnd = ждать_окна(ДО_НАЖАТИЯ, 20).expect("окно пропало");
    ждать_элемента(hwnd, КНОПКА, 20);

    // Уводим фокус на другое окно: консоль, из которой запущен тест.
    let чужое = ждать_окна("PowerShell", 5).or_else(|| ждать_окна("cmd", 5));
    if let Some(чужое) = чужое {
        assert_ne!(чужое, hwnd, "ищем именно другое окно, а не то же");
        archotic_lib::tools::control::фокус_на(чужое);
        // Даём системе время увидеть новое активное окно: без паузы
        // проверка прошла бы потому, что фокус ещё никуда не уехал,
        // и доказывала бы пустое.
        std::thread::sleep(Duration::from_millis(800));
    } else {
        eprintln!("UIA: не нашёл чужого окна, проверяю без увода фокуса");
    }

    let найденные = ждать_элемента(hwnd, КНОПКА, 20);
    uia::нажать(&найденные.элементы[0]).unwrap_or_else(|о| panic!("нажатие не удалось: {о}"));

    assert!(
        ждать_заголовка(ПОСЛЕ_НАЖАТИЯ, 15),
        "нажатие не сработало при чужом фокусе. Сейчас: {:?}",
        заголовки()
    );
}