//! Гейт S8 на живом железе: пять сценариев управления ПК.
//!
//! Юнит-тесты доказывают, что окна перечисляются, а координаты
//! пересчитываются правильно. Это не говорит о главном: **позовёт ли
//! модель нужный инструмент и приведёт ли действие к нужному
//! результату**.
//!
//! Проверяется не «инструмент вызван», а «после действия получилось
//! то, что человек просил». Клик считается сделанным, только если
//! кнопка действительно нажата и файл записан. Иначе тест проходит
//! при клике мимо.
//!
//! Испытательное окно — настоящее окно Win32 из
//! `tests/fixtures/forma.ps1`. Настоящее нужно потому, что элемент
//! ищется по своему тексту через `EnumChildWindows`, и проверить это
//! можно только на реальном окне с реальными кнопками.
//!
//! Запуск:
//! ```text
//! ARKHA_BIN_DIR=data/bin ARKHA_MODELS_DIR=<папка с gguf> \
//!   ARKHA_TEST_TIER=T3 \
//!   cargo test --test s8_gate -- --nocapture --test-threads=1
//! ```
//!
//! Один поток обязателен: сценарии открывают и закрывают окна, а
//! гейты S2 и S6 держат сайдкар на своём порту.

mod common;

use arkha_lib::agent::executor::{Agent, Message, Outcome, PendingApproval};
use arkha_lib::permissions::Settings;
use arkha_lib::tools::Registry;
use common::{Живая, поднять};
use std::path::PathBuf;
use std::process::{Child, Command};
use std::sync::atomic::AtomicBool;

const ПОРТ: u16 = 18108;
const ЗАГОЛОВОК_ФОРМЫ: &str = "Проверка ArkHa";

/// Подставной пользователь: разрешает всё на задачу.
///
/// Разрешение «на всю задачу», а не по одному действию: иначе на
/// пять сценариев пришлось бы отвечать на каждый вызов отдельно, и
/// гейт проверял бы интерфейс подтверждений, а не управление ПК.
struct Разрешающий {
    вопросы: Vec<PendingApproval>,
}

impl arkha_lib::agent::executor::Спрашивающий for Разрешающий {
    fn спросить(&mut self, вопрос: &PendingApproval) -> arkha_lib::agent::approvals::Решение {
        self.вопросы.push(вопрос.clone());
        arkha_lib::agent::approvals::Решение::ВсюЗадачу
    }
}

/// Настройки для сценариев управления.
///
/// Управление разрешено **явно**. Это не обход ограничения, а его
/// проверка: по умолчанию запуск программ и клики не разрешены, и
/// знакомство должно их выдать. Гейт проверяет поведение после
/// разрешения; отказ проверяет отдельный сценарий.
///
/// Если убрать эти строки, сценарии начнут падать на «не разрешено
/// явно» — и это будет правильным поведением, а не поломкой гейта.
fn настройки() -> Settings {
    use arkha_lib::permissions::{CapabilityRule, Executor};
    let mut s = Settings::default();
    s.executor = Executor::Live;
    s.approval_mode = arkha_lib::permissions::ApprovalMode::Risky;
    for возможность in ["apps.launch", "windows.control"] {
        s.capabilities.insert(
            возможность.into(),
            CapabilityRule { enabled: true, mode: None },
        );
    }
    s
}

/// Путь к испытательному скрипту.
fn скрипт() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/forma.ps1")
}

/// Окно, которое гасится само.
///
/// `Child` при падении не убивает процесс. Без явного `kill` каждое
/// окно переживало бы тест, и к четвёртому сценарию их было бы
/// несколько: поиск «Проверка ArkHa» стал бы неоднозначным, а
/// гейт начал бы проверять не то.
struct Форма {
    ребёнок: Child,
}

/// Окно, которое тоже нужно погасить: промежуточное создаётся одной
/// командой PowerShell и переживает тест так же.
struct Промежуточное {
    ребёнок: Child,
}

impl Drop for Промежуточное {
    fn drop(&mut self) {
        let _ = self.ребёнок.kill();
        let _ = self.ребёнок.wait();
    }
}

impl Drop for Форма {
    fn drop(&mut self) {
        let _ = self.ребёнок.kill();
        let _ = self.ребёнок.wait();
    }
}

/// Поднять испытательное окно и дождаться его появления.
fn открыть_форму(выход: &PathBuf) -> Форма {
    let ребёнок = Command::new("powershell")
        .arg("-NoProfile")
        .arg("-STA")
        .arg("-ExecutionPolicy")
        .arg("Bypass")
        .arg("-File")
        .arg(скрипт())
        .arg(выход)
        .spawn()
        .expect("не удалось запустить испытательное окно");
    for _ in 0..100 {
        if ждать_окна(ЗАГОЛОВОК_ФОРМЫ, 15) {
            // Что именно видно в переборе. Без этой распечатки провал
            // выглядит как «модель не позвала», хотя на самом деле
            // окна может не быть в списке вообще.
            let видимые = arkha_lib::tools::windows::окна();
            let заголовки: Vec<&str> = видимые.iter().map(|о| о.заголовок.as_str()).collect();
            eprintln!("S8: окна при подъёме формы: {заголовки:?}");
            return Форма { ребёнок };
        }
        std::thread::sleep(std::time::Duration::from_millis(200));
    }
    panic!("испытательное окно не появилось за 30 секунд");
}

/// Ждём появления окна с подстрокой в заголовке.
fn ждать_окна(подстрока: &str, секунд: u64) -> bool {
    let край = std::time::Instant::now() + std::time::Duration::from_secs(секунд);
    loop {
        if окно_есть(подстрока) {
            return true;
        }
        if std::time::Instant::now() > край {
            return false;
        }
        std::thread::sleep(std::time::Duration::from_millis(300));
    }
}

/// Проверить, что окно видно прямо сейчас.
fn окно_есть(подстрока: &str) -> bool {
    arkha_lib::tools::windows::найти(подстрока)
        .iter()
        .any(|о| о.видимое)
}

/// Прогнать задачу через живой цикл и вернуть результат.
fn цикл(sidecar: &arkha_lib::model_manager::Sidecar, задача: &str) -> (Outcome, Разрешающий) {
    let mut модель = Живая::новый(sidecar.base_url());
    let mut спрашивающий = Разрешающий { вопросы: Vec::new() };
    let итог = Agent::со_спросом(
        &mut модель,
        настройки(),
        std::sync::Arc::new(AtomicBool::new(false)),
        &mut спрашивающий,
    )
    .run(vec![Message::user(задача)], 1);
    (итог, спрашивающий)
}

fn вызовы(итог: &Outcome) -> Vec<String> {
    итог.calls.iter().map(|c| c.tool.clone()).collect()
}

/// Подробный след вызовов: инструмент, успех и что он вернул.
///
/// Одних имён недостаточно. На живой модели навык падал с ответом
/// «у меня 15 окон», и по именам вызовов это не диагностируется:
/// видно, что `windows.find` позвали, но не видно, что он вернул.
fn след(итог: &Outcome) -> Vec<String> {
    итог.calls
        .iter()
        .map(|c| {
            let сводка: String = c.summary.chars().take(220).collect();
            format!("{} ok={} {}", c.tool, c.ok, сводка)
        })
        .collect()
}

/// Сценарий 1: секретарь должен увидеть открытые окна.
///
/// Проверяется не вызов инструмента, а ответ: если окно есть, а в
/// ответе его нет — секретарь не «увидел», даже если инструмент
/// отработал.
#[test]
fn сценарий_1_видит_открытые_окна() {
    let Some((sidecar, _)) = поднять(ПОРТ, "S8") else {
        return;
    };
    let dir = std::env::temp_dir().join(format!("arkha-s8-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("папка");
    let _форма = открыть_форму(&dir.join("out.txt"));

    let (итог, _) = цикл(&sidecar, "Что сейчас открыто на компьютере? Перечисли окна.");
    eprintln!("S8-1: вызовы {:?}, ответ {:?}", вызовы(&итог), итог.answer);

    // Замер после работы агента: окно могло пропасть, а могло остаться
    // невидимым в списке. Это разные поломки, и лечатся они по-разному.
    let видимые = arkha_lib::tools::windows::видимые();
    eprintln!(
        "S8-1: после цикла видимых окон {}, форма среди них: {}, найти(): {}",
        видимые.len(),
        видимые.iter().any(|о| о.заголовок.contains(ЗАГОЛОВОК_ФОРМЫ)),
        arkha_lib::tools::windows::найти(ЗАГОЛОВОК_ФОРМЫ).len()
    );
    eprintln!(
        "S8-1: видимые — {:?}",
        видимые.iter().map(|о| о.заголовок.as_str()).collect::<Vec<_>>()
    );

    assert!(
        вызовы(&итог).iter().any(|т| т == "windows.list"),
        "модель должна была посмотреть окна. Вызовы: {:?}. Ответ: {:?}",
        вызовы(&итог),
        итог.answer
    );
    assert!(
        итог.answer.contains(ЗАГОЛОВОК_ФОРМЫ),
        "в ответе должно быть наше окно «{ЗАГОЛОВОК_ФОРМЫ}», а есть: {:?}",
        итог.answer
    );
}

