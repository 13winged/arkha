// Разовая правка: оборачивает видимый текст JSX в t().
//
// Правило жёсткое: текст берётся ТОЛЬКО между «>» и «<». Иначе
// предыдущие прогоны съедали дженерики useState<...> и ключи объектов
// вида `executor: режим,` — и то и другое выглядит как обычный текст.
//
// Запуск: node scripts/i18n-codemod.mjs. После прогона удалить.

import { readFileSync, writeFileSync } from "node:fs";

const путь = "src/App.tsx";
const исходные = readFileSync(путь, "utf8").split("\n");

const НЕ_ПЕРЕВОДИТЬ = new Set([
  "память_сейчас",
  "--кегль",
  "arkha-font-size",
  "arkha-lang",
]);

const ЕСТЬ_КИРИЛЛИЦА = /[А-Яа-яЁё]/;
const ЗНАКИ_КОДА = /[<>{}()=;|`$]/;

const перевести = (с) =>
  НЕ_ПЕРЕВОДИТЬ.has(с)
    ? null
    : `t("${с.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}")`;

const выход = [];
let обёрнуто = 0;

for (let i = 0; i < исходные.length; i++) {
  const строка = исходные[i];

  // Случай «>текст</тег>» целиком в одной строке.
  const одна = строка.match(/^(\s*)(>[^<>]*)<(.*)$/);
  if (одна && ЕСТЬ_КИРИЛЛИЦА.test(одна[2])) {
    const внутрь = одна[2].slice(1).trim();
    const перевод = внутрь && !ЗНАКИ_КОДА.test(внутрь) ? перевести(внутрь) : null;
    if (перевод) {
      выход.push(`${одна[1]}>{${перевод}}<${одна[3]}`);
      обёрнуто++;
      continue;
    }
  }

  // Случай «>» в конце строки, текст ниже, «<» в конце следующей.
  // Текстовых строк подряд может быть сколько угодно: JSX склеивает
  // их пробелом, значит и ключ собираем слитно.
  if (/>\s*$/.test(строка) && !/^\s*(?:\/\/|\/\*|\*)/.test(строка)) {
    const куски = [];
    let j = i + 1;
    let последняя = i;
    while (j < исходные.length) {
      const следующая = исходные[j];
      if (следующая.trim() === "" && куски.length > 0) {
        // Пустая строка внутри текста — обычный перенос, продолжаем.
        j++;
        continue;
      }
      if (!ЕСТЬ_КИРИЛЛИЦА.test(следующая) || ЗНАКИ_КОДА.test(следующая)) break;
      if (/^\s*(const|let|return|import|export)\b/.test(следующая)) break;
      куски.push(следующая.trim());
      последняя = j;
      j++;
    }

    if (куски.length > 0 && /<\/?[A-Za-z]/.test(исходные[последняя + 1] ?? "")) {
      const ключ = куски.join(" ");
      const перевод = перевести(ключ);
      if (перевод) {
        // Хвост последней строки текста уходит внутрь выражения.
        const хвост = исходные[последняя].slice(
          исходные[последняя].length - (исходные[последняя].trim().length - куски[куски.length - 1].length),
        );
        выход.push(строка.replace(/([^>]*>\s*)$/, `$1{${перевод}}${хвост}`));
        for (let k = i + 1; k < последняя; k++) выход.push("");
        i = последняя;
        обёрнуто++;
        continue;
      }
    }
  }

  выход.push(строка);
}

let код = выход.join("\n");

// Проход второй: <тег>Текст</тег> целиком в одной строке. Требует
// парный тег, поэтому в кодовые конструкции не попадает.
код = код.replace(
  /(<([A-Za-z][\w.]*)(?:\s[^<>]*)?>)([^<>{}]*[А-Яа-яЁё][^<>{}]*)(<\/\2\s*>)/g,
  (всё, открыть, тег, внутрь, закрыть) => {
    const ключ = внутрь.trim();
    if (!ключ || ЗНАКИ_КОДА.test(ключ)) return всё;
    const перевод = перевести(ключ);
    return перевод ? `${открыть}{${перевод}}${закрыть}` : всё;
  },
);

// Проход третий: подсказки и имена элементов в атрибутах.
код = код.replace(
  /\b(placeholder|title|aria-label|empty)="([^"]*[А-Яа-яЁё][^"]*)"/g,
  (всё, имя, значение) => {
    const ключ = значение.trim();
    const перевод = ЗНАКИ_КОДА.test(ключ) ? null : перевести(ключ);
    return перевод ? `${имя}={${перевод}}` : всё;
  },
);

if (!код.includes('from "./i18n"')) {
  код = код.replace(
    /^(import .*from "@tauri-apps\/api\/event";)/m,
    '$1\nimport { t, язык, поставитьЯзык, восстановитьЯзык, следить } from "./i18n";',
  );
}

writeFileSync(путь, код, "utf8");
console.log(`обёрнуто: ${обёрнуто}`);